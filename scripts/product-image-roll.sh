# Кандидат — контейнер, запущенный из образа $IMAGE_REPO:*. В режиме репетиции
# кандидат ровно один и клиентских среди них нет вовсе.
CANDIDATES=""
while IFS='|' read -r _ n st img cfgimg net priv; do
  [[ -n "$n" ]] || continue
  if [[ -n "$REHEARSE" ]]; then
    [[ "$n" == "$REHEARSE" ]] || continue
  else
    [[ "$cfgimg" == "$IMAGE_REPO:"* ]] || continue
  fi
  CANDIDATES="$CANDIDATES$n|$st|$img|$net|$priv"$'\n'
done <<<"$CONTAINERS"

# ═════════════════════════════════════════════════════════════════════════════
bold "[6/8] образ $IMAGE_TAG (собирается, только если его ещё нет)"
# ═════════════════════════════════════════════════════════════════════════════
# Контекст сборки — ВРЕМЕННАЯ КОПИЯ ровно тех путей, что копирует Dockerfile, а
# не $AGENT_DIR целиком. Две причины, обе измеренные: в каталоге лежат
# node_modules и dist (101 MiB на 22.09.2026), которые уехали бы в демон ни за
# чем; и случайный файл, оставшийся от прошлой установки (rsync идёт без
# --delete), не может попасть в образ, метка которого утверждает, что в нём
# ровно это содержимое.
#
# ── СБОРКА ПРОПУСКАЕТСЯ, ЕСЛИ ОБРАЗ С ЭТОЙ МЕТКОЙ УЖЕ ЕСТЬ ───────────────────
# Это не оптимизация, а ГЛАВНОЕ СВОЙСТВО прогона. Сборка невоспроизводима:
# из одних и тех же исходников выходят разные идентификаторы (измерено, см.
# шапку). Пересобери мы «на всякий случай» — идентификатор сменился бы, все
# контейнеры оказались бы «отставшими», и КАЖДЫЙ выкат бэкенда гасил бы
# клиентские сайты ни за чем. Метка равна содержимому; образ с такой меткой уже
# собран из этого же содержимого; собирать нечего.
NEW_ID=""
EXIST=$(remote "$(rs "SUDO=$(shq "$SUDO"); TAG=$(shq "$IMAGE_TAG")" <<'EOS'
set -u
$SUDO docker image inspect "$TAG" --format '{{.Id}}' 2>/dev/null || echo НЕТ
EOS
)") || die "не смог спросить про образ $IMAGE_TAG"
EXIST=$(tail -1 <<<"$EXIST")
[[ "$EXIST" == sha256:* ]] || EXIST="НЕТ"

if [[ -n "$DRY_RUN" ]]; then
  if [[ "$EXIST" != "НЕТ" && -z "$FORCE_BUILD" ]]; then
    NEW_ID="$EXIST"
    plan "образ $IMAGE_TAG на машине УЖЕ ЕСТЬ: ${NEW_ID:0:19} — СБОРКИ НЕ БЫЛО БЫ"
    plan "  отставшими считаю всё, что запущено не с него"
  elif [[ "$EXIST" != "НЕТ" ]]; then
    plan "образ $IMAGE_TAG есть (${EXIST:0:19}), но FORCE_BUILD=1 — пересобрал бы; новый идентификатор заранее неизвестен"
    plan "  ⚠ это пересоздало бы ВСЕ контейнеры: сборка невоспроизводима"
  else
    plan "образа $IMAGE_TAG на машине ещё нет — собрал бы его из $AGENT_DIR ($CTX_PATHS)"
    plan "  идентификатор заранее неизвестен: сборка невоспроизводима"
  fi
  plan "переставил бы $IMAGE_REPO:$IMAGE_BASE_TAG на $IMAGE_TAG"
elif [[ "$EXIST" != "НЕТ" && -z "$FORCE_BUILD" ]]; then
  NEW_ID="$EXIST"
  BUILT="нет — образ с этой меткой уже был на машине"
  ok "образ $IMAGE_TAG уже собран из этого же содержимого: ${NEW_ID:0:19} — не пересобираю"
  echo "      Пересобрать принудительно (обновился базовый образ, повреждён слой): FORCE_BUILD=1"
else
  if [[ -n "$FORCE_BUILD" && "$EXIST" != "НЕТ" ]]; then
    warn "FORCE_BUILD=1: образ $IMAGE_TAG есть (${EXIST:0:19}), но пересобираю."
    warn "  Сборка невоспроизводима — идентификатор сменится, и пересозданы будут ВСЕ контейнеры."
  fi
  if [[ -n "$REHEARSE" ]]; then bold "      (репетиция: образ собирается по-настоящему)"; fi
  BUILD=$(remote "$(rs "SUDO=$(shq "$SUDO"); DIR=$(shq "$AGENT_DIR"); TAG=$(shq "$IMAGE_TAG"); PATHS=$(shq "$CTX_PATHS")" <<'EOS'
set -u
CTX=$(mktemp -d /tmp/linkeon-img.XXXXXX) || { echo "BUILD_ERR нет временного каталога"; exit 0; }
trap 'rm -rf "$CTX"' EXIT
cd "$DIR" || { echo "BUILD_ERR нет $DIR"; exit 0; }
# shellcheck disable=SC2086
$SUDO cp -a $PATHS "$CTX/" 2>/dev/null || { echo "BUILD_ERR не смог собрать контекст из «${PATHS}»"; exit 0; }
[ -f "$CTX/docker/Dockerfile" ] || { echo "BUILD_ERR в контексте нет docker/Dockerfile"; exit 0; }
echo BUILD_BEGIN
# Сборка НЕ глушится: её вывод — единственное, по чему разбирают отказ. Код
# возврата берётся у самой сборки, а не у `tail`, — `| tail` уже глотал
# падение сборки на этом проекте, и выкат ехал дальше как ни в чём не бывало.
$SUDO docker build -f "$CTX/docker/Dockerfile" -t "$TAG" "$CTX" 2>&1
echo "BUILD_END rc=$?"
EOS
)") || die "сборка образа не запустилась на $TARGET"
  if grep -q '^BUILD_ERR' <<<"$BUILD"; then
    die "контекст сборки не собрался: $(grep -m1 '^BUILD_ERR' <<<"$BUILD" | sed 's/^BUILD_ERR //')"
  fi
  # См. оговорку про pipefail у endline в prod_sql: без заглушки пропавший
  # маркер (оборванный ssh) убивал бы скрипт вместо того, чтобы сказать об этом.
  BRC=$(grep -o 'BUILD_END rc=[0-9]*' <<<"$BUILD" | tail -1) || BRC=""
  BRC="${BRC##*rc=}"
  if [[ "$BRC" != "0" ]]; then
    sed -n '/^BUILD_BEGIN$/,/^BUILD_END /p' <<<"$BUILD" | tail -25 | sed 's/^/        /' >&2 || true
    if [[ -n "$BRC" ]]; then
      die "docker build вернул rc=$BRC — образ не собран, ни один контейнер не тронут"
    fi
    die "маркер конца сборки не приехал (связь оборвалась посреди вывода) — образ считаю несобранным, ни один контейнер не тронут"
  fi
  NEW_ID=$(remote "$(rs "SUDO=$(shq "$SUDO"); TAG=$(shq "$IMAGE_TAG")" <<'EOS'
set -u
$SUDO docker image inspect "$TAG" --format '{{.Id}}' 2>/dev/null || echo НЕТ
EOS
)") || die "не смог прочитать идентификатор собранного образа"
  NEW_ID=$(tail -1 <<<"$NEW_ID")
  [[ "$NEW_ID" == sha256:* ]] || die "после сборки образа $IMAGE_TAG нет — docker build отчитался успехом впустую"
  BUILT="да"
  ok "собран $IMAGE_TAG = ${NEW_ID:0:19}"
  if [[ "$NEW_ID" == "$BASE_ID" ]]; then
    ok "идентификатор совпал с нынешним $IMAGE_REPO:$IMAGE_BASE_TAG — образ не изменился"
  fi
fi

# ── уборка за репетицией ─────────────────────────────────────────────────────
#
# ОБЪЯВЛЕНА ДО УСТАНОВКИ И ПОВЕШЕНА НА EXIT, а не вызвана одной строкой в
# конце. Разница измерена, а не придумана: первая же попытка репетиции упала на
# сборке производного образа, до конца скрипта не дошла — и оставила
# /srv/products/roll-rehearsal. Следующий заход отказался стартовать («каталог
# уже существует»), пришлось убирать руками. Уборка, которая отрабатывает
# только на удачном прогоне, не уборка: мусор остаётся ровно в том случае,
# ради которого она и нужна.
#
# Функция обязана быть ОПРЕДЕЛЕНА раньше установки: trap исполняется в момент
# выхода, и если `die` случится до строки с определением, ловушка позвала бы
# несуществующую команду.
#
# Убирает ТОЛЬКО СВОЁ и по точным именам: контейнер репетиции, её страховочные
# копии, её производный образ и её каталог. Каталогов продуктов не касается
# ничем — ни маской, ни перебором.
REHEARSE_CLEANED=""
rehearse_cleanup() {
  [[ -n "$REHEARSE" && -z "$DRY_RUN" && -z "$REHEARSE_CLEANED" ]] || return 0
  REHEARSE_CLEANED=1
  bold "      убираю за репетицией"
  local out
  out=$(remote "$(rs "SUDO=$(shq "$SUDO"); NAME=$(shq "$REHEARSE"); REPO=$(shq "$IMAGE_REPO"); ROOT=$(shq "$REHEARSE_DIR_ROOT")" <<'EOS'
set -u
# Последний рубеж перед rm -rf: имя проверено регулярным выражением при старте,
# но каталог удаляется без оглядки, и пустое либо составное имя снесло бы
# /srv/products целиком — вместе с чекаутами клиентов.
# ⚠ ЗДЕСЬ НЕЛЬЗЯ ВЕТВЛЕНИЕ ВИДА case. Его образцы кончаются непарной закрывающей
# скобкой, а на маке /bin/bash — 3.2: он ищет конец объемлющей подстановки
# простым счётом скобок и закрывает её на этой скобке — даже когда ветвление
# лежит внутри закавыченного heredoc. Дальше разбор уезжает в мусор.
# Измерено 23.09.2026: репетиция дошла до конца, а уборка отвалилась с
# синтаксической ошибкой. Хуже того, bash -n этого НЕ ловит: вложенную
# подстановку он разбирает лениво, уже при раскрытии.
#
# ⚠⚠ ПО ТОЙ ЖЕ ПРИЧИНЕ В ЭТОМ heredoc НЕЛЬЗЯ НЕПАРНЫЕ СКОБКИ И ОБРАТНЫЕ КАВЫЧКИ
# ДАЖЕ В КОММЕНТАРИЯХ. Счётчик скобок не знает, что перед ним комментарий.
# Первая редакция этого самого предупреждения содержала и то и другое — и
# сломала файл ровно тем, о чём предупреждала. Та же оговорка про bash 3.2,
# что в шапке, просто с другой стороны.
if [ -z "$NAME" ] || [ "$NAME" != "${NAME#*/}" ] || [ "$NAME" = "." ] || [ "$NAME" = ".." ]; then
  echo CLEAN_REFUSED; exit 0
fi
if [ -z "$ROOT" ] || [ "$ROOT" = "/" ]; then echo CLEAN_REFUSED; exit 0; fi
D="$ROOT/$NAME"
$SUDO docker rm -f "$NAME" >/dev/null 2>&1 || true
# `| grep | while` — конвейер намеренно не под pipefail (его тут нет) и пустой
# список имён это не ошибка.
$SUDO docker ps -a --format '{{.Names}}' | grep "^${NAME}__pre_" | while IFS= read -r c; do
  $SUDO docker rm -f "$c" >/dev/null 2>&1 || true
done
$SUDO docker image rm -f "$REPO:rehearse-stale" >/dev/null 2>&1 || true
# Каталог сносится ТОЛЬКО со своей меткой внутри. Рядом лежат чекауты клиентов;
# «имя совпало» — не основание для rm -rf, метку туда кладём мы сами.
if [ -e "$D" ] && [ ! -f "$D/.linkeon-rehearsal" ]; then
  echo "CLEAN_FOREIGN $D — нет метки .linkeon-rehearsal, каталог не наш, не трогаю"
  exit 0
fi
$SUDO rm -rf "$D"
[ -e "$D" ] && { echo "CLEAN_LEFT $D"; exit 0; }
$SUDO docker inspect "$NAME" >/dev/null 2>&1 && { echo "CLEAN_LEFT контейнер $NAME"; exit 0; }
echo CLEAN_OK
EOS
)" 2>/dev/null) || out=""
  if [[ "$out" == *CLEAN_OK* ]]; then
    ok "репетиционный контейнер, каталог и производный образ убраны"
    return 0
  fi
  warn "уборка за репетицией НЕ подтвердилась${out:+ (машина ответила: $(tr '\n' ' ' <<<"$out"))} — проверить и убрать руками:"
  warn "  ssh $TARGET '${SUDO:+sudo }docker rm -f $REHEARSE; ${SUDO:+sudo }rm -rf $REHEARSE_DIR_ROOT/$REHEARSE'"
  return 0
}

# Ловушка ставится ДО первой записи на машину. $SRC_TMP убирается тем же
# обработчиком: второй `trap ... EXIT` молча затёр бы первый.
if [[ -n "$REHEARSE" && -z "$DRY_RUN" ]]; then
  trap 'rc=$?; rehearse_cleanup; rm -rf "$SRC_TMP"; exit $rc' EXIT
fi

# Репетиционный контейнер заводится ПОСЛЕ сборки и намеренно НА ДРУГОМ ОБРАЗЕ —
# производном от свежего (тот же FROM плюс метка). Иначе репетиция не
# репетирует: если исходники не менялись, сборка даёт тот же идентификатор,
# контейнер оказывается «уже свежим» и весь путь пересоздания не проверяется.
if [[ -n "$REHEARSE" && -z "$DRY_RUN" ]]; then
  bold "      завожу одноразовый контейнер «${REHEARSE}»"
  SETUP=$(remote "$(rs "SUDO=$(shq "$SUDO"); NAME=$(shq "$REHEARSE"); NEWIMG=$(shq "$NEW_ID"); NEWTAG=$(shq "$IMAGE_TAG"); URL=$(shq "$REHEARSE_LINKEON_URL"); PFROM=$(shq "$REHEARSE_PORT_FROM"); PTO=$(shq "$REHEARSE_PORT_TO"); REPO=$(shq "$IMAGE_REPO"); ROOT=$(shq "$REHEARSE_DIR_ROOT")" <<'EOS'
set -u
D="$ROOT/$NAME"
MARK="$D/.linkeon-rehearsal"

# ── ЧЕЙ ЭТО КАТАЛОГ ──────────────────────────────────────────────────────────
# Метка внутри каталога — единственное основание его удалять. Каталог без
# метки НЕ НАШ: рядом лежат чекауты клиентов, и «похоже на мусор прошлой
# репетиции» не тот довод, по которому можно звать rm -rf. Каталог со своей
# меткой — остаток нашего же оборвавшегося захода, его сносим и заводим заново
# (иначе повторный заход после обрыва связи упирался бы в собственный след).
if [ -e "$D" ]; then
  if [ -f "$MARK" ]; then
    $SUDO docker rm -f "$NAME" >/dev/null 2>&1 || true
    $SUDO rm -rf "$D" || { echo "SETUP_ERR остаток прошлой репетиции $D не убирается"; exit 0; }
  else
    echo "SETUP_ERR каталог $D уже существует и НЕ помечен как репетиционный — не трогаю его"
    exit 0
  fi
fi

# Уборка за собой на ЛЮБОМ отказе ниже. Раньше её не было, и первая же неудача
# (отказ сборки производного образа) оставляла /srv/products/<имя>: следующий
# заход отказывался стартовать, и каталог убирали руками. Скрипт здесь знает
# состояние точнее всех — он его и создал, поэтому убирает он же, а не только
# ловушка на той стороне ssh.
fail() { # fail <текст>
  $SUDO docker rm -f "$NAME" >/dev/null 2>&1 || true
  $SUDO docker image rm -f "$REPO:rehearse-stale" >/dev/null 2>&1 || true
  [ -f "$MARK" ] && $SUDO rm -rf "$D"
  echo "SETUP_ERR $1"
  exit 0
}

# Порт ищется среди ВСЕХ контейнеров, включая остановленные (у остановленного
# .NetworkSettings.Ports пуст, поэтому спрашиваем .HostConfig.PortBindings), и
# сверх того у слушающих сокетов.
busy=$($SUDO docker ps -a --format '{{.Names}}' | while IFS= read -r c; do
         $SUDO docker inspect "$c" --format '{{range $p, $bs := .HostConfig.PortBindings}}{{range $b := $bs}}{{$b.HostPort}}{{println}}{{end}}{{end}}' 2>/dev/null
       done; ss -ltnH 2>/dev/null | awk '{print $4}' | sed 's/.*://')
PORT=""
p="$PFROM"
while [ "$p" -le "$PTO" ]; do
  if ! printf '%s\n' "$busy" | grep -qx "$p"; then PORT="$p"; break; fi
  p=$((p+1))
done
[ -n "$PORT" ] && [ -n "${PORT#0}" ] || { echo "SETUP_ERR свободного порта в $PFROM-$PTO нет"; exit 0; }

$SUDO mkdir -p "$D" || { echo "SETUP_ERR не смог создать $D"; exit 0; }
# Метка ставится ПЕРВОЙ, ещё до содержимого: упади следующая же строка — каталог
# уже опознаётся как наш, и уборка имеет право его снести.
$SUDO touch "$MARK" || { $SUDO rmdir "$D" 2>/dev/null || true; echo "SETUP_ERR не смог пометить $D как репетиционный"; exit 0; }
$SUDO tee "$D/package.json" >/dev/null <<PKG
{ "name": "$NAME", "version": "1.0.0", "private": true,
  "scripts": { "start": "node server.js", "build": "echo nothing to build" } }
PKG
$SUDO tee "$D/server.js" >/dev/null <<'SRV'
const http = require('http');
const PORT = process.env.PORT || 3000;
http.createServer((req, res) => {
  if (req.url === '/health') { res.writeHead(200, {'content-type':'application/json'}); return res.end('{"ok":true,"sha":"rehearsal"}'); }
  res.writeHead(200, {'content-type':'text/plain; charset=utf-8'});
  res.end('linkeon rehearsal container');
}).listen(PORT);
SRV
# entrypoint.sh отказывается стартовать без .git в /product — репетиция обязана
# пройти тот же путь, что и продукт.
$SUDO git init -q "$D" \
  && $SUDO git -C "$D" config user.email 'rehearsal@linkeon.io' \
  && $SUDO git -C "$D" config user.name 'Linkeon Rehearsal' \
  && $SUDO git -C "$D" add -A \
  && $SUDO git -C "$D" commit -qm 'репетиционный каркас' \
  || fail "не смог сделать чекаут в $D"
$SUDO chown -R 1000:1000 "$D"

# Заведомо ОТЛИЧНЫЙ образ: тот же FROM плюс метка. Так контейнер гарантированно
# отстаёт, и пересоздание проверяется целиком.
#
# FROM берёт МЕТКУ, а не идентификатор: идентификаторы здесь укорочены до 12
# символов (`sha256:8ddbcabec6b5`), и docker такую ссылку во FROM не принимает —
# измерено, сборка отказывала, а репетиция объявляла «не смог собрать
# производный образ» и не начиналась вовсе.
printf 'FROM %s\nLABEL io.linkeon.rehearsal="1"\n' "$NEWTAG" \
  | $SUDO docker build -q -t "$REPO:rehearse-stale" - >/dev/null 2>&1 \
  || fail "не смог собрать производный образ для репетиции (FROM $NEWTAG)"

# Токен случайный: он никуда не подойдёт, раннер будет честно не опознан. Это и
# есть репетиция МЕХАНИКИ, а не связи с сервером.
$SUDO docker run -d --name "$NAME" --restart unless-stopped \
  -v "$D:/product" \
  -p "127.0.0.1:$PORT:3000" \
  -e "LINKEON_URL=$URL" \
  -e "RUNNER_TOKEN=rehearsal-$(head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n')" \
  -e CLAUDE_CODE_OAUTH_TOKEN=rehearsal-not-a-real-token \
  -e PRODUCT_START_SCRIPT=server.js -e PORT=3000 \
  --memory=1g --cpus=1 "$REPO:rehearse-stale" >/dev/null \
  || fail "docker run репетиционного контейнера отказал"
echo "SETUP_OK port=$PORT"
EOS
)") || die "репетиционный контейнер завести не удалось"
  if ! grep -q '^SETUP_OK' <<<"$SETUP"; then
    red "$(grep -m1 '^SETUP_ERR' <<<"$SETUP" | sed 's/^SETUP_ERR //' || true)"
    # Установка убирает за собой сама (см. fail в её теле); ловушка на выходе
    # доберёт остальное. Каталог, который не наш, не трогается ни там, ни там.
    die "репетиция не началась — клиентские контейнеры не тронуты, за собой убрано"
  fi
  REHEARSE_PORT=$(sed -n 's/^SETUP_OK port=//p' <<<"$SETUP" | tail -1)
  ok "репетиционный контейнер «${REHEARSE}» поднят на порту $REHEARSE_PORT из $IMAGE_REPO:rehearse-stale"
  # Пересобираем список: новый контейнер появился уже после опроса.
  CANDIDATES=$(remote "$(rs "SUDO=$(shq "$SUDO"); NAME=$(shq "$REHEARSE")" <<'EOS'
set -u
$SUDO docker inspect "$NAME" --format \
  "$NAME|{{.State.Status}}|{{.Image}}|{{.HostConfig.NetworkMode}}|{{.HostConfig.Privileged}}" 2>/dev/null
EOS
)") || die "репетиционный контейнер не опрашивается"
fi

