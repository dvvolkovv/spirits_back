#!/bin/bash
# Замер ресурсов во время встречи Meet — для планирования ёмкости.
#
# Заведён потому, что отчёт по первой рабочей встрече (10.09.2026) пришлось
# сдать с оценкой вместо числа: RSS Chrome во время разговора никто не снял, а
# повторить встречу — это позвать живого человека. Теперь замер запускается
# одной командой рядом с входом бота.
#
# Chrome живёт В КОНТЕЙНЕРЕ ВОРКЕРА Attendee (Celery-режим, отдельного пода на
# бота нет), поэтому память встречи — это прирост этого контейнера, а не
# отдельного процесса на хосте.
#
# Запуск на стенде:
#   bash measure-meeting.sh [сколько_замеров] [интервал_сек]   # по умолчанию 40 × 10с
#
# Колонки:
#   t,с       — секунды с начала замера
#   конт-RAM  — память контейнера воркера Attendee (вместе с Chrome)
#   конт-CPU  — его же CPU; на хосте с N ядрами 100% = одно ядро
#   chrome    — суммарный RSS процессов Chrome внутри контейнера
#   шт        — сколько процессов Chrome (у него их всегда несколько)
#   воркер    — суммарный RSS наших процессов voice-host (пул + задание)
#   LA1       — загрузка хоста за минуту

set -u
N=${1:-40}
EVERY=${2:-10}
C=attendee-attendee-worker-local-1

printf "%-6s %-11s %-9s %-9s %-4s %-9s %-6s\n" "t,с" "конт-RAM" "конт-CPU" "chrome" "шт" "воркер" "LA1"
for i in $(seq 1 "$N"); do
  T=$(( i * EVERY ))

  # Одним вызовом: docker stats --no-stream сам занимает секунду-две.
  STAT=$(docker stats --no-stream --format '{{.Name}}|{{.CPUPerc}}|{{.MemUsage}}' 2>/dev/null | grep "$C" || true)
  CPU=$(printf '%s' "$STAT" | cut -d'|' -f2)
  MEM=$(printf '%s' "$STAT" | cut -d'|' -f3 | awk '{print $1}')

  # ps внутри контейнера: Chrome форкается на несколько процессов, нужна сумма.
  CH=$(docker exec "$C" sh -c "ps -eo rss=,comm= 2>/dev/null | awk '/chrome/ {s+=\$1} END {printf \"%d\", s/1024}'" 2>/dev/null | tr -cd '0-9')
  # `grep -c` при нуле совпадений возвращает код 1, поэтому «|| echo 0»
  # дописывал вторую строку и ломал таблицу. Гасим код внутри и чистим пробелы.
  CNT=$(docker exec "$C" sh -c "ps -eo comm= 2>/dev/null | grep -c chrome || true" 2>/dev/null | tr -cd '0-9')

  # Наши процессы: пул воркера плюс процесс задания (fork на встречу).
  VH=$(ps -eo rss=,args= 2>/dev/null | awk '/voice-host/ && !/awk/ {s+=$1} END {printf "%d", s/1024}')

  LA=$(cut -d' ' -f1 /proc/loadavg)

  printf "%-6s %-11s %-9s %-9s %-4s %-9s %-6s\n" \
    "$T" "${MEM:-—}" "${CPU:-—}" "${CH}M" "${CNT:-0}" "${VH}M" "$LA"
  sleep "$EVERY"
done
