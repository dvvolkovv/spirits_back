import { fileURLToPath } from 'node:url';

/**
 * Свои настройки сервис читает сам.
 *
 * Раньше их давало окружение, в котором его однажды запустили, — и это вышло
 * боком: ключи Zoom легли в `.env`, `pm2 restart` поднял процесс со СТАРЫМ
 * окружением, и бот отказался идти на встречу с «нет ключей Zoom», хотя ключи
 * были на месте (16.09.2026). Окружение процесса — снимок момента запуска, а
 * файл настроек живёт дальше и меняется.
 *
 * Импортируется ПЕРВЫМ: модули читают env на уровне модуля, то есть в момент
 * импорта, и опоздать здесь означает прочитать пустоту.
 *
 * Уже заданные переменные не трогаем: то, что передали снаружи (например, порт
 * при отладке), важнее файла.
 */
try {
  process.loadEnvFile(fileURLToPath(new URL('../.env', import.meta.url)));
} catch (e) {
  // Файла может не быть вовсе — тогда работаем на том, что дало окружение.
  if (e?.code !== 'ENOENT') console.warn('настройки из .env не прочитались:', e?.message);
}
