/**
 * Какие адреса встреч мы понимаем.
 *
 * Отдельным модулем, а не внутри сервера: это единственное место, где ошибка
 * видна не сразу — бот молча уйдёт не на ту площадку или откажет по живой
 * ссылке. Тесты на такое пишутся, а сервер ради них поднимать не хочется.
 *
 * Хосты везде точные. Необязательный поддомен — с точкой внутри группы: без
 * неё прошли бы `notzoom.us` и `notmeet.google.com`, и это та самая ошибка,
 * от которой в `meeting-link.ts` защищаются двумя комментариями.
 */
const PLATFORM_BY_URL = [
  [/https?:\/\/telemost\.yandex\.ru\/j\/\d{6,20}/i, 'telemost'],
  // Личные ссылки Zoom `/my/<имя>` не поддержаны: номера встречи в них нет, и
  // SDK по ним войти не может.
  [/https?:\/\/(?:[a-z0-9-]+\.)?zoom\.us\/(?:j|w)\/\d{9,12}/i, 'zoom'],
  // Код Meet — три-четыре-три буквы; `lookup`-ссылки и `/new` не поддержаны.
  [/https?:\/\/meet\.google\.com\/[a-z]{3}-[a-z]{4}-[a-z]{3}/i, 'meet'],
];

/** Площадка по адресу встречи. `null` — не наша забота. */
export function platformFor(url) {
  for (const [re, name] of PLATFORM_BY_URL) if (re.test(url || '')) return name;
  return null;
}
