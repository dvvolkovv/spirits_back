import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { send } from '../src/webhooks.mjs';

/**
 * Пустой адрес вебхуков обязан быть ВИДЕН.
 *
 * До 19.10.2026 `send` на пустом адресе молча возвращал «успех». Это и скрыло
 * настоящую поломку: на проде адрес не был задан вовсе, бот не отправлял
 * ничего, в логе не было ни строчки — а снаружи встречи ломались необъяснимо.
 * Ассистент не видел участников и выходил через пятнадцать минут при живых
 * людях (Телемост 13.10.2026); не сумевший войти бот не мог об этом сказать, и
 * звонок висел в `dialing`, пока пользователю было написано «ассистент на
 * встрече» (Meet 19.10.2026).
 *
 * Чинится это на обеих сторонах: бэкенд с той же даты вообще не создаёт бота
 * без вебхуков (createBot в src/meeting/attendee.client.ts), а здесь остаётся
 * страховка на случай, если бот запустят руками.
 */
describe('вебхуки без адреса', () => {
  /** Лог, который считает жалобы. Настоящий console утопил бы вывод тестов. */
  const counting = () => {
    const warns = [];
    return { log: { warn: (m) => warns.push(String(m)) }, warns };
  };

  test('жалуется в лог и не делает вид, что отправил', async () => {
    const { log, warns } = counting();
    const res = await send('', 'c2VjcmV0', { trigger: 'bot.state_change' }, log);
    // `true` — намеренно: вызывающий считает `false` отказом ДОСТАВКИ и
    // повторяет (syncParticipants), а повторять здесь нечего — адреса не
    // появится. Видимость даёт лог, а не код возврата.
    assert.equal(res, true);
    assert.equal(warns.length, 1, 'жалоба обязана быть ровно одна');
    assert.match(warns[0], /вебхуки не настроены/);
  });

  test('жалуется ОДИН раз, а не на каждое событие', async () => {
    // События идут десятками в минуту: жалоба на каждое утопила бы лог ровно
    // тогда, когда по нему разбираются.
    const { log, warns } = counting();
    for (let i = 0; i < 5; i++) {
      await send('', 'c2VjcmV0', { trigger: 'meet_participant' }, log);
    }
    assert.equal(warns.length, 0, 'про этот процесс уже сказано в тесте выше');
  });
});
