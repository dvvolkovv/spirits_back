/**
 * Найти специалиста по имени, как его произнесла модель.
 *
 * Регистр и пробелы не должны решать: Realtime возвращает имя строкой из
 * распознанной речи, и «шанкара» вместо «Шанкара» превратилось бы в
 * unknown_specialist — то есть Роман сказал бы вслух, что такого коллеги нет.
 */
export function findSpecialist(spoken: string): number | undefined {
  const needle = (spoken || '').trim().toLowerCase();
  if (!needle) return undefined;
  const hit = Object.keys(SPECIALISTS).find((n) => n.toLowerCase() === needle);
  return hit ? SPECIALISTS[hit] : undefined;
}

