-- Чем кончился звонок: человек попрощался или связь порвалась.
--
-- До этого сервер не различал их вовсе. Воркер в обоих случаях сообщал
-- `participant_disconnected`, строка писалась 'completed', и при перезвоне
-- после обрыва ассистент здоровался заново вместо «нас прервало» (живой
-- разговор владельца 28.10.2026, спека «Контекст и суверенитет» §4.8).
--
-- Две колонки, и обе нужны:
--   end_reason — вердикт для тех, кто принимает решения (см. end-reason.ts);
--   end_raw    — что на самом деле сказал LiveKit, слово в слово.
-- Вердикт выводится из кодов протокола и проверен пока только по его
-- документации. Если живые звонки покажут другое, чинить надо отображение —
-- а для этого сырое должно быть записано, а не вычислено заново.
--
-- NULL означает «не знаем»: у звонков до этой правки причины нет и не будет.
ALTER TABLE voice_calls
  ADD COLUMN IF NOT EXISTS end_reason text,
  ADD COLUMN IF NOT EXISTS end_raw text;
