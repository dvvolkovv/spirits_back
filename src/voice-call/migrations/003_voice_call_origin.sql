-- Откуда начат звонок: 'launcher' (кнопка на локскрине) или 'web' (чат my.linkeon).
--
-- Нужно для двух вещей, и обе из спеки «Контекст и суверенитет»:
--   1. состав контекста — вебу секция device не положена, у него нет устройства (§4.1);
--   2. срок хранения транскрипта — TTL для лаунчера, бессрочно для веба (§7.2).
--
-- Дефолт 'launcher' намеренно: старые версии компаньона метку не пришлют, а они
-- как раз лаунчерные, и ошибаться надо в сторону более короткого хранения.
ALTER TABLE voice_calls
  ADD COLUMN IF NOT EXISTS origin text NOT NULL DEFAULT 'launcher';
