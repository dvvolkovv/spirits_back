-- токены, а голосом была бесплатной — голос работал бесплатным каналом к
-- платным ассистентам. Замечено 26.08.2026.
--
-- Колонка нужна не для списания (оно идёт через token_consumption_tasks), а
-- чтобы цифру можно было показать в звонке и потом сверить: сколько стоила
-- каждая консультация отдельно.

