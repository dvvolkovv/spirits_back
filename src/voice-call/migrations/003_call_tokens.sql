-- 003_call_tokens.sql
-- Сколько токенов списано за сам разговор.
--
-- Раньше строка учёта писалась со статусом 'completed' и нулём к списанию:
-- минуты считались, но не стоили ничего. Так было задумано в первой версии —
-- тариф за минуту назначать было не из чего. После того как консультации
-- специалистов начали списываться, эта половина стала выглядеть
-- непоследовательно: работа ассистента стоит денег, а полчаса разговора нет.
--
-- Колонка нужна не для списания (оно идёт через token_consumption_tasks), а
-- чтобы показать цифру в карточке звонка. Брать её из cost_usd на фронте
-- нельзя: курс живёт в бэкенде и меняется, а карточка должна показывать то,
-- что реально списано, а не пересчёт по сегодняшнему курсу.

ALTER TABLE voice_calls ADD COLUMN IF NOT EXISTS tokens_charged INTEGER NOT NULL DEFAULT 0;
