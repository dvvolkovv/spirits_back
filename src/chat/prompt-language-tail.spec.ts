import * as fs from 'fs';
import * as path from 'path';

/// Требование языка должно стоять В КОНЦЕ каждого собираемого промпта.
///
/// Дважды починено и дважды не помогло, потому что путей сборки промпта три:
/// прямой к Anthropic, релей r.linkeon.io для обычных ассистентов и отдельный
/// для служебных ответов. Языковая директива стоит в начале каждого, а за ней
/// приклеиваются персона, профиль, задачи, баланс и история — всё по-русски.
/// Модель читает язык последних строк как образец.
///
/// Тест смотрит на исходник, а не на поведение: поведение проверяется живым
/// запросом, но забыть четвёртый путь легко, и обнаружится это снова только
/// у пользователя.
describe('языковая строка в конце промпта', () => {
  const src = fs.readFileSync(
    path.join(__dirname, 'chat.service.ts'),
    'utf8',
  );

  it('каждая сборка промпта заканчивается строкой на целевом языке', () => {
    // Сколько путей строит промпт — столько раз должна встретиться и строка.
    const directives = src.match(/LanguageService\.buildDirective/g) || [];
    const tails = src.match(/LANGUAGE_REPLY_LINE\[/g) || [];
    expect(tails.length).toBeGreaterThanOrEqual(directives.length);
  });

  it('строка не потеряна из импорта', () => {
    expect(src).toMatch(/import \{[^}]*LANGUAGE_REPLY_LINE/);
  });
});
