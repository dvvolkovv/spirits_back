/**
 * Кризисное правило: что делать, если человек пишет о самоубийстве, о вреде
 * себе, об угрозе жизни или о насилии.
 *
 * КОМУ ЕГО ДОБАВЛЯЕТ КОД. Только пользовательским ассистентам (custom_agents):
 * их промпты пишут сами пользователи, и кризисного блока там нет. Штатные
 * ассистенты несут этот же текст в конце своего промпта в таблице agents —
 * добавлять его им ещё и здесь значило бы класть в промпт два экземпляра.
 *
 * Куда добавляется:
 *   • веб — buildRelayStablePrefix в chat.service.ts. Через него идут и
 *     текстовый ход, и ход с вложениями: сессия на релее у них одна;
 *   • Telegram — resolveSystemPrompt в tg-bot/tg-router.service.ts.
 *
 * Правило написано по-русски, как и остальные блоки промпта: отвечает модель
 * на языке пользователя, это обеспечивает языковая директива. Номера —
 * российские; тем, кто не в России, правило велит назвать местную экстренную
 * службу.
 */
export const CRISIS_RULE = `КРИЗИСНАЯ СИТУАЦИЯ — ЭТО ПРАВИЛО ВАЖНЕЕ ВСЕХ ОСТАЛЬНЫХ
Если человек пишет о мыслях о самоубийстве или о том, чтобы причинить себе вред, об угрозе своей или чужой жизни, о насилии — над ним или с его стороны:
- Отложи методику, сценарий и формат ответа. Запрет давать советы здесь не действует.
- Ответь просто и тепло: ты слышишь, это серьёзно, человек не один. Без нотаций, паники и фраз вроде «я всего лишь программа».
- Если неясно, насколько всё остро, прямо спроси, думает ли он о самоубийстве и в безопасности ли он сейчас. Прямой вопрос не подталкивает, а помогает.
- Предложи живую помощь прямо сейчас:
  — опасность для жизни сейчас — 112;
  — линия психологической помощи МЧС России: +7 (495) 989-50-50, круглосуточно и анонимно;
  — детям, подросткам и их родителям — детский телефон доверия 8-800-2000-122, бесплатно.
  Если человек не в России — местная экстренная служба.
- Предложи прямо сейчас связаться с тем, кому он доверяет, и не оставаться одному.
- Не отправляй к другим ассистентам платформы: кризисной помощи среди них нет.
- Не давай сведений о способах навредить себе или другим.
- Оставайся в разговоре, пока человек хочет говорить. К прежней теме возвращайся, только если он сам этого захочет.`;

/**
 * Промпт пользовательского ассистента с кризисным правилом в конце — там же,
 * где оно стоит у штатных. Пустой промпт правило не теряет.
 */
export function withCrisisRule(prompt: string | null | undefined): string {
  const own = (prompt || '').trim();
  return own ? `${own}\n\n${CRISIS_RULE}` : CRISIS_RULE;
}
