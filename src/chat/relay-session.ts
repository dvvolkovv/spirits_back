/**
 * Ключ сессии релея (r.linkeon.io) — ЕДИНСТВЕННЫЙ источник правды.
 *
 * Релей резюмит Claude-сессию по этому ключу, и от него же зависят папки
 * файлов хода на диске: они называются по `fs_key` — HMAC этого ключа
 * (linkeon-relay-fields.ts), то есть `/tmp/agent-uploads/<fs_key>_<имя>` и
 * `/tmp/agent-output/<fs_key>`; без секретов `fs_key` нет, и релей берёт сам
 * ключ. Два разных ключа для одного разговора — это два разных агента с разной
 * памятью и разными папками.
 *
 * Так и разошлось 18.08.2026: коммит 882befb добавил язык в ключ текстового
 * хода (`chat.service.ts`), а загрузка файлов (`chat.controller.ts`,
 * upload-and-chat) осталась на старом `<userId>_<assistantId>`. Три недели файл
 * жил ровно один ход: путь к нему объявлялся в промпте upload-сессии, а весь
 * дальнейший разговор шёл в `_<язык>`-сессии, которая про этот файл не знала
 * ничего — в её транскриптах имя файла не встречается ни разу. Пользователь
 * присылал выписку и через десять минут слышал «точного числа заранее не
 * назвать» про то, что лежало в присланном файле.
 *
 * Поэтому ключ считается ЗДЕСЬ и только здесь: любой новый путь к релею обязан
 * звать эту функцию, а не клеить строку у себя.
 *
 * Точка «Чистого листа» входит в ключ: та же пара (пользователь, ассистент)
 * после новой точки — новый ключ, а значит новая Claude-сессия без старой памяти.
 * И новая папка файлов хода (fs_key — от ключа): файлов до точки в папке новой
 * сессии нет, это задумано — ассистент после точки не должен на них опираться.
 * Лента при этом одна: ссылки на прежние файлы в ней остаются.
 */
export function relaySessionKey(
  userId: string,
  assistantId: string,
  userLanguage: string,
  // Изолированная сессия пинга мониторинга (probe + fresh, только тестовые
  // аккаунты): задан — значит он и есть ключ.
  freshSessionId?: string,
  // Точка «Чистого листа» (spec 2026-11-17-context-reset): новая точка —
  // новая Claude-сессия, релей не резюмит память, накопленную до неё.
  resetAt?: Date | null,
): string {
  if (freshSessionId) return freshSessionId;
  const base = `${userId}_${assistantId}_${userLanguage}`;
  return resetAt ? `${base}_r${resetAt.getTime()}` : base;
}
