/**
 * Ключ сессии релея (r.linkeon.io) — ЕДИНСТВЕННЫЙ источник правды.
 *
 * Релей резюмит Claude-сессию по этому ключу и по нему же раскладывает файлы на
 * диске: `/tmp/agent-uploads/<ключ>_<имя>` и `/tmp/agent-output/<ключ>`. Два
 * разных ключа для одного разговора — это два разных агента с разной памятью и
 * разными папками.
 *
 * Так и разошлось 18.08.2026: коммит 882befb добавил язык в ключ текстового
 * хода (`chat.service.ts`), а загрузка файлов (`chat.controller.ts`,
 * upload-and-chat) осталась на старом `<userId>_<assistantId>`. Три недели файл
 * жил ровно один ход: путь к нему объявлялся в промпте upload-сессии, а весь
 * дальнейший разговор шёл в `_<язык>`-сессии, которая про этот файл не знала
 * ничего — в её транскриптах имя файла не встречается ни разу. Пользователь
 * присылал выписку и через десять минут слышал «точного числа заранее не
 * назвать» про то, что лежало в присланном файле.
 *
 * Поэтому ключ считается ЗДЕСЬ и только здесь: любой новый путь к релею обязан
 * звать эту функцию, а не клеить строку у себя.
 */
export function relaySessionKey(
  userId: string,
  assistantId: string,
  userLanguage: string,
  // «Чистый лист»: у режима своя сессия на релее, чтобы прошлый разговор не
  // протаскивался в неё мимо наших блокировок. Задан — значит он и есть ключ.
  freshSessionId?: string,
): string {
  if (freshSessionId) return freshSessionId;
  return `${userId}_${assistantId}_${userLanguage}`;
}
