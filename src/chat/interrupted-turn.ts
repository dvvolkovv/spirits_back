/**
 * Служебная строка в реплику, пришедшую посреди идущего хода той же сессии
 * релея.
 *
 * Такая реплика пре-эмптит ход на релее: процесс сессии убивается, начатая
 * работа до человека не доходит. Чаще всего это не новая задача, а «ты
 * работаешь?», «ещё раз», «?» — человек не дождался, либо уточнение уже
 * начатой задачи («и добавь колонку…»). Без этой строки модель отвечала
 * статусом «нет, сейчас ничего не идёт» и ждала «запускай», либо начинала
 * всё заново (находка «Затыков недели» 2ff1a026).
 *
 * Три исхода: статус-вопрос/повтор — продолжить с сохранённого; уточнение —
 * продолжить с сохранённого, но с поправкой на уточнение; новая задача —
 * начать её. Только текстовый ход релея своей сессии (relayRunning по
 * relaySid, см. ChatService) — чужую сессию (другой язык, «чистый лист»,
 * другой ассистент) реплика не прерывает, и строки там нет.
 *
 * Строку получает только ТЕКСТОВЫЙ ход. Загрузка файла, пришедшая посреди
 * текстового хода, прерывает его на релее точно так же (общий relaySid), но
 * «тот ход прерван» не получает — у ChatController.uploadAndChat этой
 * проверки нет. Зато оба пути получают relayUndeliveredNote, если предыдущий
 * ход той же сессии не прерван, а ЖДЁТ релей за шлагбаумом выката
 * (relay-drain-retry.ts): его сообщение до модели ещё не дошло, и новое
 * сообщение несёт его с собой (с 16.11.2026, пункт aa27b1d5).
 *
 * Два окна неточности здесь приемлемы, раз строка — не гарантия, а подсказка
 * модели: (1) между нашей проверкой relayRunning и тем, как процесс реально
 * поднимется на релее, проходит доля секунды самого HTTP-запроса; (2) ход с
 * крупными вложениями передаёт их заметное время, в течение которого метка
 * уже стоит, а процесса на релее ещё нет. В обоих случаях строка может
 * появиться или пропасть чуть не в такт с реальностью — это не ломает ничего,
 * модель просто реагирует с небольшой задержкой.
 *
 * Ещё три окна — у ждущего хода (relayUndeliveredNote): (3) ждущий ход успел
 * проскочить к релею, пока новый собирал промпт, — модель увидит его текст
 * дважды, это безвредно; (4) новый ход прочитал состояние сессии раньше, чем
 * старый встал в ожидание, — старый не перенесён и кончается не молча, а
 * заглушкой «ассистент обновляется — отправьте ещё раз»
 * (ChatService.postRelayTurn); (5) новый ход забрал текст ждущего, а потом
 * упал сам по причине не из шлагбаума (startFailed / fileFailed: 500, 504,
 * обрыв, тайм-аут), — ждущий уже кончился молча как перебитый, и его
 * сообщение до модели так и не доходит, молча: человек видит ошибку только
 * у нового и переотправит его, а не старое. Из одной вкладки так не выйдет — пока ход
 * идёт, кабинет держит новое сообщение в своей очереди досылки; нужны два
 * устройства или вкладки. Принято, не закрываем.
 */
export const INTERRUPTED_TURN_NOTE =
  '[Служебно: это сообщение пришло, пока ты ещё выполнял прошлый запрос, и тот ход прерван — ' +
  'ответ до человека не дошёл. Если сообщение не меняет задачу (вопрос о статусе, ' +
  '«ещё раз», «?», «ну что там») — сразу продолжи прерванную работу: возьми то, что прерванный ' +
  'ход успел сохранить, и шаги выше в разговоре. Если сообщение уточняет задачу (например, «и добавь ' +
  'колонку…») — тоже продолжи прерванную работу, но с учётом уточнения. В обоих случаях не ' +
  'отвечай одним статусом и не начинай заново. Если сообщение меняет задачу — делай новое.]';

/** Недошедшее сообщение человека: текст и имена приложенных файлов. */
export interface RelayCarry {
  message: string;
  files: string[];
}

/**
 * Служебная строка для модели: прошлое сообщение человека не дошло — ход
 * ждал релей за шлагбаумом выката, и его перебило это сообщение. Файлы
 * повторно не отправляются (их байты остались в том запросе) — модель
 * просит прислать их ещё раз.
 */
export function relayUndeliveredNote(carry: RelayCarry): string {
  const parts = ['[Служебно: предыдущее сообщение человека до тебя не дошло — платформа обновлялась.'];
  const text = String(carry.message ?? '').trim();
  if (text) parts.push(`Вот оно: «${text}».`);
  if (carry.files.length) {
    parts.push(`К нему были приложены файлы: ${carry.files.join(', ')} — до тебя они не дошли; попроси человека прислать их ещё раз.`);
  }
  // «Всех», а не «обоих»: цепочка ждущих ходов несёт больше двух сообщений.
  parts.push('Ответь с учётом всех этих сообщений.]');
  return parts.join(' ');
}
