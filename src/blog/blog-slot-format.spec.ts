import { formatSlotWhen } from './blog-slot-format';

/**
 * Все ожидаемые строки ниже перепроверены отдельно через node -e с той же
 * арифметикой (сдвиг +3ч и чтение UTC-компонент), а день недели — ещё и через
 * getUTCDay() на анкерной дате 2026-01-01 (четверг). Это не «по памяти»:
 * реальная памятка задачи для даты 2026-09-24T07:00:00Z называла её средой —
 * это среда, 24 сентября 2026 на самом деле ЧЕТВЕРГ. Ориентир в задаче был
 * ошибочным, поэтому ниже — проверенное значение, а не переписанный образец.
 */
describe('formatSlotWhen', () => {
  it('дата из задания (2026-09-24T07:00:00Z) — «в четверг», а не «в среду»', () => {
    // на момент now (пн 21.09, 08:00 МСК) слот не сегодня и не завтра
    const slot = new Date('2026-09-24T07:00:00Z');
    const now = new Date('2026-09-21T05:00:00Z');
    expect(formatSlotWhen(slot, now)).toBe('в четверг, 24 сентября, в 10:00 МСК');
  });

  it('слот сегодня же (тот же слот, что и в nextSlotAfter) — «сегодня», не день недели', () => {
    const slot = new Date('2026-09-21T07:00:00Z');   // пн 10:00 МСК
    const now = new Date('2026-09-21T05:00:00Z');    // пн 08:00 МСК, тот же день
    expect(formatSlotWhen(slot, now)).toBe('сегодня в 10:00 МСК');
  });

  it('слот завтра — «завтра», не день недели', () => {
    const slot = new Date('2026-09-23T07:00:00Z');   // ср 10:00 МСК
    const now = new Date('2026-09-22T12:00:00Z');    // вт 15:00 МСК
    expect(formatSlotWhen(slot, now)).toBe('завтра в 10:00 МСК');
  });

  /**
   * Критично: «сегодня/завтра» считаем по МОСКОВСКОЙ календарной дате, а не
   * по UTC. В 22:00 UTC в Москве уже 01:00 следующих суток — если сравнивать
   * по UTC-дате, слот на то же московское утро ошибочно назовётся «в
   * <день недели>» вместо «сегодня».
   */
  it('«сегодня» считается по московской дате, а не по UTC-дате (после 21:00 UTC в Москве уже новые сутки)', () => {
    const now = new Date('2026-09-21T22:00:00Z');    // UTC-дата 21.09, но МСК-дата уже 22.09 (01:00)
    const slot = new Date('2026-09-22T07:00:00Z');   // 22.09 10:00 МСК
    expect(formatSlotWhen(slot, now)).toBe('сегодня в 10:00 МСК');
  });

  it('«завтра» корректно переходит через границу года', () => {
    const now = new Date('2026-12-31T15:00:00Z');    // 31.12, 18:00 МСК
    const slot = new Date('2027-01-01T05:00:00Z');   // 01.01.2027, 08:00 МСК
    expect(formatSlotWhen(slot, now)).toBe('завтра в 08:00 МСК');
  });

  it('вторник требует предлога «во», а не «в» — «во вторник»', () => {
    const slot = new Date('2026-09-29T07:00:00Z');   // вт 10:00 МСК, не сегодня/завтра относительно now
    const now = new Date('2026-09-21T05:00:00Z');
    expect(formatSlotWhen(slot, now)).toBe('во вторник, 29 сентября, в 10:00 МСК');
  });

  it('воскресенье форматируется без переноса на «понедельник» через getUTCDay()===0', () => {
    const slot = new Date('2026-09-27T07:00:00Z');   // вс 10:00 МСК
    const now = new Date('2026-09-21T05:00:00Z');
    expect(formatSlotWhen(slot, now)).toBe('в воскресенье, 27 сентября, в 10:00 МСК');
  });

  it('год переходит корректно: 31.12 вечером по UTC в Москве уже 1 января', () => {
    const slot = new Date('2026-12-31T21:00:00Z');   // 01.01.2027, 00:00 МСК
    const now = new Date('2026-09-21T05:00:00Z');
    expect(formatSlotWhen(slot, now)).toBe('в пятницу, 1 января, в 00:00 МСК');
  });

  it('час и минуты дополняются нулём слева: 07:05, а не 7:5', () => {
    const slot = new Date('2026-09-24T04:05:00Z');   // 24.09, 07:05 МСК
    const now = new Date('2026-09-21T05:00:00Z');
    expect(formatSlotWhen(slot, now)).toBe('в четверг, 24 сентября, в 07:05 МСК');
  });

  /**
   * Telegram обрезает/отвергает текст всплывашки answerCallbackQuery длиннее
   * 200 символов. Сама фраза формата — лишь часть итогового текста в
   * blog-approval.service.ts, так что берём щедрый запас.
   */
  it('фраза всегда короткая — даже самый длинный день недели и осмысленный запас укладываются с большим запасом в лимит Telegram 200 символов', () => {
    const slot = new Date('2026-09-27T07:00:00Z');   // «в воскресенье» — самое длинное название дня
    const now = new Date('2026-09-21T05:00:00Z');
    const phrase = formatSlotWhen(slot, now);
    expect(phrase.length).toBeLessThan(60);
  });
});
