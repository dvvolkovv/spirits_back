-- 004_one_post_per_slot.sql
-- Один пост на слот публикации — гарантия в базе, а не только в коде.
--
-- Одобренный пост больше не держит очередь черновиков, поэтому одобренных
-- стало несколько сразу, и слот каждому считается как ближайший СВОБОДНЫЙ
-- (`nextFreeSlotAfter`). Но код, прочитав «свободно», ничего не гарантирует:
-- владелец жмёт «Опубликовать» в личке, пока в админке одобряют другой пост, а
-- `linkeon-api` поднят в cluster_mode, и два процесса считают свободный слот
-- одновременно. Оба прочли бы «понедельник свободен» и оба туда записались бы.
--
-- Индекс пускает в слот ровно одного. Проигравший получает 23505 по имени
-- этого индекса (`SLOT_INDEX` в blog-slot-claim.ts) и берёт следующий
-- свободный слот; перенос в админке отвечает 409 slot_taken.
--
-- Частичный: слот держат только `approved` и `publishing`. Опубликованный пост
-- своё время уже отработал, отклонённый и сорвавшийся — не выйдут; держи они
-- слот, отклонённый в понедельник пост навсегда закрыл бы понедельник.
--
-- `publishing` в предикате обязателен. Сорвавшаяся отправка возвращает пост из
-- `publishing` в `approved` СО СВОИМ ЖЕ `slot_at` (ретрай паблишера, сторож
-- зависших). Это одна и та же строка, и со своей прежней версией она не
-- конфликтует. Не держи `publishing` слот — другой пост мог бы занять его на
-- время отправки, и возврат в `approved` упал бы на 23505: пост застрял бы в
-- `publishing`, а сторож падал бы на нём каждые пять минут.
--
-- Пустой `slot_at` уникальность не нарушает (NULL не равен NULL); одобрение
-- его всё равно не оставляет.
--
-- Индекс создаётся без CONCURRENTLY: раннер катит каждый файл в транзакции, а
-- таблица — десятки строк. Если в базе УЖЕ есть два поста в одном слоте,
-- создание упадёт с «could not create unique index … is duplicated» — это
-- ровно тот дефект, от которого индекс стережёт. Проверка до наката:
--
--   SELECT slot_at, array_agg(id) FROM blog_post
--    WHERE status IN ('approved', 'publishing')
--    GROUP BY slot_at HAVING count(*) > 1;
--
-- Непусто — развести посты переносом в админке (reschedule) и накатить снова.

CREATE UNIQUE INDEX IF NOT EXISTS uq_blog_post_slot
  ON blog_post (slot_at)
  WHERE status IN ('approved', 'publishing');
