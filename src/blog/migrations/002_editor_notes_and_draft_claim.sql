-- 002_editor_notes_and_draft_claim.sql
-- Две колонки: замечания владельца к черновику и отметка о захвате черновика
-- в работу.
--
-- 1. editor_notes — замечания владельца.
--
-- Реплай на черновик в личке раньше ложился прямо в `body`: чтобы поправить
-- одну фразу, владелец должен был написать весь пост за редактора. Теперь
-- присланный текст — это ЗАМЕЧАНИЕ, пост уходит на переработку, а редактор
-- пишет заново с его учётом.
--
-- Массив, а не одно поле: замечания накапливаются. Второе владелец пишет,
-- глядя на второй черновик, но первое от этого не перестаёт действовать — с
-- одним полем редактор чинил бы одно и ломал другое по кругу. Предел
-- накопления держит TypeScript (`appendEditorNote` в `blog.types.ts`), а не
-- база: он зависит от размера промпта, а не от схемы.
--
-- NOT NULL DEFAULT '{}': иначе у всех строк, заведённых до этой миграции,
-- было бы NULL, и первый же append начинался бы с null вместо пустого списка.
--
-- 2. drafting_started_at — отметка «черновик взят в работу».
--
-- `prepareDrafts` ходит раз в 5 минут, а подготовка черновика (релей с
-- таймаутом 300 с плюс генерация картинки) регулярно длится дольше тика. У
-- переработки при этом НЕТ смены статуса — пост после замечания уже в
-- `drafting`, — так что захватывать было нечем: второй тик брал тот же пост,
-- платил второй раз за релей и картинку и присылал владельцу второй черновик
-- того же поста.
--
-- Захват делается тем же приёмом, что уже доказан на публикации: UPDATE с
-- условием и RETURNING, выигрывает ровно один. Замок в памяти процесса не
-- годится — `linkeon-api` поднят в cluster_mode, и первый же
-- `pm2 scale linkeon-api 2` разнёс бы тики по процессам молча; крон вдобавок
-- иногда дёргают отдельным процессом руками.
--
-- БЕЗ DEFAULT — пустая отметка означает «готов к работе прямо сейчас».
-- Поставить сюда DEFAULT now() значило бы объявить все существующие
-- черновики взятыми в работу и заткнуть канал до протухания порога.

ALTER TABLE blog_post
  ADD COLUMN IF NOT EXISTS editor_notes text[] NOT NULL DEFAULT '{}'::text[];

ALTER TABLE blog_post
  ADD COLUMN IF NOT EXISTS drafting_started_at timestamptz;
