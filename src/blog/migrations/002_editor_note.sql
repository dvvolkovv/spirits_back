-- 002_editor_note.sql
-- Замечания владельца к черновику.
--
-- Реплай на черновик в личке раньше ложился прямо в `body`: чтобы поправить
-- одну фразу, владелец должен был написать весь пост за редактора. Теперь
-- присланный текст — это ЗАМЕЧАНИЕ, пост уходит на переработку, а редактор
-- пишет заново с его учётом.
--
-- Массив, а не одно поле: замечания накапливаются. Второе владелец пишет,
-- глядя на второй черновик, но первое от этого не перестаёт действовать — с
-- одним полем редактор чинил бы одно и ломал другое по кругу. Предел
-- накопления держит TypeScript (`appendEditorNote` в `blog.types.ts`), а не
-- база: он зависит от размера промпта, а не от схемы.
--
-- NOT NULL DEFAULT '{}': иначе у всех строк, заведённых до этой миграции,
-- было бы NULL, и первый же append начинался бы с null вместо пустого списка.

ALTER TABLE blog_post
  ADD COLUMN IF NOT EXISTS editor_notes text[] NOT NULL DEFAULT '{}'::text[];
