-- 005_real_case_source.sql
-- Реальный кейс — новый источник темы: историю приносит владелец, и редактор
-- пересказывает её без вымысла (блок REAL_CASE в blog-editor.prompt.ts).
--
-- Рубрика остаётся 'case', поэтому вся логика рубрик — новость вытесняет кейс,
-- протухают только новости, подписи — работает для реального кейса без
-- изменений. Меняется только набор допустимых источников.
--
-- Миграция лишь расширяет допустимое, старый код с ней совместим — поэтому
-- катится раньше кода. BEGIN/COMMIT здесь нет намеренно: раннер катит каждый
-- файл в своей транзакции, а руками — `psql --single-transaction`. Иначе между
-- DROP и ADD таблица на миг осталась бы вовсе без проверки источника.
--
-- Повторный прогон безопасен: DROP ... IF EXISTS снимает ограничение, ADD
-- ставит его заново.

ALTER TABLE blog_post DROP CONSTRAINT IF EXISTS blog_post_source_check;
ALTER TABLE blog_post ADD CONSTRAINT blog_post_source_check
  CHECK (source IN ('backlog','git','stats','manual','real'));

-- Уникальный индекс на source_ref — чтобы «одно сообщение Telegram, не больше
-- одного кейса» держалось и при одновременной доставке апдейтов. Проверка
-- source_ref и сама вставка в addTopic — это два отдельных запроса
-- (read-then-insert), и между ними есть окно: вебхук разбирает каждый апдейт
-- через setImmediate, а после рестарта очередь апдейтов прилетает пачкой —
-- оригинал сообщения и его правка обрабатываются одновременно и оба успевают
-- пройти проверку «ещё не видели», прежде чем кто-то из них вставит строку.
-- Индекс закрывает это окно на уровне базы: проигравшая вставка получит
-- ошибку уникальности, которую код трактует как «уже заводилась», а не как
-- сбой (см. TG_SOURCE_REF_INDEX в blog-topic.service.ts).
--
-- Индекс частичный — ловит только Telegram-ссылки (`tg:...`). У остальных
-- источников sourceRef обязан повторяться по смыслу: у кейсов по ассистенту
-- (`stats:<id>`) одно и то же значение приходит каждый месяц, и безусловный
-- уникальный индекс сломал бы это намеренное повторение.
--
-- IF NOT EXISTS — по той же причине, что и выше: повторный прогон этой
-- миграции безопасен. CONCURRENTLY не нужен и не годится: раннер катит файл
-- одной транзакцией (а CREATE INDEX CONCURRENTLY внутри транзакции Postgres
-- запрещает), и blog_post — крошечная таблица, так что обычная блокировка на
-- время создания некритична.
CREATE UNIQUE INDEX IF NOT EXISTS blog_post_tg_source_ref_uniq
  ON blog_post (source_ref) WHERE source_ref LIKE 'tg:%';
