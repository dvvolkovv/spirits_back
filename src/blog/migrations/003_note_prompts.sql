-- 003_note_prompts.sql
-- id сообщений-приглашений «Что поправить?» к посту.
--
-- Кнопка «✍️ Замечание» под черновиком присылает владельцу приглашение с
-- полем ответа (ForceReply). Ответ на него ссылается на message_id
-- ПРИГЛАШЕНИЯ, а не черновика, и без этого списка `handleReplyEdit` его не
-- узнал бы: текст замечания ушёл бы ассистенту в чат, то есть кнопка сделала
-- бы хуже, чем было без неё.
--
-- Массив, а не одно поле: владелец может нажать кнопку дважды (в том числе
-- двойным касанием), и ответ на ПЕРВОЕ приглашение тоже должен быть узнан.
-- С одним полем второе нажатие затирало бы первое, и ответ на него молча
-- уходил бы ассистенту.
--
-- Список не чистится ни при переработке, ни на терминальных статусах:
-- приглашение остаётся в чате навсегда, а ответ на него блог обязан узнать в
-- любом статусе поста — чтобы объяснить владельцу, почему замечание сейчас не
-- принять, а не отдать текст ассистенту. Рост держит предел в коде
-- (`MAX_NOTE_PROMPTS` в `blog.types.ts`), а не схема.
--
-- Индекса нет намеренно: поиск идёт по review_chat_id — ведущей колонке
-- idx_blog_post_review_msg, — а в чате владельца десятки постов в год.
--
-- NOT NULL DEFAULT '{}' — как у editor_notes: пустой список это нормальное
-- состояние поста, к которому замечания не просили, а не «неизвестно».

ALTER TABLE blog_post
  ADD COLUMN IF NOT EXISTS note_prompt_ids bigint[] NOT NULL DEFAULT '{}'::bigint[];
