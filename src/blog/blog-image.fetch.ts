import axios from 'axios';

/**
 * Картинку в Telegram отдаём БАЙТАМИ, а не ссылкой.
 *
 * Telegram по URL ходит своими серверами, а my.linkeon.io живёт за РФ-edge
 * Selectel — та же ingress-фильтрация, из-за которой вебхуку понадобился
 * закреплённый IP (TG_WEBHOOK_IP). На проде это выглядит так:
 *
 *   sendPhoto?photo=https://my.linkeon.io/smm-media/...png
 *     → 400 «Bad Request: failed to get HTTP URL content»
 *   тот же файл мультипартом → ok, message_id
 *
 * Снаружи ссылка отдаётся (200, полтора мегабайта), но за 5.4 секунды — фетчер
 * Telegram до origin либо не доходит, либо не дожидается. На тестовом стенде
 * другой хост и другой путь раздачи, поэтому там дефект не проявлялся.
 *
 * Качаем здесь, а не в каждом из двух вызывающих сервисов: и апрув-черновик
 * в личку, и публикация в канал берут один и тот же файл одним и тем же
 * способом — расходиться этим двум местам незачем.
 */

/**
 * Таймаут на скачивание.
 *
 * С сервера MinIO отдаёт за миллисекунды; худшее, что видели живьём, — 5.4 с
 * снаружи через прокси. Пятнадцать секунд — втрое больше худшего наблюдения и
 * при этом достаточно мало, чтобы пять постов одного тика публикации
 * (`publishDue` берёт LIMIT 5) уложились в 75 секунд: это далеко и от самого
 * тика (5 минут), и от порога сторожа зависших `STUCK_PUBLISHING_MINUTES`
 * (10 минут), за которым пост в `publishing` перевзводится и может уехать в
 * канал дважды. Тянуть дольше смысла нет: если хранилище не ответило за
 * пятнадцать секунд, пост подождёт следующего тика, а не будет держать захват.
 */
export const IMAGE_FETCH_TIMEOUT_MS = 15_000;

/**
 * Больше этого Telegram в `sendPhoto` всё равно не примет (лимит 10 МБ), так
 * что качать смысла нет — наши баннеры весят около полутора мегабайт.
 */
export const MAX_IMAGE_BYTES = 10 * 1024 * 1024;

/**
 * @returns байты картинки
 * @throws понятную человеку ошибку: она уходит в `last_error` поста и в личку
 *         владельцу, поэтому в ней и ссылка, и причина.
 */
export async function fetchImageBytes(url: string): Promise<Buffer> {
  if (!/^https?:\/\//i.test(String(url))) {
    throw new Error(`картинка не скачалась (${url}): ссылка должна быть http(s)`);
  }
  try {
    const resp = await axios.get(url, {
      responseType: 'arraybuffer',
      timeout: IMAGE_FETCH_TIMEOUT_MS,
      maxContentLength: MAX_IMAGE_BYTES,
    });
    const buf = Buffer.from(resp.data);
    // Пустой ответ с кодом 200 Telegram отвергает невнятным 400 — лучше
    // назвать причину здесь, чем разбирать её потом по ответу Bot API.
    if (!buf.length) throw new Error('пустой ответ');
    return buf;
  } catch (e: any) {
    throw new Error(`картинка не скачалась (${url}): ${e.message}`);
  }
}
