import { call } from './articles/call';
import { chat } from './articles/chat';
import { renderArticle } from './render';

/**
 * Справка о «Чистом листе» как точке отсчёта (spec 2026-11-17-context-reset).
 * Повод — тикет 7a348750: ИИ-поддержка не связала «пропала история» с
 * «Чистым листом». Сторож держит смысл при слиянии с соседними правками статьи
 * «Чат»: её подпирает предел 5 КБ, и строки о листе легко вырезать молча.
 */
describe('статья «Чат»: «Чистый лист» — точка отсчёта', () => {
  const web = renderArticle(chat, 'ru', 'web');
  const fix = web.slice(web.indexOf('## Если не получается'));

  it('точка — у этого ассистента, а не у всех', () => {
    expect(web).toContain('«Чистый лист» — этот ассистент начинает с нуля');
  });

  it('переписка остаётся, черта в ленте показывает, откуда ассистент помнит', () => {
    expect(web).toContain('Переписка остаётся');
    expect(web).toContain('черта в ленте');
  });

  it('точка действует на всех устройствах', () => {
    expect(web).toContain('На всех устройствах');
  });

  it('в «Если не получается» — «ассистент забыл»: переписка цела, прошлое не вернуть', () => {
    expect(fix).toContain('Ассистент «забыл» разговор — возможно, нажимали «Чистый лист»');
    expect(fix).toContain('переписка цела');
    expect(fix).toContain('только пересказать');
  });

  it('старого описания листа нет', () => {
    expect(web).not.toContain('без прошлой истории');
    expect(web).not.toContain('живёт в этой вкладке');
  });

  it('по перечню тем статью находят на жалобу «ассистент забыл»', () => {
    expect(chat.summary).toContain('чистый лист');
    expect(chat.summary).toContain('«забыл»');
  });
});

describe('статья «Звонок»: «Чистый лист» не стирает память Романа', () => {
  // Решение владельца 17.11: recall (заметки и итоги звонков) точкой не отсекается.
  it('заметки и итоги звонков после «Чистого листа» остаются', () => {
    expect(renderArticle(call, 'ru', 'web')).toContain('«Чистый лист» заметок и итогов звонков не стирает');
  });
});
