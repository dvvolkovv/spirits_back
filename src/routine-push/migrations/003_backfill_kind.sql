-- Опознание пресета «энергия дня» переезжает с русского заголовка на kind,
-- иначе локализация заголовка молча сломает и дедупликацию в
-- ensureEnergyPreset, и выбор текста пуша в deliver.
--
-- Канонический ключ — `daily:<assistantId>`, а НЕ 'energy_of_day'.
-- Причина: app-widget.controller.ts проверяет включённость энерго-рутины
-- запросом по kind = 'daily:14' (фикс от 2026-08-23 — до него гейт смотрел на
-- 'energy_of_day', которого не было ни у кого, и энергия не отдавалась ни разу).
-- Любой другой ключ здесь вернул бы тот баг.
--
-- Нормализуем legacy-строки: до этой миграции RoutineStore.create писал
-- kind='custom' литералом, а более ранние версии — 'daily:14'.
-- Сравнение с русским заголовком корректно ровно один раз: эти строки писались
-- до локализации, других заголовков у них быть не может.
UPDATE routine_pushes
   SET kind = 'daily:' || assistant_id
 WHERE kind <> 'daily:' || assistant_id
   AND assistant_id = '14'
   AND title = 'Энергия дня';
