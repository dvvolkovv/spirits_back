/**
 * Чинит имя файла, приехавшее из multipart-формы.
 *
 * multer 1.x (busboy) декодирует `filename` из Content-Disposition как latin1,
 * а браузеры отправляют его в UTF-8. Кириллица из-за этого приезжает
 * мохабракозяброй: «Копия Договора.pdf» превращается в
 * «ÐÐ¾Ð¿Ð¸Ñ ÐÐ¾Ð³Ð¾Ð²Ð¾ÑÐ°.pdf».
 *
 * Ломается от этого не только вид имени в истории чата: то же имя уходит на
 * релей и попадает в поле зрения модели — ассистент читает бессмыслицу вместо
 * «Копия договора 8.25». В переписке 79088644408 за 11.08 так приехали все семь
 * приложений к апелляционной жалобе.
 *
 * Восстановление ровно обратное искажению: взять байты как latin1 и прочитать
 * их как UTF-8. Проверки вокруг обязательны — иначе честное latin1-имя
 * (немецкое «Straße.pdf» от старого клиента) мы бы этой же операцией сломали.
 */

// Диапазон, куда попадают байты UTF-8, прочитанные как latin1.
const HIGH_LATIN1 = /[-ÿ]/;
const CYRILLIC = /[Ѐ-ӿ]/;
// Признак удачного восстановления: появилось что-то за пределами latin1 —
// кириллица, расширенная латиница, типографика («№», кавычки-ёлочки, тире).
const RECOVERED = /[Ā-￿]/;
const REPLACEMENT_CHAR = '�';

export function decodeMultipartFilename(name: unknown): string {
  if (typeof name !== 'string') return '';
  if (!name) return name;
  // Ничего похожего на искажение — имя чистое (ASCII или уже правильный UTF-8).
  if (!HIGH_LATIN1.test(name)) return name;
  // Кириллица уже на месте — значит имя доехало целым, чинить нечего.
  if (CYRILLIC.test(name)) return name;

  const decoded = Buffer.from(name, 'latin1').toString('utf8');
  // Битая последовательность: декодирование дало U+FFFD. Исходник не хуже.
  if (decoded.includes(REPLACEMENT_CHAR)) return name;
  // Ничего не восстановилось — имя и было настоящим latin1. Не трогаем.
  if (!RECOVERED.test(decoded)) return name;
  return decoded;
}
