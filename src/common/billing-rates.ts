/**
 * Единый курс перевода реальной стоимости в Linkeon-токены.
 *
 * ПРИМЕНЯЕТСЯ ТОЛЬКО К ПУТЯМ, КОТОРЫЕ ЕДЯТ ЁМКОСТЬ ПОДПИСКИ CLAUDE MAX:
 *   - SDK-путь (streamUniversalAgent → r.linkeon.io)
 *   - Маша (claudeCli на проде)
 *   - Telegram-боты (claudeCli на проде)
 *
 * НЕ ПРИМЕНЯТЬ к генерации картинок, видео и озвучки. Это принципиально другая
 * экономика: подписка Claude — фиксированный платёж, и курс здесь нормирует
 * ДЕФИЦИТНУЮ ЁМКОСТЬ, а не возмещает деньги. Imagen, Kling и Yandex Speech мы
 * оплачиваем живыми деньгами по факту, поэтому у них курс должен покрывать
 * реальный отток кэша (сейчас 100_000 и 75_000 — оставлены намеренно).
 * Подставишь сюда 3600 — будешь брать с юзера около 7 ₽ за доллар, который
 * стоил под 80 ₽.
 *
 * Откуда 4500. Пересчёт 2026-08-17 по той же формуле, что и первый курс: цель —
 * выручка 3× стоимости сиденья (~$200/мес ≈ 16 000 ₽), то есть ~48 000 ₽/мес.
 * При цене пакета Professional (1990 ₽ за 1M токенов):
 *
 *   48 000 ₽ / 1990 ₽ × 1M = 24.1M токенов/мес
 *   24.1M / $5 280 ≈ 4 570 → берём 4 500 (округление вниз в пользу юзера)
 *
 * $5 280/мес — свежая нагрузка: 11–16.08 прод сжёг $1 055.85 на 1 323 ходах,
 * то есть $176/сутки и $0.798 за ход. Прежний курс 3 600 считался от $6 400/мес
 * (замер 07.08, ДО правок ёмкости: блокировка субагентов, разрежение
 * синтетик-зонда, снижение порога ротации сессий). Расход после них упал на
 * ~18%, и на том же курсе выручка отставала от цели ровно на эту разницу —
 * поэтому старая редакция этого файла и заканчивалась «пересчитать, вероятно
 * вверх». Пересчитано.
 *
 * Что это меняет для пользователя: средний ход дорожает с ~2 900 до ~3 600
 * токенов (+25%), пакет 1990 ₽ вместо ~348 ходов даёт ~278. Цены и размеры
 * пакетов не тронуты, балансы не мигрированы — курс действует только вперёд.
 * Витрина обещает «≈ N сообщений» из своей константы (spirits_front,
 * config/tokenPackages.ts): её поднимали этой же правкой, иначе обещание
 * пережило бы курс и стало неправдой.
 *
 * До первого единого курса ставки расходились: SDK-путь 1 200, Маша и tg-боты
 * 100 000. Один и тот же доллар расхода списывался по-разному в 83 раза в
 * зависимости от того, к какому ассистенту обратился пользователь.
 */
export const SEAT_TOKENS_PER_USD = Number(process.env.SEAT_TOKENS_PER_USD || 4500);

/**
 * Курс рубля к доллару, по которому мы считаем возмещение живых денег.
 *
 * Вынесен в env, чтобы поправка курса не требовала выката: цифра тут стареет
 * быстрее всего остального в файле.
 */
export const RUB_PER_USD = Number(process.env.RUB_PER_USD || 80);

/**
 * Сколько рублей приносит один токен. Опорный пакет — Professional,
 * 1990 ₽ за 1M: он помечен popular и по нему же считался курс подписки выше.
 *
 * Пакеты разной ёмкости стоят по-разному (от 2.98 ₽ за 1000 у стартового до
 * 1.43 ₽ у максимального), поэтому фактическая наценка у конкретного
 * пользователя гуляет вокруг заданной в зависимости от того, что он купил.
 * Опорную точку надо было выбрать одну, и это середина линейки.
 */
export const RUB_PER_TOKEN = Number(process.env.RUB_PER_TOKEN || 1990 / 1_000_000);

/** Во сколько раз выручка должна покрывать живые деньги. Решение владельца. */
export const CASH_MARKUP = Number(process.env.CASH_MARKUP || 1.5);

/**
 * Курс для путей, которые мы оплачиваем ЖИВЫМИ ДЕНЬГАМИ по счёту вендора.
 *
 * Здесь курс не нормирует дефицитную ёмкость, а возмещает отток кэша с
 * наценкой: сколько заплатили вендору, столько и берём, умножив на CASH_MARKUP.
 *
 * Зачем понадобился отдельно. Голосовой звонок считался по SEAT_TOKENS_PER_USD,
 * то есть по курсу подписки Claude, — при том что Realtime оплачивается OpenAI
 * живыми деньгами. Встреча 07.09.2026 на 69 минут: счёт OpenAI 4.13 доллара,
 * списано 18 604 токена, это 26–55 ₽ в зависимости от пакета против ~330 ₽
 * расхода. Предупреждение об этом стояло в шапке файла с самого начала и всё
 * равно не сработало — потому что курс подписки был единственным экспортом, и
 * взять было больше нечего.
 *
 * При 80 ₽ за доллар и опорном пакете выходит около 60 300 токенов за доллар.
 * Прежние 100 000 и 75 000 у картинок, видео и озвучки — из тех же соображений,
 * но заданы числом и подразумевают наценку около 2.5× и 1.9×. Свести их сюда
 * стоит, но это отдельное решение о цене: трогать их этой правкой не стал.
 */
export const CASH_TOKENS_PER_USD = Math.round((CASH_MARKUP * RUB_PER_USD) / RUB_PER_TOKEN);
