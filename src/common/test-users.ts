/**
 * Аккаунты, которые не должны попадать в продуктовые и качественные метрики.
 *
 * Список был локальной константой в funnel.service, и это работало ровно до
 * появления второго потребителя: 15.08.2026 алерт «всплеск англоязычных
 * ответов» целиком состоял из учёток, заведённых и удалённых в тот же день при
 * отладке удаления аккаунта. Метрика качества про них не знала, потому что
 * исключение жило только в воронке.
 *
 * Держим одной копией, чтобы третий потребитель не завёл третий список.
 */
export const TEST_USERS = ['70000000000', '79030169187', '79169403771', '79656445804'];

/** Переопределение через env: FUNNEL_EXCLUDED_USERS=79001112233,79004445566 */
export function excludedUsers(): string[] {
  const fromEnv = (process.env.FUNNEL_EXCLUDED_USERS || '')
    .split(',').map((s) => s.trim()).filter(Boolean);
  return fromEnv.length > 0 ? fromEnv : TEST_USERS;
}

/**
 * Регулярка синтетических номеров 790300xxxxx (нагрузочные прогоны).
 * Живёт рядом со списком: оба нужны одному и тому же фильтру.
 */
export const TEST_USER_PATTERN = '^790300[0-9]{5}$';
