import { supportReplyText } from './support-reply-text';

const text = (t: string) => ({ type: 'text', text: t });
const tool = (name = 'mcp__support-tools__escalate_to_owner') => ({ type: 'tool_use', name, input: {} });

describe('текст ответа ИИ-поддержки', () => {
  // Прогон 01.11.2026: «…подробный ответ.Твой вопрос передан команде» —
  // реплика до вызова инструмента и после него склеились без пробела.
  it('реплика до вызова инструмента не попадает к человеку', () => {
    expect(supportReplyText([
      [text('Я передам твой вопрос в команду, чтобы ты получил подробный ответ.')],
      [tool()],
      [text('Твой вопрос передан команде.')],
    ])).toBe('Твой вопрос передан команде.');
  });

  it('текст и вызов в одном сообщении — тоже реплика до вызова', () => {
    expect(supportReplyText([
      [text('Сейчас посмотрю справку.'), tool('mcp__support-tools__linkeon_help')],
      [text('Ключ меняется через ассистента.')],
    ])).toBe('Ключ меняется через ассистента.');
  });

  it('после последнего вызова модель промолчала — берём последний текст перед ним', () => {
    expect(supportReplyText([
      [text('Готовый ответ.'), tool()],
      [],
    ])).toBe('Готовый ответ.');
  });

  it('без инструментов — весь текст, абзацами', () => {
    expect(supportReplyText([[text('Первый абзац.')], [text('Второй абзац.')]]))
      .toBe('Первый абзац.\n\nВторой абзац.');
  });

  it('пусто — пустая строка, заглушку подставляет вызывающий', () => {
    expect(supportReplyText([[tool()], [text('   ')]])).toBe('');
    expect(supportReplyText([])).toBe('');
  });
});
