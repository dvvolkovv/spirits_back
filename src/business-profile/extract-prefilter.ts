/**
 * Локальный фильтр перед LLM-вызовом извлечения бизнес-фактов.
 *
 * Отдельный от tasks/extract-prefilter намеренно: там маркеры — глаголы
 * действия («сделат», «запуст», «дедлайн»), здесь — обороты, которыми
 * сообщают факты о деле. Один фильтр на двоих пришлось бы размыть, и он
 * потерял бы главное свойство: дёшево срезать большинство ходов.
 *
 * `\b` не работает с кириллицей в JS (word boundary держится на \w =
 * ASCII-буквы/цифры/подчёркивание, кириллица в него не входит — значит
 * по обе стороны границы после кириллической буквы всегда «не-\w», и
 * `\b` там попросту не срабатывает), поэтому здесь везде substring-match,
 * как и в фильтре задач.
 *
 * Исключение — «ип»: как голая подстрока она попадает в «в принципе»,
 * «типичная» и т.п., а это очень частые обороты в разговоре — заметный
 * поток пустых LLM-вызовов. Для неё границу слова эмулируем вручную:
 * по обе стороны либо начало/конец строки, либо не-буква/не-цифра.
 * Строку предварительно приводим к нижнему регистру, чтобы не зависеть
 * от того, как /i обрабатывает кириллицу в классах символов.
 */
const BUSINESS_MARKERS =
  /(ооо|самозанят|усн|нпд|осно|патент|ндс|налог|оборот|выручк|доход|прибыл|маржа|клиент|заказчик|покупател|сотрудник|мастер|команд|нас (двое|трое|четверо|пятеро)|работник|штат|точк|филиал|салон|студи|магазин|бизнес|компани|фирм|производств|услуг|подрядчик|поставщик|аренд|касс|счёт|счет|тысяч|миллион|млн|руб|₽)/i;

const IP_WORD_MARKER = /(^|[^а-яё0-9a-z])ип([^а-яё0-9a-z]|$)/;

const PLEASANTRY =
  /^\s*(привет|здравств|спасибо|спасиб|пожалуйста|ок|окей|ага|да|нет|good|hi|hello|thanks|спс|ясно|понятно|круто|супер|👍|❤️)[!.,\s]*$/i;

export function shouldSkipBusinessExtraction(message: string): boolean {
  const trimmed = (message || '').trim();
  if (!trimmed) return true;
  if (PLEASANTRY.test(trimmed)) return true;
  // Без бизнес-маркера извлекать нечего в любой реплике, короткой или длинной.
  if (BUSINESS_MARKERS.test(trimmed)) return false;
  if (IP_WORD_MARKER.test(trimmed.toLowerCase())) return false;
  return true;
}
