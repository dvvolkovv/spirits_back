const withLine = (id: string, text: string): ShortScript => {
  const s = script();
  s.lines = s.lines.map((l) => (l.id === id ? { ...l, text } : l));
  if (id === 'h') s.hook = text;
  return s;
};

/** Сообщения текстовых правил (раскадровка и длина — без номера правила). */
const ruleMessages = (out: string[]) => out.filter((m) => /^правил[оа] /.test(m));

/** «Находка (место)» из сообщений одного правила: «правило 6: … — «бесплатно» (подпись telegram)» → «бесплатно» (подпись telegram). */
const findings = (out: string[], rule: string) =>
  out.filter((m) => m.startsWith(`${rule}:`)).map((m) => m.slice(m.lastIndexOf(' — «') + 3));

