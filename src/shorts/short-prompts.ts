/**
 * Данные в сообщении модели — между метками. Метки внутри самого текста
 * вырезаются: иначе ответ ассистента закрыл бы свой блок и дописал «инструкцию».
 */
function fenced(label: string, text: string): string {
  const body = String(text ?? '').replace(/<{3,}|>{3,}/g, '').trim();
  return `<<<${label}\n${body}\n${label}>>>`;
}

/** Переводы строк — в пробел: «\n[3]» внутри абзаца подделал бы нумерацию, многострочный вопрос — пункт списка. */
const oneLine = (text: string): string => String(text ?? '').replace(/\s+/g, ' ').trim();

