/** Сценка в сообщении модели — теми же полями, что она пишет сама. */
export function describeSkit(s: Skit): string {
  return [
    `cast: ${s.cast.map((c) => `${c.hero} — ${c.role}`).join(', ')}`,
    `setting: ${oneLine(s.setting)}`,
    `opening: ${oneLine(s.opening)}`,
    `action: ${oneLine(s.action)}`,
    ...s.lines.map((l, i) => `реплика ${i + 1}, ${l.hero}${l.box !== undefined && l.box !== null ? ` [${l.box}]` : ''}: ${oneLine(l.text)}`),
  ].join('\n');
}

const RECENT_SKIT_CHARS = 300;

/** Сценки прошлого ролика одной строкой — режиссёру, чтобы не повторял места и шутки: и конфликта, и развязки. */
export function recentSkitLine(conflict: Skit, punchline?: Skit | null): string {
  const tail = punchline?.action ? `; развязка: ${punchline.action}` : '';
  return Array.from(oneLine(`${conflict.setting} — ${conflict.action}${tail}`)).slice(0, RECENT_SKIT_CHARS).join('');
}

export interface DirectorInput {
  rubric: ShortRubric;
  angle: ShortAngle;
  topicHint: string | null;
  fixedAssistant: AgentLite | null;
  assistants: AgentLite[];
  recentQuestions: string[];
  ownerNote: string | null;
  previousQuestion: string | null;
  /**
   * Ролик со сценками: сценки последних роликов (recentSkitLine); сценка 1
   * прошлой сцены этого ролика («Переснять», просьба сценариста) — придумать
   * другую; отвергнутый вариант этого круга — его вопрос оставить, сценку
   * исправить по нарушениям.
   */
  skit?: { recent: string[]; replaced: Skit | null; rejected: { question: string; skit: Skit } | null; violations: string[] };
}

export function buildDirectorMessage(i: DirectorInput): string {
  const parts = [`Рубрика: ${RUBRIC_TITLES[i.rubric]}. Подача: ${i.angle} — ${ANGLE_TITLES[i.angle]}.`];
  if (i.rubric === 'case') {
    parts.push(
      'Реальная история владельца: задай её ассистенту заново вопросом от первого лица, без имён, названий организаций и сумм.',
    );
  }
  parts.push(i.topicHint ? `Тема: ${i.topicHint}` : 'Тему выбери сам — из профиля ассистента.');
  // Здоровье — только в спокойной подаче: правило 12 смотрит на имя ассистента,
  // и ролик с Полиной в «разносе» не исправит никакая переписка.
  const assistants = PROVOCATIVE_ANGLES.includes(i.angle) ? i.assistants.filter((a) => !isHealthAssistant(a.name)) : i.assistants;
  parts.push(
    i.fixedAssistant
      ? `Ассистент задан: ${i.fixedAssistant.id} — ${i.fixedAssistant.name}: ${i.fixedAssistant.description}`
      : `Ассистенты (id — имя: профиль):\n${assistants.map((a) => `${a.id} — ${a.name}: ${a.description}`).join('\n')}`,
  );
  if (i.previousQuestion) parts.push(`Прошлая сцена этого ролика — придумай другую:\n${fenced('ВОПРОС', i.previousQuestion)}`);
  if (i.ownerNote) parts.push(`Замечания — учти:\n${fenced('ЗАМЕЧАНИЯ', i.ownerNote)}`);
  if (i.recentQuestions.length) {
    parts.push(`Уже было (не повторяй):\n${fenced('УЖЕ БЫЛО', i.recentQuestions.map((q) => `- ${oneLine(q)}`).join('\n'))}`);
  }
  if (i.skit?.recent.length) {
    parts.push(`Сценки последних роликов (не повторяй места и шутки):\n${fenced('СЦЕНКИ', i.skit.recent.map((s) => `- ${oneLine(s)}`).join('\n'))}`);
  }
  if (i.skit?.replaced) parts.push(`Сценка 1 прошлой сцены — придумай другую:\n${fenced('ПРОШЛАЯ СЦЕНКА 1', describeSkit(i.skit.replaced))}`);
  if (i.skit?.rejected) {
    parts.push(
      `Твой прошлый вариант — ассистента и вопрос оставь, исправь только сценку 1:\n${fenced('ВОПРОС', i.skit.rejected.question)}\n${fenced('СЦЕНКА 1', describeSkit(i.skit.rejected.skit))}`,
    );
  }
  if (i.skit?.violations.length) parts.push(`Сценка нарушила правила — исправь:\n${i.skit.violations.map((v) => `- ${v}`).join('\n')}`);
  return parts.join('\n\n');
}

