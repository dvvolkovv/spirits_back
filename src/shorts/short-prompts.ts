export interface WriterInput {
  rubric: ShortRubric;
  angle: ShortAngle;
  assistantName: string;
  assistantDescription: string;
  question: string;
  paragraphs: ShortParagraph[];
  ownerNote: string | null;
  writerFeedback: string | null;
  previousScript: ShortScript | null;
  /** Подписи отвергнутого круга; у сценария из базы их нет — там они уже с хвостом ссылок. */
  previousCaptions?: WriterCaptions | null;
  violations: string[];
  /**
   * Ролик со сценками: конфликт, который открывает ролик; принятая развязка из
   * прошлого сценария (её клип мог быть уже снят) и отвергнутая в этом круге.
   */
  skit?: { conflict: Skit; acceptedPunchline: Skit | null; rejectedPunchline: Skit | null };
}

/**
 * Прошлый вариант — теми метками, что в нарушениях и отзыве студии:
 * «реплика a1», «подпись telegram», «youtube.title». Финал пишет код — его нет.
 */
function previousVariant(s: ShortScript, c: WriterCaptions | null): string {
  // У сценок реплики зацепки нет — она надпись, и нарушения зовут её «зацепка».
  const hookId = s.lines.find((l) => l.scene === 'hook')?.id ?? 'зацепка';
  const support = s.hookBox !== undefined && s.hookBox !== null ? `hookBox ${s.hookBox}` : 'без опоры';
  const out = [`${hookId}: ${s.hook} (${support})`];
  for (const l of s.lines) {
    if (l.scene === 'question') out.push(`${l.id}: ${l.text}`);
    if (l.scene === 'answer') out.push(`${l.id} [${l.box ?? '—'}]: ${l.text}`);
  }
  if (c) {
    out.push(
      `подпись telegram: ${c.telegram}`,
      `подпись vk: ${c.vk}`,
      `youtube.title: ${c.youtube.title}`,
      `youtube.description: ${c.youtube.description}`,
      `youtube.tags: ${(c.youtube.tags ?? []).join(', ')}`,
    );
  }
  return `Прошлый вариант:\n${out.join('\n')}`;
}

export function buildWriterMessage(i: WriterInput): string {
  const parts = [
    `Рубрика: ${RUBRIC_TITLES[i.rubric]}. Подача: ${i.angle} — ${ANGLE_TITLES[i.angle]}.`,
    `Ассистент: ${i.assistantName} — ${i.assistantDescription}`,
    `Спросили:\n${fenced('ВОПРОС', i.question)}`,
    `Ответ по абзацам:\n${fenced('ОТВЕТ АССИСТЕНТА', i.paragraphs.map((p) => `[${p.n}] ${oneLine(p.text)}`).join('\n'))}`,
  ];
  if (i.skit) parts.push(`Сценка 1 (конфликт) — открывает ролик:\n${fenced('СЦЕНКА 1', describeSkit(i.skit.conflict))}`);
  if (i.previousScript) parts.push(previousVariant(i.previousScript, i.previousCaptions ?? null));
  if (i.skit?.acceptedPunchline) {
    parts.push(
      `Принятая сценка 2 (развязка) — не пиши punchline, если замечания и нарушения её не касаются:\n${fenced('ПРИНЯТАЯ СЦЕНКА 2', describeSkit(i.skit.acceptedPunchline))}`,
    );
  }
  if (i.skit?.rejectedPunchline) parts.push(`Прошлый вариант сценки 2:\n${fenced('СЦЕНКА 2', describeSkit(i.skit.rejectedPunchline))}`);
  // Не «владельца»: здесь и прошлые замечания, и просьбы сценариста, которые новая сцена уже учла.
  if (i.ownerNote) parts.push(`Замечания (в том числе прошлые, уже учтённые сценой):\n${fenced('ЗАМЕЧАНИЯ', i.ownerNote)}`);
  if (i.writerFeedback) parts.push(`Студия: ${i.writerFeedback}`);
  if (i.violations.length) parts.push(`Прошлый вариант нарушил правила — исправь:\n${i.violations.map((v) => `- ${v}`).join('\n')}`);
  return parts.join('\n\n');
}
