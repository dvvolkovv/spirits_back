-- Выключатели интеграций.
--
-- Зачем таблица, а не переменные окружения: включение экспериментальной
-- интеграции — операционное решение, а не выкатка. Из .env его не видно, оно
-- требует доступа к серверу и рестарта API, и о том, кто и когда включил,
-- не остаётся следа.
--
-- `key` — строка вида `meeting:meet`. Пространство имён через двоеточие,
-- потому что интеграции будут не только встречами.
--
-- ОТСУТСТВИЕ СТРОКИ ЗНАЧИТ «ВЫКЛЮЧЕНО». Это главное свойство таблицы: новая
-- интеграция, приехавшая с выкаткой кода, не начинает работать сама.
CREATE TABLE IF NOT EXISTS integration_flags (
  key        TEXT PRIMARY KEY,
  enabled    BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Кто переключил. Строка, а не FK: админ может быть заведён и удалён, а
  -- запись о переключении обязана пережить его.
  updated_by TEXT
);

-- Засеваем ТЕКУЩИМ поведением, а не желаемым: миграция не должна ничего
-- включить и ничего выключить.
--
--   talerid — уже работает на проде, карточка показывается всем;
--   meet, zoom — на проде выключены отсутствием ключей Attendee;
--   teams — моста для него у нас ещё нет.
--
-- ON CONFLICT DO NOTHING: повторный прогон не сбрасывает то, что переключили
-- руками в админке.
INSERT INTO integration_flags (key, enabled) VALUES
  ('meeting:talerid', TRUE),
  ('meeting:meet',    FALSE),
  ('meeting:zoom',    FALSE),
  ('meeting:teams',   FALSE)
ON CONFLICT (key) DO NOTHING;
