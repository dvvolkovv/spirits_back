-- 007_retire_smm_producer.sql
-- Убирает Юлию (smm_producer, id 15) из продукта.
--
-- РЕШЕНИЕ ВЛАДЕЛЬЦА 06.09.2026.
--
-- ЧТО ЭТО ДАЁТ. `/webhook/agents` (AgentsService.getAgents) фильтрует по
-- `is_active`, поэтому снятия флага достаточно: ассистент пропадает с экрана
-- выбора и из настроек голосов. Секции на фронте условные
-- (`visibleAssistants.some(...)` в AssistantSelection.tsx) — пустого заголовка
-- «🎬 SMM-продюсер» не останется.
--
-- ПОЧЕМУ ФЛАГ, А НЕ DELETE. На строку 15 ссылается история: 1770 сообщений в
-- custom_chat_history с session_id '%_15', плюс agent_id в
-- token_consumption_tasks и 43 кампании в smm_campaign. Удаление строки
-- обнулило бы принадлежность этой истории и сделало бы возврат невозможным;
-- флаг снимается и ставится обратно одним UPDATE.
--
-- КОГО ЗАДЕВАЕТ. Практически никого: из 1770 сообщений 1464 принадлежат
-- тестовому аккаунту 70000000000 и 130 — админскому 79030169187. Последняя
-- живая переписка настоящего пользователя — 03.08.2026. У одного профиля
-- (79097990777) она стоит в preferred_agent, но он не писал ей с 28.06.2026;
-- при следующем заходе он увидит экран выбора ассистента.
--
-- ЧТО ОСТАЁТСЯ В КОДЕ НАМЕРЕННО. SMM-раздел целиком не сносится (владелец
-- выбрал убрать ассистента, а не раздел): smm-модуль, воркер рендера,
-- ScenarioEditModal и таблицы smm_* остаются на месте и просто перестают быть
-- достижимыми через чат. Вернуть Юлию — это `SET is_active = true`.
--
-- E2E-тест tests/playwright/julia-creator.spec.js удалён этой же правкой: он
-- ищет Юлю на экране выбора и без неё краснеет по существу, а не по флаку.

UPDATE agents SET is_active = false WHERE id = 15;
