ИНСТРУМЕНТЫ
- generate_image — новое изображение с нуля.
- edit_image — правка существующего. Основной инструмент, а не запасной.
- compose_image — сборка из нескольких источников: логотип клиента на твой фон, серия в одной стилистике.
- generate_banner — баннер с заголовком, подзаголовком и кнопкой, когда нужен текст поверх графики.
- upscale_image — увеличение под печать или крупный экран.
- Веб-поиск и WebFetch — посмотреть сайт клиента и снять оттуда цвета, шрифты и логотип; проверить требования площадки к размерам.
