/**
 * Как ассистент подписан во встрече: «Роман · ассистент Дмитрия».
 *
 * Эту строку видят живые люди в двух местах сразу — в списке участников
 * комнаты и как автора сообщений в её чате. Собирается она ЗДЕСЬ и один раз,
 * а дальше уезжает воркеру готовой: раньше её складывали по одному и тому же
 * шаблону в двух местах (бэкенд — для токена комнаты Taler ID, воркер — для
 * updateName и чата), и разъехаться они могли молча.
 *
 * Падеж. Владелец 14.09.2026 на живой встрече прочитал «Роман · ассистент
 * Дмитрий» — то есть подпись сообщала, что ассистента зовут Дмитрий. Имя
 * приходит из профиля в именительном, а шаблону нужен родительный; заглушка
 * «пользователя» в родительном и была, отчего ошибку не замечали.
 */

/** Заглушка вместо имени. Уже в родительном падеже — склонять её нельзя. */
const FALLBACK = 'пользователя';

/** После них в родительном пишется «и», а не «ы»: Ольга → Ольги, Саша → Саши. */
const HUSHING_AND_VELAR = 'гкхжчшщ';

/**
 * Родительный падеж имени владельца.
 *
 * Правила покрывают русские личные имена, и только их. Всё, что на них не
 * похоже, возвращается как есть: исказить имя человека хуже, чем оставить его
 * в именительном.
 *
 * Сознательные пропуски:
 *   • имя из нескольких слов — фамилии склоняются по своим правилам, и
 *     женское «Волкова → Волковой» из правил для имён не выводится;
 *   • латиница и любые другие алфавиты — склонять нечем;
 *   • женские имена на согласную и «Любовь» — определить род по написанию
 *     нельзя, и «Любовь» станет «Любовя». Цена ошибки тут ниже, чем цена
 *     отказа склонять «Игоря» и «Дмитрия», которые встречаются на порядок чаще.
 */
export function ownerGenitive(raw?: string | null): string {
  const name = (raw || '').trim();
  if (!name) return FALLBACK;
  if (name === FALLBACK) return FALLBACK;
  // Одно слово и только кириллица — иначе не трогаем.
  if (!/^[а-яё]+$/i.test(name)) return name;

  const last = name.slice(-1).toLowerCase();
  const body = name.slice(0, -1);

  if (last === 'й' || last === 'ь') return `${body}я`;
  if (last === 'я') return `${body}и`;
  if (last === 'а') {
    const prev = body.slice(-1).toLowerCase();
    return `${body}${HUSHING_AND_VELAR.includes(prev) ? 'и' : 'ы'}`;
  }
  // Прочие гласные (Нино, Дарко, Дэни) в русском не склоняются.
  if ('еёиоуыэю'.includes(last)) return name;
  return `${name}а`;
}

/** Подпись ассистента для списка участников и чата комнаты. */
export function assistantSignature(agentName: string, ownerName?: string | null): string {
  return `${agentName} · ассистент ${ownerGenitive(ownerName)}`;
}
