-- Голос ассистента в OpenAI Realtime.
--
-- NULL — берётся значение по умолчанию из окружения (сейчас cedar). Заводится
-- под встречи: в звонке ведущий всегда один и голос у него общий, а на встречу
-- заходит тот ассистент, в чей чат кинули ссылку, и звучать все одинаково не
-- должны.
--
-- Голосов у Realtime десять на двадцать с лишним ассистентов, так что часть
-- всё равно совпадёт. Подбирать НА СЛУХ: в voice-host/src/agent.ts на этом
-- месте стоит предупреждение — там дважды выбрали голос по описанию и дважды
-- промахнулись мимо пола.
ALTER TABLE agents ADD COLUMN IF NOT EXISTS realtime_voice TEXT;
