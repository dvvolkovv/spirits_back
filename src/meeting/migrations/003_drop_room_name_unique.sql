-- 003_drop_room_name_unique.sql
-- Снимаем уникальность voice_calls.room_name.
--
-- Для звонка она была безобидной: там комната одноразовая, `voice_<uuid>`,
-- и повториться не могла в принципе. Для встречи room_name — это `room_<КОД>`
-- постоянной комнаты, и второй вход ассистента в ту же комнату упирался в
-- constraint с ошибкой 500.
--
-- Уникальность здесь ничего не защищала: ни один запрос не делает upsert по
-- room_name, поиск идёт по id, а очистка зависших — по статусу и провайдеру.
-- Заходить в одну комнату по очереди — нормальный сценарий: сегодня Роман,
-- завтра Алексей, послезавтра снова Роман.
--
-- Поймано на живой встрече 27.08.2026, первым же повторным входом.
ALTER TABLE voice_calls DROP CONSTRAINT IF EXISTS voice_calls_room_name_key;
