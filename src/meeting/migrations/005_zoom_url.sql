-- Полный адрес входа во внешнюю встречу.
--
-- Понадобился с Zoom: у Meet адрес однозначно собирается из кода
-- (`https://meet.google.com/<код>`), а у Zoom в ссылке ещё хост аккаунта
-- (`us04web.zoom.us`, `<компания>.zoom.us`) и хеш пароля. Складывать это в
-- external_room, где у остальных провайдеров лежит короткий код, значило бы
-- завести колонку с двумя разными смыслами — и однажды перепутать их.
--
-- NULL для всех, кроме Zoom: там, где адрес выводится из кода, он не нужен.
ALTER TABLE voice_calls ADD COLUMN IF NOT EXISTS external_url TEXT;
