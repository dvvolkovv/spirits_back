import {
  CanActivate,
  ExecutionContext,
  Injectable,
  Logger,
  UnauthorizedException,
} from '@nestjs/common';
import * as crypto from 'crypto';
import { PgService } from '../common/services/pg.service';

/**
 * `openssl rand -hex 32` даёт 64 символа; граница вдвое ниже — чтобы отсечь
 * заглушки вроде `test` или `changeme`, но не спорить с тем, кто принесёт свой
 * длинный токен не в hex. За гвардом лежит claimJob, отдающий расшифрованные
 * секреты продуктов, так что молчаливый слабый токен здесь дороже, чем
 * гибкость формата.
 *
 * ПРОВЕРЯЕТСЯ ТЕПЕРЬ ПРЕДЪЯВЛЕННЫЙ токен, а не ожидаемый: ожидаемого больше
 * нет нигде — сверка уехала в реестр машин. Побочно это ещё и отбой до базы:
 * `Bearer test` от интернет-сканера не доходит до запроса и не оставляет
 * строки в журнале (см. отказ по неизвестному токену ниже — вот ТОТ пишется).
 */
const MIN_TOKEN_LEN = 32;

/**
 * Печатный ASCII без пробела. Не про стойкость, а про то, что иначе конфиг
 * недостижим в принципе: значения HTTP-заголовков латинские (latin1), и
 * неASCII-токен нашему же агенту не отправить — `http.request` бросает
 * ERR_INVALID_CHAR ещё до запроса. Досланный сырым сокетом, он вернётся
 * latin1-строкой и после utf8-перекодировки разойдётся с записанным в реестр.
 * Пробел отсечён заодно: хвостовой пробел в конфиге агента иначе давал бы
 * вечный 401 без единой подсказки.
 */
const TOKEN_SHAPE = /^[\x21-\x7e]+$/;

/**
 * Запрос, прошедший HostGuard. Контракт гварда с контроллером: метка машины
 * лежит НА ЗАПРОСЕ, потому что выведена из предъявленного токена. Взятая из
 * тела, она была бы заявлением агента о себе — то есть правом развернуть чужой
 * продукт у себя.
 */
export interface HostAgentRequest {
  hostId: string;
}

/**
 * Агент машины продуктов представляет МАШИНУ, а не продукт и не пользователя,
 * поэтому ни JwtGuard, ни RunnerGuard не подходят.
 *
 * ## ЧТО ЗДЕСЬ ПРОИСХОДИТ (кусок 4а, задача 2)
 *
 * Гвард не сверяет токен с одним значением — он ПРЕВРАЩАЕТ токен в метку
 * машины. Пока машина была одна, токен лежал в `PRODUCT_HOST_TOKEN`, и вопрос
 * «какая машина спросила» не стоял: ответ был один. С двумя машинами общий
 * токен означает, что задание достаётся тому, кто первым спросил, — то есть
 * продукт клиента разворачивается у владельца, на машине, где его каталога
 * нет. Метка машины И ЕСТЬ её токен, и выводит её отсюда только этот код.
 *
 * ## РЕЕСТР — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВДЫ
 *
 * `PRODUCT_HOST_TOKEN` остаётся ровно одним: тем, из чего миграция 005 заводит
 * машину `own` при первом накате. Гвард его не читает вовсе, и после выката
 * переменная из окружения бэкенда удаляется — оставленная, она была бы вторым
 * способом пройти гвард, расходящимся с реестром молча. Поворот токена машины
 * делается правкой реестра (сторож — сценарий 42а интеграционного сьюта).
 *
 * ## ПОЧЕМУ СВЕРКИ ПОСТОЯННОГО ВРЕМЕНИ ЗДЕСЬ БОЛЬШЕ НЕТ
 *
 * Не потому, что «сравнивает индекс, а не мы» — индекс сравнивает обычным
 * memcmp и по времени тоже наблюдаем. Причина сильнее: сравнивается sha256
 * ВЫСОКОЭНТРОПИЙНОГО токена, а не сам токен. Идеальный оракул по времени выдал
 * бы злоумышленнику префикс ХЕША — ценность нулевая: чтобы предъявить токен,
 * нужен прообраз. Подобрать хеш побайтно он тоже не может: наружу он подаёт
 * токен, а не хеш, и лавинный эффект sha256 лишает его возможности менять
 * сравниваемое значение по байту. Ровно это рассуждение уже стоит в проде у
 * RunnerGuard (001, `runner_token_hash`).
 *
 * Обратная сторона названа честно: короткий/кривой токен отбивается ДО запроса
 * к базе, и такой ответ приходит заметно быстрее. Утекает «форма токена
 * подошла» — то, что и так написано в .env.example и в инсталляторе агента.
 *
 * ## ЗАПРОС НА КАЖДЫЙ ОПРОС — И ПОЧЕМУ ОН НЕ КЕШИРУЕТСЯ
 *
 * Агент опрашивает раз в 3 секунды, то есть 0.33 запроса в секунду НА МАШИНУ.
 * Замерено 21.09.2026 на тестовой ноде (PostgreSQL 16.14, юникс-сокет, реестр
 * из 2 строк, по 2000 повторов) ВМЕСТЕ С ROUND TRIP через node-pg:
 *
 *   попадание  медиана 0.201 мс, p95 0.362 мс, p99 0.665 мс
 *   промах     медиана 0.154 мс, p95 0.301 мс, p99 0.533 мс
 *
 * В самой базе — 0.063 мс и три страницы буфера: `Index Scan using
 * product_hosts_agent_token_hash_key` плюс агрегат по двум строкам. То есть
 * почти всё время здесь — это дорога до Postgres, а не работа. Рядом на том же
 * маршруте стоят UPDATE отметки о жизни и claimJob с `FOR UPDATE SKIP LOCKED`;
 * этот SELECT самый дешёвый из трёх.
 *
 * Кеш здесь не экономит ничего и ломает существенное: пока живёт запись,
 * отозванный токен продолжает пускать, а только что заведённая машина
 * получает 401 — то есть ровно тот молчаливый отказ, ради выявления которого
 * написан весь этот кусок. Плюс кеш, ключом которого служит присланное
 * значение, — это неограниченная карта под управлением того, кто стучится.
 *
 * ## РАЗБОР ЗАГОЛОВКА
 *
 * Слово-в-слово повторяет RunnerGuard: два гварда с разным пониманием
 * `Bearer ` в одном модуле — готовый источник «на одной машине работает, на
 * другой нет».
 */
@Injectable()
export class HostGuard implements CanActivate {
  private readonly log = new Logger(HostGuard.name);

  constructor(private readonly pg: PgService) {}

  async canActivate(context: ExecutionContext): Promise<boolean> {
    const req = context.switchToHttp().getRequest();

    // МЕТКА СНИМАЕТСЯ ДО ЛЮБЫХ ПРОВЕРОК, а не только не ставится при отказе.
    // По HTTP `req.hostId` подделать нельзя — тело приезжает в `req.body`,
    // заголовки в `req.headers`, и ни то, ни другое на сам запрос не
    // раскладывается. Но инвариант этот живёт в Express, а не в этом
    // репозитории, и стоит одной строки: после гварда на запросе лежит либо
    // метка, выведенная из токена, либо ничего.
    delete req.hostId;

    // Заголовок берём только строкой. `String(...)` принял бы одноэлементный
    // массив (`String(['Bearer x']) === 'Bearer x'`), и безопасность держалась
    // бы на том, что Node отбрасывает дубликаты Authorization — детали ядра вне
    // этого репозитория, которую здесь ничто не проверяет.
    const header = req.headers['authorization'];
    const raw = typeof header === 'string' ? header : '';
    const token = raw.startsWith('Bearer ') ? raw.slice(7) : '';
    if (!token) throw new UnauthorizedException('Missing host token');
    if (token.length < MIN_TOKEN_LEN || !TOKEN_SHAPE.test(token)) {
      throw new UnauthorizedException('Bad host token');
    }

    const hash = crypto.createHash('sha256').update(token).digest('hex');

    // ОДИН ЗАПРОС, ДВА ОТВЕТА. Второй подзапрос отличает «токен чужой» от «в
    // реестре вообще пусто», и различие не косметическое: пустой реестр —
    // состояние ДОСТИЖИМОЕ (005 при незаполненном PRODUCT_HOST_TOKEN на чистой
    // базе нарочно ничего не заводит), и без отдельного сообщения оно выглядит
    // как «у агента не тот токен». Оператор ушёл бы чинить конфиг машины,
    // который в порядке. Счётчик по таблице в две строки стоит нисколько, а
    // round trip остаётся один.
    //
    // Скалярный подзапрос, а не `WHERE ... LIMIT 1`, намеренно: при двух
    // строках с одним хешем он падает `more than one row returned by a
    // subquery`, то есть громко. Уникальность хеша держит база (005), но если
    // её когда-нибудь снимут, отказ лучше молчаливой выдачи произвольной
    // машины, то есть чужих заданий.
    const r = await this.pg.query(
      `SELECT (SELECT id FROM product_hosts WHERE agent_token_hash = $1) AS host_id,
              (SELECT count(*) FROM product_hosts) AS total`,
      [hash],
    );
    const row = r.rows[0];
    const hostId: string | null = row?.host_id ?? null;

    if (!hostId) {
      if (Number(row?.total ?? 0) === 0) {
        this.log.error(
          'реестр машин пуст: ни один агент не получит задания. ' +
            'Машина заводится миграцией 005 из PRODUCT_HOST_TOKEN либо строкой в product_hosts',
        );
        throw new UnauthorizedException('host registry not configured');
      }
      // СТРОКА В ЖУРНАЛЕ ОБЯЗАТЕЛЬНА. Снаружи агент с чужим токеном выглядит
      // полностью исправным: юнит active, перезапусков нет, ошибок нет — он
      // просто никогда не получает работы (измерено в куске 2, сценарий 21д).
      // Это единственное место, где такой агент вообще виден.
      //
      // Печатается НАЧАЛО ХЕША, а не токен: по нему отличимы друг от друга
      // повторы одного агента и перебор разными токенами, и по нему же
      // оператор проверяет реестр запросом. Сам токен в журнал не уезжает —
      // логи читает больше людей, чем конфиги машин.
      //
      // Шумит: агент опрашивает раз в 3 секунды, то есть 20 строк в минуту,
      // пока конфиг не починят. Это принято сознательно — глушилка по времени
      // была бы местом, где строка может пропасть, а пропасть ей нельзя. До
      // этой ветки доходит только тот, кто предъявил ПРАВДОПОДОБНЫЙ токен:
      // сканеры с `Bearer test` отбиваются выше и журнал не трогают.
      this.log.warn(
        `неизвестный токен агента машины (sha256 ${hash.slice(0, 8)}…) — ` +
          'этот агент не получит ни одного задания',
      );
      throw new UnauthorizedException('Unknown host token');
    }

    // Кладётся ОДНА МЕТКА, а не вся строка машины — в отличие от RunnerGuard,
    // который кладёт на запрос продукт целиком. Разница в том, что лежит
    // дальше по маршруту: ответ опроса — это контракт с другим репозиторием, и
    // строка реестра, оказавшись на запросе, однажды уедет в него целиком
    // вместе с хешем токена. Выдаче заданий нужна ровно метка.
    req.hostId = hostId;
    return true;
  }
}
