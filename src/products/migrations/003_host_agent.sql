-- 003_host_agent.sql
-- Отметка о том, что агент машины продуктов выходил на связь.
-- Дизайн: spirits_front/docs/superpowers/specs/2026-09-07-linkeon-products-hosting-design.md

-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ РЕЕСТР ХОСТОВ. Реестр отвергнут в спеке по
-- YAGNI, и триггер пересмотра там назван прямо — второй хост. Здесь хранится
-- не «хост», а один факт: когда агент последний раз предъявил токен. Появится
-- второй хост — эта таблица станет его реестром, добавив ключ; до тех пор
-- колонка-ключ описывает ровно то, что есть, — ОДНУ строку.
--
-- ПОЧЕМУ В POSTGRES, А НЕ В ПАМЯТИ ПРОЦЕССА. Две причины, и обе уже
-- наступали в этом репозитории:
--   1. прод запущен в кластерном режиме. Число инстансов нигде не
--      зафиксировано (см. доку класса ProvisioningService), а память у них
--      раздельная: агент опросил бы один процесс, кабинет спросил бы другой —
--      и получил бы «агент молчит» при исправном агенте;
--   2. отметка в памяти обнуляется при каждом `pm2 restart`, то есть при
--      каждом выкате. Ровно в эту минуту агент тоже не может опрашивать
--      (бэкенд перезапускается), так что кабинет показывал бы тревогу после
--      каждого деплоя — то есть ровно тогда, когда она ничего не значит.
-- В Redis класть незачем: модуль продуктов разговаривает только с Postgres, а
-- свежесть отметки считается предикатом в SQL рядом с остальными (см.
-- HEARTBEAT_FRESH_SQL) — по часам СЕРВЕРА, одним и тем же `now()`.
--
-- ОДНА СТРОКА ГАРАНТИРУЕТСЯ БАЗОЙ, А НЕ АККУРАТНОСТЬЮ ВЫЗЫВАЮЩЕГО.
-- `id boolean PRIMARY KEY CHECK (id)` допускает единственное значение `true`:
-- второй строки не существует ни при какой гонке, поэтому «последний визит»
-- читается без ORDER BY и без max(). Без CHECK ключ пустил бы `false`, и
-- таблица тихо стала бы хранить две отметки, из которых запрос брал бы
-- случайную.
CREATE TABLE IF NOT EXISTS product_host_agent (
  id      boolean PRIMARY KEY DEFAULT true CHECK (id),
  -- NOT NULL: строка существует только затем, чтобы нести это значение.
  -- DEFAULT now() — чтобы вставка читалась как «агент только что был», а не
  -- как «строку завели неизвестно когда».
  seen_at timestamptz NOT NULL DEFAULT now()
);
