-- 004_rent.sql
-- Аренда продуктов в токенах: до какого момента оплачено, сон при нехватке
-- баланса и вид задания в очереди агента хоста.
-- Дизайн: spirits_front/docs/superpowers/specs/2026-09-16-linkeon-products-rent-design.md

-- ДО КАКОГО МОМЕНТА ОПЛАЧЕНО.
--
-- DEFAULT здесь делает СРАЗУ ДВЕ работы, и обе — ровно один раз:
--   1. существующим строкам (demo, shop2 и всё, что появится до выката)
--      ADD COLUMN проставляет значение, вычисленное в момент ALTER. Это и есть
--      обещанный спекой бесплатный первый месяц для заведённых раньше;
--   2. каждому новому продукту — тот же месяц от его собственного заведения.
--      INSERT в provisioning.service.ts эту колонку не перечисляет и
--      перечислять не должен: срок задаёт политика аренды, а не вызывающий код.
--
-- ОТДЕЛЬНЫЙ `UPDATE ... WHERE paid_until IS NULL` ЗДЕСЬ БЫЛ БЫ ДЕФЕКТОМ.
-- Модуль накатывает свои миграции сам, в onModuleInit, то есть при КАЖДОМ
-- `pm2 restart`. Разовой правкой данных такой UPDATE не является: он
-- перевыдавал бы бесплатный месяц (считая его от минуты рестарта) любой
-- строке, у которой колонка пуста, — а пуста она была бы у каждого продукта,
-- заведённого после выката, раз INSERT её не заполняет. Продукт бесконечно
-- жил бы «в первом месяце», и заметить это можно было бы только по
-- недосчитанной выручке. `ADD COLUMN IF NOT EXISTS` на втором прогоне — честный
-- no-op, поэтому бесплатный месяц выдаётся ровно однажды.
--
-- NOT NULL, а не nullable: NULL означал бы «срок неизвестен», и продукт с ним
-- выпадал бы из отбора сборщика (`paid_until <= now()` на NULL даёт NULL, то
-- есть не-совпадение) — то есть хостился бы бесплатно и навсегда, молча.
ALTER TABLE products ADD COLUMN IF NOT EXISTS paid_until timestamptz
  NOT NULL DEFAULT now() + interval '1 month';

-- ПОЧЕМУ СПИТ. Nullable намеренно: NULL — «не спит / причины нет», текст —
-- причина. NOT NULL DEFAULT '' дал бы третье состояние (пустая строка), а
-- «пустая строка» и «нет причины» в этом коде уже различались неправильно.
-- Словарём не закрывается: сегодня значение одно, но это ЧЕЛОВЕЧЕСКИЙ текст
-- для карточки, а не признак для запросов. Признак — status.
ALTER TABLE products ADD COLUMN IF NOT EXISTS sleep_reason text;

-- СТАТУС СНА.
-- Словарь перечислен ЦЕЛИКОМ, все семь значений, а не дописан одним. См.
-- identity/migrations/003_telegram_provider.sql: там дописывание одного
-- значения потеряло 'apple' и сломало вход. Состав сверен с живой базой прода
-- 16.09.2026 (`\d products`): шесть значений, ни одного лишнего.
--
-- DROP + ADD, а не DO/EXCEPTION duplicate_object: перехват дубля молча
-- сохраняет СТАРОЕ определение, и правка словаря не доезжает до баз, где
-- ограничение уже есть. Тот же приём, что в 002.
--
-- 'blocked' в этом списке заводит МИГРАЦИЯ 007 (гашение администратором), и
-- дописан он сюда по правилу из 002: именованный словарь объявлен в трёх файлах
-- — 002, 004 и 007, — и состав у него обязан быть один. Файл, отставший от
-- соседей, отказывает на первой же живой строке с новым значением и замолкает
-- навсегда.
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_status_check;
ALTER TABLE products ADD CONSTRAINT products_status_check
  CHECK (status IN ('provisioning','running','degraded','stopped','archived','failed','sleeping','blocked'));

-- ВИД ЗАДАНИЯ. Сегодня вид один и подразумевается; со сном их три.
--
-- DEFAULT здесь ОСТАЁТСЯ — в отличие от products.kind, у которого 002 его
-- снимает следующей же строкой. Разница не в стиле: у продукта забытый kind
-- означал бы бота, выставленного наружу сайтом, то есть тихую ошибку с ценой;
-- здесь же единственный существующий INSERT (provisioning.service.ts,
-- `INSERT INTO product_provision_jobs (product_id, status)`) вида не передаёт и
-- передавать не обязан — задание без вида это заведение. Снять DEFAULT значило
-- бы сломать постановку заданий в ту же секунду.
--
-- ВНИМАНИЕ НА ИМЯ: колонка `kind` теперь есть у ОБЕИХ таблиц — у products это
-- форма продукта ('site'|'bot'), здесь — вид задания. Любой запрос, где обе
-- таблицы в области видимости, обязан писать `j.kind` / `p.kind`: неуточнённое
-- `kind` в таком запросе — ошибка неоднозначности в рантайме. Существующий
-- claimJob уточняет везде (проверено), новые — обязаны тоже.
ALTER TABLE product_provision_jobs ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'provision';
ALTER TABLE product_provision_jobs DROP CONSTRAINT IF EXISTS product_provision_jobs_kind_check;
ALTER TABLE product_provision_jobs ADD CONSTRAINT product_provision_jobs_kind_check
  CHECK (kind IN ('provision','sleep','wake'));

-- ОТБОР ПО СРОКУ ОПЛАТЫ: сборщику — «кому пора платить», пробуждению — «кого
-- будить первым» (спящие в порядке засыпания).
--
-- Предикат — ТОЛЬКО `archived_at IS NULL`, и это осознанно уже́ напрашивавшегося
-- `AND status = 'running'`. Архивный продукт не платит никогда — это свойство
-- архива. А вот набор платящих статусов не устоялся: на проде 16.09.2026 из
-- шести продуктов четыре в 'degraded' (раннер перестал отмечаться), и вопрос,
-- платят ли они, решается не здесь. Частичный индекс, вшивший в себя один
-- статус, пришлось бы пересоздавать вместе с этим решением, а до тех пор он не
-- обслуживал бы ни выборку спящих для пробуждения (status = 'sleeping'), ни
-- расширенный отбор. Планировщику широкий предикат не мешает: он подходит
-- любому запросу, чьё условие его подразумевает.
CREATE INDEX IF NOT EXISTS idx_products_paid_until
  ON products (paid_until)
  WHERE archived_at IS NULL;
