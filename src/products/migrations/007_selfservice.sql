-- 007_selfservice.sql
-- Самообслуживание: гашение продукта администратором (свой статус и причина) и
-- потолок числа продуктов на аккаунт.
-- Дизайн: spirits_front/docs/superpowers/specs/2026-09-22-linkeon-products-selfservice-design.md

-- ═══════════════════════ СТАТУС БЛОКИРОВКИ ═══════════════════════
--
-- ПОЧЕМУ ОТДЕЛЬНЫЙ СТАТУС, А НЕ ПРИЧИНА СНА. Соблазн — гасить существующим
-- механизмом сна и различать поводы текстом `sleep_reason`. Так нельзя, и это
-- читается прямо в коде: `wakeAffordable` (rent.service.ts) отбирает
-- `p.status = 'sleeping'` и ставит задание пробуждения каждому, на кого хватает
-- баланса, а `wakeTick` ходит по владельцам таких продуктов раз в минуту.
-- Погашенный администратором продукт воскресал бы САМ — через минуту после
-- того, как нарушитель положит денег. Решение администратора отменялось бы
-- платежом того, из-за кого оно принято.
--
-- ПОЧЕМУ СТАТУС, А НЕ МАШИННЫЙ КОД ПРИЧИНЫ РЯДОМ СО СНОМ. Существующие отборы
-- перечисляют статусы ПОИМЁННО, а не пишут «всё, кроме». Их десять, и все
-- сверены по коду 22.09.2026:
--
--   rent.chargeRent, rent.tick, rent.requestSleep   p.status IN ('running','degraded')
--   rent.wakeAffordable, rent.wakeTick             p.status = 'sleeping'
--   provisioning.promoteReady (выборка и запись)   'provisioning' либо разбуженный 'sleeping'
--   provisioning.retry                             p.status = 'failed'
--   provisioning.failStaleProvisioning (обе ветки) p.status = 'provisioning'
--   turns.markStaleRunners, turns.claimNext        p.status = 'running'
--
-- Новое значение выпадает из всех десяти САМО СОБОЙ. Код причины рядом со сном
-- потребовал бы дописать условие в каждое, и любое забытое дало бы молчаливый
-- дефект.
--
-- ЧЕГО ЭТОТ ФАЙЛ НЕ РЕШАЕТ, И ЭТО НАДО ЗНАТЬ ТОМУ, КТО ПИШЕТ ГАШЕНИЕ.
-- «Выпадает само собой» верно ровно для отборов, которые блокированного
-- трогать НЕ должны. Есть одно место, где выпадение — это дефект, а не
-- подарок: `ProvisioningService.claimJob` выдаёт агенту задание по условию
--
--     CASE j.kind WHEN 'provision' THEN p.status = 'provisioning'
--                 ELSE               p.status = 'sleeping' END
--
-- то есть задание вида 'sleep' достаётся только СПЯЩЕМУ продукту. Гашение
-- ставит именно такое задание, оставляя продукт в 'blocked', — и агент его
-- не получит никогда: контейнер продолжит работать, домен продолжит отдавать
-- то, за что продукт погасили, а через десять минут (PROVISION_DEADLINE_MIN)
-- `failStaleProvisioning` закроет задание чужой формулировкой про истёкший срок
-- заведения. Ветку 'sleep' в claimJob придётся расширить до
-- `p.status IN ('sleeping','blocked')` вместе с реализацией гашения.
--
-- Там же второе: путь отказа `completeJob` переводит продукт по виду задания
-- (`WHEN 'sleep' THEN 'degraded'`) БЕЗ оглядки на его нынешний статус. Сорвётся
-- гашение — и блокированный продукт сам уедет в 'degraded', то есть снова
-- станет платить аренду и принимать правки.
--
-- СЛОВАРЬ РАСШИРЯЕТСЯ ВО ВСЕХ ФАЙЛАХ, ГДЕ ОБЪЯВЛЕН, А НЕ ТОЛЬКО ЗДЕСЬ.
-- Модуль накатывает ВЕСЬ список миграций при КАЖДОМ старте API, и файлы,
-- стоящие в списке раньше, навешивают свой словарь на живые данные заново.
-- Именованный `products_status_check` объявлен в 002 и в 004; оставь их
-- семизначными — и первый же блокированный продукт уронит на своей строке
-- ADD CONSTRAINT в 002. Весь файл (простой протокол = неявная транзакция)
-- откатится, applyMigration запишет строку в лог и поедет дальше, а 002 станет
-- мёртвой молча, навсегда и вместе со всем, что в неё когда-нибудь допишут.
-- Ровно это уже случилось в куске 3 со статусом 'sleeping' (см. длинный блок в
-- 002_provisioning.sql). Поэтому 002, 004 и 007 несут ОДИН И ТОТ ЖЕ состав из
-- восьми значений; сторожат «один именованный словарь — один состав во ВСЕХ
-- миграциях» (products.migration.spec.ts) и сценарий 20е исполнением.
--
-- Инлайнового CHECK из `CREATE TABLE` в 001 это не касается: он стоит под
-- IF NOT EXISTS и на живой базе не исполняется вовсе — потому словарь там и
-- остался пятизначным. На ПУСТОЙ базе 001 его создаёт, и PostgreSQL даёт ему
-- то же имя `products_status_check` (<таблица>_<колонка>_check), которое 002
-- тут же снимает своим DROP CONSTRAINT IF EXISTS и заменяет полным.
--
-- DROP + ADD, а не DO/EXCEPTION duplicate_object: перехват дубля молча
-- сохраняет СТАРОЕ определение, и правка словаря не доезжает до баз, где
-- ограничение уже есть. Тот же приём, что в 002 и 004.
--
-- ПОВТОРНАЯ НАКАТКА БЕЗВРЕДНА и на живых данных: новый состав — НАДМНОЖЕСТВО
-- прежнего, поэтому ADD CONSTRAINT не может отказать ни на одной существующей
-- строке. Цена та же, что уже платят 002 и 004: короткий ACCESS EXCLUSIVE и
-- один проход по таблице на каждый рестарт API.
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_status_check;
ALTER TABLE products ADD CONSTRAINT products_status_check
  CHECK (status IN ('provisioning','running','degraded','stopped','archived','failed','sleeping','blocked'));

-- ЗА ЧТО ПОГАШЕН. Текст для владельца: общего списка продуктов у
-- администратора нет, жалоба приходит с доменом, и единственное, из чего
-- владелец узнает причину, — эта колонка в его карточке.
--
-- СВОЯ КОЛОНКА, А НЕ `sleep_reason`, И ПРИЧИНА ИЗМЕРИМАЯ, а не эстетическая.
-- Гашение ставит задание вида 'sleep', а путь отказа такого задания
-- (`ProvisioningService.completeJob`) обнуляет `sleep_reason`:
-- `sleep_reason = CASE closed.kind WHEN 'sleep' THEN NULL ELSE ... END`.
-- Причина блокировки, сложенная туда, стиралась бы ровно тогда, когда гашение
-- сорвалось, — то есть в том случае, где объяснение нужнее всего. То же делает
-- `promoteReady` при переводе в работу.
--
-- Nullable намеренно и по образцу `sleep_reason` (004): NULL — «не блокирован /
-- причина не записана», текст — причина. NOT NULL DEFAULT '' завёл бы третье
-- состояние (пустая строка), которое этот код уже однажды путал с «причины
-- нет». Словарём не закрывается: это ЧЕЛОВЕЧЕСКИЙ текст для карточки, а не
-- признак для запросов. Признак — status.
ALTER TABLE products ADD COLUMN IF NOT EXISTS block_reason text;

-- ═══════════════════ ПОТОЛОК ПРОДУКТОВ НА АККАУНТ ═══════════════════
--
-- ЗАЧЕМ. Вкладка «Продукты» открывается всем, а первый месяц бесплатный:
-- вдвоём эти два решения означают, что один человек заводит двадцать продуктов
-- — весь потолок клиентской машины — и не платит ничего до следующего месяца.
-- Потолок машины (product_hosts.capacity) от этого не спасает: он общий, и
-- заполнить его может кто угодно.
--
-- ОТДЕЛЬНАЯ ТАБЛИЦА МОДУЛЯ, А НЕ КОЛОНКА В ai_profiles_consolidated. Та —
-- таблица балансов, чужая ответственность, и она даже не входит в этот список
-- миграций (интеграционный сьют заводит её минимальную копию сам). Модуль
-- продуктов держит свои данные у себя — как product_hosts и
-- product_provision_jobs.
--
-- СТРОКА ПОЯВЛЯЕТСЯ ТОЛЬКО У ТЕХ, КОМУ ПОТОЛОК ПОДНЯЛИ. Умолчание живёт
-- константой в коде (DEFAULT_MAX_PRODUCTS), а не копией в каждой строке: иначе
-- правка умолчания превратилась бы в правку данных всех аккаунтов сразу, а
-- аккаунты, заведённые до неё, молча остались бы на старом числе.
--
-- НИКАКОГО INSERT В ЭТОМ ФАЙЛЕ, и это не забывчивость. Файл исполняется при
-- КАЖДОМ старте API: любая «разовая» правка данных здесь повторяется на каждом
-- `pm2 restart`. Ровно эта ловушка разобрана в 004 на примере бесплатного
-- месяца. Сторожат «правки данных в файле нет» (products.migration.spec.ts) и
-- сценарий 20ж исполнением.
CREATE TABLE IF NOT EXISTS product_user_limits (
  -- text, а не varchar(20): у OAuth/email-пользователей идентификатор — UUID на
  -- 36 символов, а не телефон. Та же причина, что у products.user_id (001).
  --
  -- PRIMARY KEY, а не просто индекс: потолок читается подзапросом без ORDER BY
  -- и без max(), и вторая строка на того же владельца означала бы потолок,
  -- выбираемый наугад. Единственность держит база, а не аккуратность того, кто
  -- заводит исключение руками.
  user_id      text PRIMARY KEY,

  -- Сколько продуктов можно этому аккаунту.
  --
  -- CHECK ИНЛАЙНОВЫЙ, а не именованный через DROP+ADD, и это осознанно — тот же
  -- приём и та же причина, что у product_hosts.audience (005). Именованный
  -- навешивался бы заново при КАЖДОМ старте API и на живых данных стал бы ещё
  -- одним местом, где случайное значение роняет весь файл. CREATE TABLE стоит
  -- под IF NOT EXISTS и на существующей базе не исполняется вовсе.
  --
  -- `> 0`, а не `>= 0`: таблица умеет ТОЛЬКО поднимать. Ноль означал бы «этому
  -- аккаунту нельзя ничего» — запрет, который выглядел бы как обычный отказ по
  -- потолку и не объяснял бы владельцу ничего. Запрещать заводить продукты — не
  -- дело этой таблицы; для «этот продукт стоять не будет» есть статус blocked,
  -- который называет причину вслух.
  max_products int NOT NULL CHECK (max_products > 0),

  -- Кому и за что подняли. Строк здесь будет единицы, заводятся они руками, и
  -- через полгода «почему у этого пять» иначе не ответит никто.
  note         text,

  created_at   timestamptz NOT NULL DEFAULT now()
);
