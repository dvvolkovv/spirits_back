-- 005_hosts.sql
-- Реестр машин под продукты и метка машины у продукта.
-- Дизайн: spirits_front/docs/superpowers/specs/2026-09-21-linkeon-products-multihost-design.md

CREATE TABLE IF NOT EXISTS product_hosts (
  -- Метка машины: короткая и человеческая ('own', 'clients'). Она же — то, во
  -- что гвард превращает предъявленный токен, и то, по чему фильтрует выдача
  -- заданий. Реестр живёт в базе, а не в окружении, именно поэтому: он нужен
  -- ВНУТРИ запроса выдачи, а не только при старте.
  id               text PRIMARY KEY,

  -- Куда ходит выкат хостовых частей.
  ssh_target       text NOT NULL,

  -- Пишется в products.host_ip при заведении продукта.
  --
  -- Тип inet — ТОТ ЖЕ, что у products.host_ip (001), и это не вкусовщина:
  -- в text-колонке сопоставление ниже (`p.host_ip = h.public_ip`) не
  -- скомпилировалось бы вовсе. Измерено на PostgreSQL 16.14:
  -- `operator does not exist: inet = text`. Отказ пришёлся бы на ПЕРВЫЙ же
  -- прогон миграции, то есть ни таблицы, ни колонки на проде не появилось бы.
  --
  -- UNIQUE не для красоты: сопоставление — это UPDATE ... FROM, то есть
  -- соединение. Две машины с одним адресом дали бы продукту метку ОДНОЙ ИЗ
  -- НИХ наугад — без ошибки, без строки в логе и без способа заметить.
  public_ip        inet NOT NULL UNIQUE,

  -- Зона доменов продуктов этой машины.
  domain_suffix    text NOT NULL,

  -- sha256 токена агента в hex. Открытый токен живёт ТОЛЬКО в конфиге машины:
  -- тот же приём, что у runner_token_hash продукта (001).
  --
  -- UNIQUE по той же причине, что и там: гвард бьёт сюда SELECT на каждый
  -- long-poll агента и берёт строку без ORDER BY. Без уникальности совпадение
  -- хешей отдавало бы ему произвольную машину — то есть чужие задания.
  agent_token_hash text NOT NULL UNIQUE,

  -- Потолок числа продуктов машины.
  capacity         int NOT NULL CHECK (capacity > 0),

  -- Принимает ли новые продукты. Машину выводят из оборота этим флагом, а не
  -- удалением строки: у неё остаются свои продукты и своя очередь заданий.
  accepts_new      boolean NOT NULL DEFAULT true,

  -- Чьи продукты сюда уезжают: продукты админов — на 'own', всех остальных —
  -- на 'clients'.
  --
  -- CHECK ИНЛАЙНОВЫЙ, а не именованный через DROP+ADD, и это осознанно.
  -- Именованный навешивался бы заново при КАЖДОМ старте API (модуль накатывает
  -- ВЕСЬ список миграций, а не только новые), и значение, дописанное в словарь
  -- поздней миграцией, роняло бы 005 на живых данных — ровно ловушка 002.
  -- CREATE TABLE стоит под IF NOT EXISTS и на существующей базе не исполняется
  -- вовсе, поэтому инлайновый словарь на живые данные не навешивается никогда.
  audience         text NOT NULL CHECK (audience IN ('own','clients')),

  created_at       timestamptz NOT NULL DEFAULT now()
);

-- МЕТКА МАШИНЫ У ПРОДУКТА.
--
-- Внешний ключ без ON DELETE: машину, на которой стоят продукты, снести
-- «заодно» нельзя — DELETE отобьётся. ON DELETE SET NULL означал бы продукты
-- без машины, то есть молча выпавшие из выдачи заданий; ON DELETE CASCADE —
-- снос реестра продуктов вместе со строкой машины.
ALTER TABLE products ADD COLUMN IF NOT EXISTS host_id text REFERENCES product_hosts(id);

-- НЫНЕШНЯЯ МАШИНА заводится из того, что уже есть в окружении бэкенда.
-- Токен агента при этом НЕ меняется: конфиг машины прежний, токен просто
-- перестаёт быть общим.
--
-- В файл приезжает УЖЕ ХЕШ, параметром сессии, а сам токен не приезжает вовсе,
-- и считает хеш Node. Две причины, обе измерены 21.09.2026:
--
--   1. digest() живёт в pgcrypto, а на проде стоят только citext и plpgsql.
--      `encode(digest(...), 'hex')` здесь — `function digest(unknown, unknown)
--      does not exist`, то есть отказ ВСЕГО файла: ни таблицы, ни колонки;
--
--   2. параметр сессии, выставленный отдельным запросом ЧЕРЕЗ ПУЛ, до этого
--      файла не доезжает. set_config(..., true) живёт до конца транзакции, а
--      через пул каждый запрос — своя транзакция. И отказа при этом НЕ
--      происходит: следующий запрос на том же соединении читает ПУСТУЮ СТРОКУ.
--      В реестр уехал бы sha256(''), гвард перестал бы узнавать настоящий
--      токен, и машина молча осталась бы без работы. Поэтому applyMigration
--      везёт 005 на ВЫДЕЛЕННОМ соединении внутри явной транзакции.
--
-- missing_ok = true и проверка на пустоту: файл, накаченный psql-ом или
-- тестовой батареей без параметра, обязан быть безвредным no-op, а не заводить
-- машину с хешем пустой строки. Прод при пустом параметре не проходит проверку
-- сопоставления в конце файла — то есть молчаливой потери тоже не будет.
INSERT INTO product_hosts (id, ssh_target, public_ip, domain_suffix,
                           agent_token_hash, capacity, audience)
SELECT 'own', 'root@139.59.210.42', '139.59.210.42', 'p.linkeon.io',
       current_setting('linkeon.own_host_token_sha256', true),
       -- ПОТОЛОК ВЫБРАН НА ГЛАЗ И НЕ ИЗМЕРЕН. Замерено 21.09.2026 другое:
       -- продукт ест около 90 МБ, на машине 3 ГБ свободно и два ядра. Двадцать
       -- спящих поместятся, двадцать ОДНОВРЕМЕННО РАБОТАЮЩИХ — нет. Настоящий
       -- предел — одновременные правки, а не число продуктов; число
       -- пересматривается по первой живой нагрузке.
       20, 'own'
 WHERE coalesce(current_setting('linkeon.own_host_token_sha256', true), '') <> ''
   AND NOT EXISTS (SELECT 1 FROM product_hosts WHERE id = 'own');

-- МЕТКА ПРОСТАВЛЯЕТСЯ СОПОСТАВЛЕНИЕМ ПО АДРЕСУ, а не умолчанием.
UPDATE products p SET host_id = h.id
  FROM product_hosts h
 WHERE p.host_id IS NULL AND p.host_ip = h.public_ip;

-- И ОТКАЗ, ЕСЛИ СОПОСТАВИТЬ НЕ УДАЛОСЬ.
--
-- «Поставлю первую попавшуюся» здесь означает продукт, получающий задания на
-- машину, где его каталога нет: заведение начнётся заново поверх пустого места.
-- Оставить метку пустой тоже нельзя молча — такой продукт выпадает из выдачи
-- заданий совсем: его не разбудят и не усыпят за неуплату, и заметить это можно
-- будет только по недосчитанной выручке.
--
-- Отказ роняет весь файл (простой протокол = одна транзакция) и — в отличие от
-- 001..004 — роняет СТАРТ API: 005 объявлена обязательной в products.service.ts.
-- Иначе отказ был бы строкой в логе, таблицы не было бы вовсе, а гвард агента и
-- выдача заданий отвечали бы 500 на каждый опрос.
--
-- Архивные не считаются: архивный продукт не получает заданий никогда.
DO $$
DECLARE orphans text;
BEGIN
  -- host(), а не ::text: inet печатает себя с маской, и в сообщении стоял бы
  -- адрес «10.0.0.99/32», которого оператор не найдёт ни в одном конфиге.
  SELECT string_agg(format('%s (host_ip %s)', slug, coalesce(host(host_ip), 'пуст')), ', '
                    ORDER BY slug)
    INTO orphans
    FROM products
   WHERE host_id IS NULL AND archived_at IS NULL;

  -- string_agg по пустой выборке даёт NULL, а не пустую строку, — отдельный
  -- count(*) не нужен.
  IF orphans IS NOT NULL THEN
    RAISE EXCEPTION 'host_ip не сошёлся ни с одной машиной реестра: %', orphans;
  END IF;
END $$;
