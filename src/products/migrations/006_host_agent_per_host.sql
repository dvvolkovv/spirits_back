-- 006_host_agent_per_host.sql
-- Отметка о жизни агента — СВОЯ У КАЖДОЙ МАШИНЫ.
-- Дизайн: spirits_front/docs/superpowers/specs/2026-09-21-linkeon-products-multihost-design.md
--
-- ЗАЧЕМ. 003 завела product_host_agent ОДНОЙ СТРОКОЙ НА ВСЁ
-- (`id boolean PRIMARY KEY DEFAULT true CHECK (id)`), и это было осознанно:
-- машина была одна, единственность держала база, читатель брал отметку без
-- ORDER BY. 003 там же назвала и триггер пересмотра — «появится второй хост —
-- эта таблица станет его реестром, добавив ключ». Он наступил.
--
-- С двумя машинами общая отметка не «немного неточна», а ЛЖЁТ РОВНО ТАМ, РАДИ
-- ЧЕГО ЗАВЕДЕНА: опрос живого агента поднимает её, и кабинет объявляет живым и
-- мёртвого соседа. Продукт на умершей машине десять минут висит «Заводится…» и
-- заканчивается чужой формулировкой про истёкший срок — то есть ровно той
-- диагностикой, которую отметка была призвана заменить, только теперь ещё и при
-- зелёном индикаторе.
--
-- ВЕСЬ ФАЙЛ — ОДИН DO-БЛОК С ПРОВЕРКОЙ ФОРМЫ, И ЭТО НЕ СТИЛЬ. Модуль накатывает
-- ВЕСЬ список миграций при КАЖДОМ старте API, а здесь меняется первичный ключ
-- живой таблицы. Наивная «идемпотентная» запись
--
--     ALTER TABLE ... DROP CONSTRAINT IF EXISTS product_host_agent_pkey;
--     ALTER TABLE ... ADD PRIMARY KEY (host_id);
--
-- повторный прогон переживает — и ценой, которую видно только исполнением: на
-- КАЖДОМ рестарте она снимает и перестраивает первичный ключ под ACCESS
-- EXCLUSIVE, а в окне между DROP и ADD уникального индекса нет вовсе. В этом
-- окне `ON CONFLICT (host_id)` у touchHostAgent — это «there is no unique or
-- exclusion constraint matching the ON CONFLICT specification», то есть отказ
-- отметки, а параллельные опросы двух агентов успевают положить по второй
-- строке на машину, на которых ADD PRIMARY KEY потом отказывает совсем. Агент
-- опрашивает раз в три секунды; рестарт API — это ровно та минута, когда он
-- опрашивает впустую и потом наверстывает.
--
-- Здесь повтор — НАСТОЯЩИЙ no-op: блок смотрит на форму таблицы и выходит, не
-- взяв ни одного тяжёлого замка. Перестройка исполняется один раз в жизни базы.
--
-- ИДЕМПОТЕНТНОСТЬ ПРОВЕРЯЕТСЯ НА СПИСКЕ, А НЕ НА ФАЙЛЕ. 003 стоит в списке
-- РАНЬШЕ и на следующем старте накатится снова — на уже перестроенную таблицу.
-- Она переживает это только потому, что вся целиком стоит под
-- `CREATE TABLE IF NOT EXISTS`: на существующей таблице она не исполняется
-- вовсе и старую форму не возвращает. Если 003 когда-нибудь дополнят
-- оператором вне CREATE TABLE — проверять надо будет заново и исполнением.
DO $$
BEGIN
  -- Таблицы нет вовсе — это не «ещё не перестроена», это несработавшая 003.
  -- 006 обязательная (FATAL_MIGRATIONS), и молчаливый выход здесь означал бы
  -- успешный старт API с отметкой, которую некуда писать: индикатор кабинета
  -- зеленеет по своему же отказу (см. products.controller.ts), то есть врёт
  -- ровно так, как этот файл запрещает.
  IF to_regclass('product_host_agent') IS NULL THEN
    RAISE EXCEPTION 'таблицы product_host_agent нет: 003_host_agent.sql не применилась';
  END IF;

  -- УЖЕ ПЕРЕСТРОЕНА. Признак — целевая колонка, а не отсутствие исходной:
  -- проверка «нет колонки id» истинна и у таблицы, которой вообще ничего не
  -- делали, если 003 когда-нибудь перепишут.
  IF EXISTS (SELECT 1 FROM pg_attribute
              WHERE attrelid = 'product_host_agent'::regclass
                AND attname = 'host_id'
                AND NOT attisdropped) THEN
    RETURN;
  END IF;

  ALTER TABLE product_host_agent ADD COLUMN host_id text;

  -- ЕДИНСТВЕННАЯ СТРОКА ПРИНАДЛЕЖАЛА ЕДИНСТВЕННОЙ МАШИНЕ, и это не догадка:
  -- до реестра машина была одна, и 005 заводит её под меткой 'own'.
  UPDATE product_host_agent SET host_id = 'own'
   WHERE EXISTS (SELECT 1 FROM product_hosts WHERE id = 'own');

  -- А ЕСЛИ 'own' В РЕЕСТРЕ НЕТ — отметку выбрасываем, а не приписываем первой
  -- попавшейся машине. Состояние достижимое: 005 нарочно сделана безвредным
  -- no-op при незаполненном PRODUCT_HOST_TOKEN, и реестр тогда пуст, а отметка
  -- от прошлых опросов в таблице лежит. Приписать её наугад значило бы объявить
  -- живой машину, которую никто не опрашивал, — ту самую ложь, ради снятия
  -- которой написан файл. Цена выброса нулевая: отметка живёт две минуты и
  -- восстанавливается первым же опросом через три секунды.
  DELETE FROM product_host_agent WHERE host_id IS NULL;

  -- DROP COLUMN уносит С СОБОЙ и первичный ключ по этой колонке — отдельный
  -- DROP CONSTRAINT не нужен и был бы хуже: он угадывал бы имя ключа, а
  -- промахнувшийся `DROP CONSTRAINT IF EXISTS` не делает НИЧЕГО и молчит.
  -- Утверждение самопроверяемое: не унеси он ключ, следующий ADD PRIMARY KEY
  -- отказал бы с «multiple primary keys for table are not allowed», то есть
  -- громко. Сторож исполнением — «первичный ключ один, и он по машине».
  ALTER TABLE product_host_agent DROP COLUMN id;

  -- NOT NULL и ключ — ПОСЛЕ заполнения и уборки: на строке без метки
  -- SET NOT NULL отказал бы всем файлом.
  ALTER TABLE product_host_agent ALTER COLUMN host_id SET NOT NULL;

  -- ЕДИНСТВЕННОСТЬ ТЕПЕРЬ НА МАШИНУ, и держит её по-прежнему база, а не
  -- аккуратность вызывающего: читатель берёт отметку машины без ORDER BY и без
  -- max(), и вторая строка означала бы, что иногда показывается позавчерашняя.
  ALTER TABLE product_host_agent ADD PRIMARY KEY (host_id);

  -- ON DELETE CASCADE — в отличие от products.host_id (005), где ON DELETE нет
  -- вовсе. Разница в том, что переживает снос машины. Продукт переживает: у
  -- него есть код, история и владелец, и снести машину «заодно» с ним нельзя.
  -- Отметка о жизни не переживает ничего: это производная от машины, живущая
  -- две минуты. Ключ без ON DELETE сделал бы снос машины невозможным, пока
  -- оператор не уберёт отметку руками, — то есть подтолкнул бы его к
  -- `DELETE ... CASCADE` на самой машине, где под каскад попадут уже продукты.
  ALTER TABLE product_host_agent
    ADD CONSTRAINT product_host_agent_host_id_fkey
    FOREIGN KEY (host_id) REFERENCES product_hosts(id) ON DELETE CASCADE;
END $$;
