import {
  BadRequestException,
  ConflictException,
  Injectable,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { PgService } from '../common/services/pg.service';

/**
 * Форма `products.id`. Проверяется ПЕРВОЙ — почему именно первой, разобрано в
 * докблоке `lookup`.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Что записывается в снятое задание. Видно только нам — в журнале заданий. */
export const JOB_KILLED_BY_BLOCK = 'снято блокировкой администратора';

/**
 * Что записывается в убитый ход. Видит ВЛАДЕЛЕЦ — в истории правок, на месте
 * результата. Слово «администратор» здесь обязательное: без него владелец
 * читает обычный отказ раннера и идёт искать поломку у себя.
 */
export const TURN_KILLED_BY_BLOCK = 'Продукт остановлен администратором';

/** Что записывается в задание, снятое снятием блокировки. */
export const JOB_KILLED_BY_UNBLOCK = 'снято снятием блокировки';

/**
 * ЧТО ГАШЕНИЕ РАССКАЗЫВАЕТ ВЫЗВАВШЕМУ. Ровно то же, что уходит в журнал, — но
 * журнал читают потом и не те: администратор жмёт кнопку и получает ответ.
 *
 * Зачем это наружу, а не `void` с `{ ok: true }` в маршруте:
 *
 *   - `slug` и `id` — потому что искали по ДОМЕНУ. Администратор прислал
 *     строку из жалобы и обязан увидеть, какой продукт под ней оказался:
 *     домены строятся из слагов, и «shop2.p.linkeon.io» вместо
 *     «shop.p.linkeon.io» — это соседний живой продукт, а не опечатка в
 *     пустоту;
 *   - `by` — чем ключ разобран. Тот же ответ на вопрос «почему нашлось
 *     именно это»;
 *   - `wasStatus` — что было ДО. 'sleeping' здесь означает «контейнер и так
 *     был погашен», 'running' — «погасили работающий»;
 *   - `killedTurns` — единственный способ узнать, что под гашением умерла
 *     ЧУЖАЯ ИДУЩАЯ ПРАВКА. Это осознанный размен (см. докблок класса), но
 *     размен молчаливый: владелец увидит оборванный ход, а администратор без
 *     этого числа не узнает, что он его оборвал.
 */
export interface BlockResult {
  id: string;
  slug: string;
  /** Статус ДО гашения. */
  wasStatus: string;
  /** Чем разобран ключ: «домену», «слагу» или «идентификатору». */
  by: string;
  killedJobs: number;
  killedTurns: number;
}

/**
 * То же у снятия. `killedTurns` здесь нет и быть не может: у блокированного
 * продукта идущих ходов не бывает — их убило гашение, а новые не ставятся
 * (BLOCKED_REFUSAL в turns.service.ts).
 */
export interface UnblockResult {
  id: string;
  slug: string;
  by: string;
  killedJobs: number;
}

/**
 * ГАШЕНИЕ ПРОДУКТА АДМИНИСТРАТОРОМ И СНЯТИЕ БЛОКИРОВКИ.
 *
 * Своим сервисом, а не дописью в ProvisioningService (тот уже за 1300 строк и
 * отвечает за заведение) и не в RentService (тот отвечает за деньги). У
 * гашения свой жизненный цикл: его вызывает человек по жалобе, оно не ходит по
 * расписанию и денег не трогает вовсе.
 *
 * ## ЧЕМ БЛОКИРОВКА ОТЛИЧАЕТСЯ ОТ СНА — ТРИ МЕСТА
 *
 * Механика общая: задание вида 'sleep' в ту же очередь, агент гасит контейнер
 * и уводит домен на заглушку. Разного три вещи, и все три — здесь.
 *
 * **1. НЕ ЖДЁТ ЗАВЕРШЕНИЯ ХОДА.** Сон за неуплату ждёт: `requestSleep`
 * отказывается ставить задание, пока ход подаёт признаки жизни, потому что
 * погашенный посреди правки контейнер убивает её молча — ни ошибки, ни строки
 * в истории. У блокировки цель другая: её ставят, когда на домене
 * недопустимое, и ждать тридцать минут молчащего хода нельзя. Идущий ход
 * умирает — осознанный размен, а не недосмотр.
 *
 * **2. УБИТЫЙ ХОД ЗАКРЫВАЕТСЯ ТЕМ ЖЕ ДЕЙСТВИЕМ**, статусом отказа и причиной.
 * Оставленный в 'running', он висел бы до срока сборщика зависших (полчаса), и
 * всё это время владелец видел бы «выполняется» у погашенного продукта, а
 * замок `product_turns_one_active` не пускал бы следующий ход. Токены за него
 * не списываются: списание живёт в `TurnsService.complete`, а этот ход не
 * завершился.
 *
 * **3. СНИМАЕТ НЕВЫПОЛНЕННОЕ ПРОБУЖДЕНИЕ.** Порядок, который ломает: продукт
 * спал за неуплату, владелец пополнил, будильник поставил 'wake' — и в этот
 * момент администратор гасит. Задание уже в очереди, и без снятия агент
 * разбудил бы блокированный продукт через секунды. Обратный порядок безопасен
 * по устройству: будильник ищет 'sleeping', а блокированный под него не
 * подпадает.
 *
 * Снятие пробуждения — не единственная причина убирать активное задание. Их
 * две, и вторая техническая: `product_provision_jobs_one_active` — частичный
 * УНИКАЛЬНЫЙ индекс, то есть пока активное задание висит, задание на гашение
 * в эту таблицу просто не встанет.
 *
 * ## ГОНКИ ЗАКРЫВАЕТ ФОРМА ЗАПРОСА, А НЕ ТРАНЗАКЦИЯ
 *
 * Тот же приём, что у `claimJob`, `completeJob`, `retry` и `requestSleep`:
 * КАЖДОЕ действие — один оператор со своими предусловиями внутри. Промежутка,
 * в который состояние успевает поменять сосед, не существует, и смерть
 * процесса не может оставить продукт наполовину погашенным. Транзакции через
 * пул в этом репозитории уже рапортовали об откате, которого не было
 * (identity.resolveOrCreate), — поэтому их здесь нет и не будет.
 *
 * Цена одного оператора в этом конкретном случае названа у `block()`: пришлось
 * ИЗМЕРИТЬ поведение частичного уникального индекса, когда один и тот же
 * оператор снимает старое задание и ставит новое.
 */
@Injectable()
export class BlockService {
  private readonly logger = new Logger(BlockService.name);

  constructor(private readonly pg: PgService) {}

  /**
   * Как искать продукт по тому, что принёс администратор.
   *
   * ОБЩЕГО СПИСКА ПРОДУКТОВ У АДМИНИСТРАТОРА НЕТ (решение владельца от
   * 21.09.2026), значит жалоба приходит С ДОМЕНОМ, а не с внутренним
   * идентификатором. Поле одно, разбирает его сервер.
   *
   * РАЗБОР СТРОГИЙ И БЕЗ ЗАПАСНОГО ВАРИАНТА: не нашли по выбранному способу —
   * отказ. Молчаливый поиск «сначала по одному, потом по другому» однажды
   * погасил бы НЕ ТОТ продукт: слаг одного продукта совпадает с началом
   * домена другого ровно потому, что домен из слага и строится.
   *
   * ПОРЯДОК ПРОВЕРОК ЗНАЧИМ. Сначала форма uuid, потом точка, потом слаг:
   * `SLUG_RE` формально пропускает строку вида '0123abcd-...-...' (строчные,
   * цифры и дефисы внутри — всё разрешено), и обратный порядок искал бы
   * идентификатор как слаг. Домен от слага отличает точка: `SLUG_RE` её
   * запрещает, то есть строка с точкой слагом быть не может вовсе.
   *
   * КЛЮЧ ПРИВОДИТСЯ К НИЖНЕМУ РЕГИСТРУ, и это НЕ запасной вариант. Слаги
   * (SLUG_RE) и домены лежат в базе только строчными, поэтому приведение
   * умеет превратить «ничего не найдено» в «найдено единственное верное» и
   * не умеет превратить одно совпадение в другое. Жалоба приходит текстом от
   * человека, и «Shop.C.Linkeon.io» в ней — обычное дело.
   */
  private lookup(raw: string): { sql: string; key: string; by: string } {
    if (typeof raw !== 'string' || !raw.trim()) {
      throw new BadRequestException('Не сказано, что гасить: нужен домен, слаг или идентификатор');
    }
    const key = raw.trim().toLowerCase();
    if (UUID_RE.test(key)) return { sql: 'p.id = $1', key, by: 'идентификатору' };
    if (key.includes('.')) return { sql: 'p.domain = $1::text', key, by: 'домену' };
    return { sql: 'p.slug = $1::text', key, by: 'слагу' };
  }

  /**
   * Отказ «не найден» обязан называть, ЧЕМ мы считали ключ. Без этого
   * администратор читает «продукт не найден» и ищет опечатку там, где её нет.
   *
   * ПРО БОТА — отдельной строкой и только на поиске по домену: у бота домена
   * НЕТ вовсе (`create()` пишет `domain` только сайтам), то есть бот по
   * домену не находится никогда и ни при какой опечатке.
   */
  /**
   * Единственный конфликт, который здесь остался, — ЧУЖАЯ вставка активного
   * задания, успевшая между нашим снимком и нашей вставкой. Оператор при этом
   * откатывается ЦЕЛИКОМ: продукт не блокирован, задания не сняты, ход жив.
   * Состояние целое, повтор безопасен — и об этом надо сказать словами, а не
   * отдать 500 с текстом «duplicate key value violates unique constraint».
   *
   * Сверка по коду `23505`, а не по тексту: текст драйвер отдаёт от
   * PostgreSQL, то есть на другой локали он другой.
   */
  private explain(e: any, action: string): never {
    if (e?.code === '23505') {
      this.logger.warn(`${action}: не прошло — у продукта появилось активное задание, откат целиком`);
      throw new ConflictException(
        `У продукта только что появилось активное задание — ${action} не выполнено, ` +
          'ничего не изменилось. Повторите через несколько секунд.',
      );
    }
    throw e;
  }

  private notFound(l: { key: string; by: string }): never {
    const tail =
      l.by === 'домену'
        ? ' Ключ с точкой разобран как домен — других способов не пробовали. ' +
          'У бота домена нет вовсе: его гасят по слагу или идентификатору.'
        : l.by === 'слагу'
          ? ' Ключ без точки и не в форме идентификатора разобран как слаг — других способов не пробовали.'
          : '';
    throw new NotFoundException(`Продукт не найден по ${l.by}: «${l.key}».${tail}`);
  }

  /**
   * Погасить продукт. ОДНИМ ОПЕРАТОРОМ: найти, снять активное задание, убить
   * идущий ход, перевести в 'blocked' с причиной, поставить задание на
   * гашение.
   *
   * ## ПОРЯДОК ЧАСТЕЙ ЗАКРЕПЛЁН ССЫЛКОЙ, А НЕ НАДЕЖДОЙ — ЭТО ИЗМЕРЕНО
   *
   * `product_provision_jobs_one_active` — ЧАСТИЧНЫЙ УНИКАЛЬНЫЙ индекс по
   * product_id при status IN ('queued','running'). Оператор ниже снимает
   * старое активное задание и тут же ставит новое, и части `WITH` по
   * документации исполняются «одновременно»: порядок между ними не обещан
   * ничем.
   *
   * Снято на PostgreSQL 16, три формы одного и того же оператора при
   * невыполненном 'wake' у продукта:
   *
   *   - вставка БЕЗ ссылки на снятие — `23505 duplicate key`. Она исполняется
   *     РАНЬШЕ снятия и упирается в живое задание;
   *   - та же вставка без ссылки, но с `ON CONFLICT DO NOTHING` — задание
   *     молча НЕ ставится. Худший исход из трёх: продукт помечен
   *     блокированным, агент ничего не получает, контейнер работает;
   *   - вставка СО ССЫЛКОЙ на снятие (`WHERE (SELECT count(*) FROM
   *     killed_jobs) >= 0`) — проходит. Ссылка заставляет планировщик
   *     исполнить снятие первым, а после снятия конфликта нет.
   *
   * Условие всегда истинно и существует ровно затем, чтобы закрепить порядок.
   * Убери его — и сценарии про невыполненное пробуждение и про повторное
   * гашение краснеют (мутация M14, 6 живых сценариев).
   *
   * ## ON CONFLICT DO NOTHING ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ
   *
   * Он выглядит как бесплатная страховка, но страхует не от того. Собственное
   * снятие конфликта уже не даёт (измерено выше), значит единственный
   * оставшийся конфликт — ЧУЖАЯ вставка активного задания, успевшая между
   * нашим снимком и нашей вставкой. И вот здесь исходы расходятся:
   *
   *   - без `ON CONFLICT` конфликт роняет ВЕСЬ оператор, то есть откатывает и
   *     перевод в blocked, и снятие заданий, и убийство хода. Ничего не
   *     произошло, администратор видит отказ и повторяет — состояние целое;
   *   - с `ON CONFLICT DO NOTHING` откатывать нечего: продукт остаётся
   *     блокированным БЕЗ задания на гашение, то есть с работающим
   *     контейнером. Ровно тот исход, ради предотвращения которого всё
   *     написано, и чинится он только повторным гашением, о необходимости
   *     которого никто не узнает.
   *
   * Поэтому конфликт здесь обязан быть ГРОМКИМ. 23505 переводится в понятный
   * отказ ниже.
   *
   * ## ПОЧЕМУ НАЙДЕННЫЙ ПРОДУКТ ОБЯЗАН БЫТЬ ОДИН
   *
   * У `products.slug` есть UNIQUE, у `products.id` — первичный ключ, а у
   * `products.domain` НЕ ТО НИ ДРУГОЕ (проверено по всем семи миграциям).
   * Сегодня домены не повторяются, потому что строятся из уникального слага,
   * но держится это на соглашении, а не на базе. Две строки с одним доменом —
   * и гашение «по жалобе на один продукт» погасило бы заодно соседний.
   * Поэтому правки идут ТОЛЬКО при ровно одном совпадении: `(SELECT count(*)
   * FROM found) = 1` стоит внутри `target`, то есть до всякой записи, а не
   * проверкой постфактум.
   *
   * ## АРХИВНЫЙ ПРОДУКТ — ОТКАЗ, И ОТКАЗ СВОИМ ТЕКСТОМ
   *
   * `archived_at IS NULL` стоит в `target`, а НЕ в `found`, и разница
   * поведенческая. В `found` он превратил бы архивный продукт в «не найден» —
   * администратор пошёл бы искать опечатку в домене, которого не существует.
   * Здесь же архивный находится, не правится и получает свой отказ.
   *
   * Гасить архивный нельзя не из аккуратности: `claimJob` выдаёт задания
   * только по `archived_at IS NULL`, то есть задание на гашение архивного не
   * досталось бы агенту НИКОГДА и навсегда заняло бы `one_active` (сборщик
   * зависших разбирает только продукты в 'provisioning'). Плюс статус
   * 'archived' был бы затёрт на 'blocked' — единственный след архивации в
   * колонке status пропал бы.
   */
  async block(rawKey: string, rawReason: string): Promise<BlockResult> {
    const l = this.lookup(rawKey);
    const reason = typeof rawReason === 'string' ? rawReason.trim() : '';
    // ПРИЧИНА ОБЯЗАТЕЛЬНА, и это не формальность. Общего списка продуктов у
    // администратора нет, уведомлений владельцу кусок 4б не делает — колонка
    // block_reason в карточке остаётся ЕДИНСТВЕННЫМ, из чего владелец узнает,
    // что случилось с его продуктом. Пустая строка здесь дала бы владельцу
    // погашенный продукт без единого слова объяснения.
    if (!reason) {
      throw new BadRequestException(
        'Не сказано, за что гасим: причина попадает в карточку владельца и без неё он не узнает ничего',
      );
    }

    const r = await this.pg
      .query(
      `WITH found AS (
          SELECT p.id, p.slug, p.status, p.archived_at
            FROM products p
           WHERE ${l.sql}
             FOR UPDATE
       ), target AS (
          SELECT f.id
            FROM found f
           WHERE f.archived_at IS NULL
             AND (SELECT count(*) FROM found) = 1
       ), killed_jobs AS (
          UPDATE product_provision_jobs j
             SET status = 'failed', error = $3, finished_at = now()
            FROM target t
           WHERE j.product_id = t.id
             AND j.status IN ('queued','running')
          RETURNING j.id
       ), killed_turns AS (
          -- Ход убивается БЕЗ оглядки на его признаки жизни — этим блокировка
          -- и отличается от сна (см. докблок класса). 'queued' здесь наравне с
          -- 'running': ход, который ещё не забрал раннер, всё равно держит
          -- замок product_turns_one_active и всё равно уехал бы в контейнер,
          -- если бы гашение сорвалось.
          UPDATE product_turns tr
             SET status = 'failed', error = $4, finished_at = now()
            FROM target t
           WHERE tr.product_id = t.id
             AND tr.status IN ('queued','running')
          RETURNING tr.id
       ), marked AS (
          -- sleep_reason НЕ трогается. Продукт мог спать за неуплату до
          -- блокировки, и снятие блокировки вернёт его в 'sleeping': стёртая
          -- причина оставила бы владельца со спящим продуктом без объяснения.
          UPDATE products p
             SET status = 'blocked', block_reason = $2
            FROM target t
           WHERE p.id = t.id
          RETURNING p.id
       ), queued AS (
          INSERT INTO product_provision_jobs (product_id, kind, status)
          SELECT m.id, 'sleep', 'queued'
            FROM marked m
           -- Ссылка на killed_jobs существует ради ПОРЯДКА, а не ради
           -- значения: см. «порядок частей закреплён ссылкой» выше. Без неё
           -- вставка исполняется раньше снятия и падает с 23505.
           --
           -- ON CONFLICT DO NOTHING здесь НЕТ намеренно: он превратил бы
           -- чужую гонку из отката всего оператора в блокированный продукт с
           -- работающим контейнером. См. докблок выше.
           WHERE (SELECT count(*) FROM killed_jobs) >= 0
          RETURNING product_id
       )
       SELECT f.id, f.slug, f.status, (f.archived_at IS NOT NULL) AS archived,
              (SELECT count(*) FROM queued)       AS queued,
              (SELECT count(*) FROM killed_jobs)  AS killed_jobs,
              (SELECT count(*) FROM killed_turns) AS killed_turns
         FROM found f`,
        [l.key, reason, JOB_KILLED_BY_BLOCK, TURN_KILLED_BY_BLOCK],
      )
      .catch((e) => this.explain(e, 'гашение'));

    if (r.rows.length === 0) this.notFound(l);
    if (r.rows.length > 1) {
      // Ни одной строки не тронуто: условие единственности стоит внутри
      // target, то есть до всякой записи.
      throw new ConflictException(
        `По ${l.by} «${l.key}» найден не один продукт, а ${r.rows.length} ` +
          `(${r.rows.map((x: any) => x.slug).join(', ')}). Гасите по слагу или идентификатору.`,
      );
    }

    const row = r.rows[0];
    if (row.archived) {
      throw new ConflictException(
        `Продукт «${row.slug}» уже в архиве — гасить нечего: контейнера нет, домен не отдаётся.`,
      );
    }

    if (Number(row.queued) !== 1) {
      // ПРИ НЫНЕШНЕЙ ФОРМЕ ЗАПРОСА СЮДА НЕ ПОПАСТЬ, и это сказано честно, а не
      // замолчано: раз `marked` дала строку, вставка либо прошла, либо упала
      // 23505 и откатила весь оператор (ловит explain выше).
      //
      // Сторож оставлен на правку, которая разорвёт связь между `marked` и
      // вставкой, — прежде всего на возвращённый `ON CONFLICT DO NOTHING`.
      // Цена ошибки молчаливая и худшая из возможных: продукт помечен
      // блокированным, аренда с него не берётся, правки не принимаются, а
      // контейнер работает и домен отдаёт то, за что продукт погасили.
      this.logger.error(
        `гашение ${row.slug}: продукт переведён в blocked, но задание на гашение НЕ встало ` +
          '(у продукта появилось активное задание) — контейнер работает, повторите гашение',
      );
      throw new ConflictException(
        `Продукт «${row.slug}» помечен блокированным, но задание на гашение не встало: ` +
          'у него появилось активное задание. Повторите гашение.',
      );
    }

    // Журнал — ЕДИНСТВЕННЫЙ след решения администратора: общего списка
    // продуктов нет, уведомлений владельцу кусок 4б не делает, и «кто и за что
    // погасил» через полгода не ответит больше никто.
    this.logger.warn(
      `гашение ${row.slug} (по ${l.by} «${l.key}»): был ${row.status}, причина «${reason}», ` +
        `снято заданий ${row.killed_jobs}, убито ходов ${row.killed_turns}`,
    );

    // Числа приводятся ЯВНО: count() в PostgreSQL — bigint, а драйвер отдаёт
    // bigint строкой (иначе потерял бы точность за 2^53). Без Number() наружу
    // уезжает {"killedTurns":"1"}, и проверка вида `if (r.killedTurns)` у
    // читателя истинна на строке '0'.
    return {
      id: row.id,
      slug: row.slug,
      wasStatus: row.status,
      by: l.by,
      killedJobs: Number(row.killed_jobs),
      killedTurns: Number(row.killed_turns),
    };
  }

  /**
   * Снять блокировку. Тот же оператор наоборот: снять задание на гашение, если
   * агент до него ещё не дошёл, вернуть в 'sleeping' и поставить пробуждение.
   *
   * ## СТАТУС 'sleeping', А НЕ 'running'
   *
   * Перевод в работу делает `promoteReady` по ИЗМЕРИМОМУ факту: раннер на
   * связи и публичный адрес отдал 200. Поставить 'running' здесь значило бы
   * объявить рабочим продукт, контейнер которого ещё даже не начали поднимать,
   * — и всё, что отбирает по 'running' (выдача ходов, списание аренды),
   * поверило бы этому объявлению.
   *
   * Путь отсюда до 'running' уже существует и проверен куском 3: задание
   * 'wake' → агент поднял контейнер → `completeJob` закрыл задание →
   * `promoteReady` увидел свежий heartbeat и ответ 200 → 'running'.
   *
   * ## ПРОБУЖДЕНИЕ СТАВИТСЯ БЕЗУСЛОВНО, А НЕ ПО БАЛАНСУ
   *
   * Соблазн — будить только тех, у кого хватает токенов, и оставить остальных
   * будильнику. Так нельзя: `wakeAffordable` считает бюджет по ТЕКУЩЕМУ
   * балансу, а у продукта с оплаченным вперёд месяцем баланс может быть нулём
   * — администратор снял бы блокировку, и не произошло бы ничего, без единого
   * слова о том, почему.
   *
   * Неплательщик от этого бесплатного хостинга не получает: ближайший оборот
   * `RentService.tick` увидит истёкший `paid_until`, спишет аренду за новый
   * месяц либо усыпит за неуплату — обычным путём и в пределах минуты.
   *
   * ## АКТИВНОЕ ЗАДАНИЕ СНИМАЕТСЯ И ЗДЕСЬ
   *
   * И это не симметрия ради симметрии. У блокированного продукта штатно висит
   * НАШЕ ЖЕ задание на гашение — агент мог до него не дойти. Оставь его, и
   * дальше пробуждение упрётся в частичный уникальный индекс: продукт уедет в
   * 'sleeping', агент заберёт СТАРОЕ задание 'sleep' и погасит контейнер.
   * Снятие блокировки выглядело бы сработавшим и не делало бы ничего.
   */
  async unblock(rawKey: string): Promise<UnblockResult> {
    const l = this.lookup(rawKey);

    const r = await this.pg
      .query(
      `WITH found AS (
          SELECT p.id, p.slug, p.status, p.archived_at
            FROM products p
           WHERE ${l.sql}
             FOR UPDATE
       ), target AS (
          SELECT f.id
            FROM found f
           WHERE f.archived_at IS NULL
             AND f.status = 'blocked'
             AND (SELECT count(*) FROM found) = 1
       ), killed_jobs AS (
          UPDATE product_provision_jobs j
             SET status = 'failed', error = $2, finished_at = now()
            FROM target t
           WHERE j.product_id = t.id
             AND j.status IN ('queued','running')
          RETURNING j.id
       ), marked AS (
          UPDATE products p
             SET status = 'sleeping', block_reason = NULL
            FROM target t
           WHERE p.id = t.id
          RETURNING p.id
       ), queued AS (
          INSERT INTO product_provision_jobs (product_id, kind, status)
          SELECT m.id, 'wake', 'queued'
            FROM marked m
           -- Ссылка ради ПОРЯДКА и отсутствие ON CONFLICT — по тем же двум
           -- причинам, что в block(); там они и разобраны.
           WHERE (SELECT count(*) FROM killed_jobs) >= 0
          RETURNING product_id
       )
       SELECT f.id, f.slug, f.status, (f.archived_at IS NOT NULL) AS archived,
              (SELECT count(*) FROM queued)      AS queued,
              (SELECT count(*) FROM killed_jobs) AS killed_jobs
         FROM found f`,
        [l.key, JOB_KILLED_BY_UNBLOCK],
      )
      .catch((e) => this.explain(e, 'снятие блокировки'));

    if (r.rows.length === 0) this.notFound(l);
    if (r.rows.length > 1) {
      throw new ConflictException(
        `По ${l.by} «${l.key}» найден не один продукт, а ${r.rows.length} ` +
          `(${r.rows.map((x: any) => x.slug).join(', ')}). Снимайте по слагу или идентификатору.`,
      );
    }

    const row = r.rows[0];
    if (row.archived) {
      throw new ConflictException(`Продукт «${row.slug}» в архиве — снимать нечего.`);
    }
    // «Не блокирован» — ОТДЕЛЬНЫЙ отказ, а не «не найден». Продукт есть, ключ
    // верный, и администратору надо сказать именно это: иначе он ищет опечатку
    // там, где её нет, а настоящая причина («кто-то уже снял» или «погасить
    // так и не вышло») остаётся неназванной.
    if (row.status !== 'blocked') {
      throw new ConflictException(
        `Продукт «${row.slug}» не блокирован (сейчас «${row.status}») — снимать нечего.`,
      );
    }

    if (Number(row.queued) !== 1) {
      // Недостижимо при нынешней форме запроса — по той же причине, что в
      // block(), и оставлено тем же сторожем на ту же будущую правку.
      this.logger.error(
        `снятие блокировки ${row.slug}: продукт переведён в sleeping, но пробуждение НЕ встало ` +
          '(у продукта появилось активное задание) — продукт остался спящим',
      );
      throw new ConflictException(
        `Блокировка с «${row.slug}» снята, но пробуждение не встало: ` +
          'у него появилось активное задание. Продукт разбудит будильник при достаточном балансе.',
      );
    }

    this.logger.warn(
      `снятие блокировки ${row.slug} (по ${l.by} «${l.key}»): снято заданий ${row.killed_jobs}, ` +
        'поставлено пробуждение',
    );

    return {
      id: row.id,
      slug: row.slug,
      by: l.by,
      killedJobs: Number(row.killed_jobs),
    };
  }
}
