import { Injectable, Logger, UnprocessableEntityException } from '@nestjs/common';
import { PgService } from '../common/services/pg.service';

/**
 * Сколько продуктов можно одному аккаунту без отдельного решения.
 *
 * Константа, а не колонка с DEFAULT и не строка на каждого: правка умолчания
 * иначе превратилась бы в правку данных всех аккаунтов сразу, а заведённые до
 * неё молча остались бы на старом числе (разобрано в 007_selfservice.sql).
 * Строка в product_user_limits появляется ТОЛЬКО у того, кому предел подняли.
 */
export const DEFAULT_MAX_PRODUCTS = 2;

/**
 * Родительный падеж после числа: «1 продукт», «2 продукта», «5 продуктов».
 *
 * Через Intl.PluralRules, а не своей лесенкой по остаткам: правило русского
 * счёта уже лежит в ICU, и списанная руками копия однажды разошлась бы с ним на
 * 11–14 (это «продуктов», хотя остаток от десяти — единица и двойка). На узле
 * со small-icu локаль 'ru' отваливается к английской и отдаёт 'other' — поэтому
 * 'other' сведён к той же форме, что 'many': «Предел — 2 продуктов» звучит
 * коряво, но остаётся понятным, а падения не даёт.
 */
const FORMS: Record<string, string> = {
  one: 'продукт',
  few: 'продукта',
  many: 'продуктов',
  other: 'продуктов',
};
const plural = (n: number) => FORMS[new Intl.PluralRules('ru').select(n)] ?? FORMS.many;

/**
 * ПОТОЛОК ЧИСЛА ПРОДУКТОВ НА АККАУНТ.
 *
 * Своим сервисом, а не дописью в ProvisioningService: тот уже за 1200 строк и
 * отвечает за заведение, а у предела свой жизненный цикл — его поднимают руками
 * строкой в таблице, и зовут его задача 2 сегодня и админка когда-нибудь.
 *
 * ## ЗАЧЕМ ОН ВООБЩЕ ПОЯВИЛСЯ
 *
 * Вкладка «Продукты» открывается всем (кусок 4б), а первый месяц бесплатный.
 * Вдвоём эти решения означают, что один человек заводит двадцать продуктов —
 * весь потолок клиентской машины — и не платит ничего до следующего месяца.
 * Потолок машины от этого не спасает: он общий, и заполнить его может кто
 * угодно.
 */
@Injectable()
export class LimitsService {
  private readonly logger = new Logger(LimitsService.name);

  constructor(private readonly pg: PgService) {}

  /**
   * Отбить заведение, если у владельца уже столько продуктов, сколько ему
   * положено. Молчит, когда место есть.
   *
   * ## СЧИТАЮТСЯ ВСЕ, КРОМЕ АРХИВНЫХ
   *
   * Спящие и блокированные в том числе. Место занято до АРХИВАЦИИ, а не до
   * остановки: у спящего остаются каталог на машине, контейнер и запись домена,
   * и просыпается он от одного пополнения баланса. Не считать спящих — значит
   * позволить накопить продуктов сверх предела и поднять их все разом. Та же
   * логика, что у потолка машины (hosts.pickForNewProduct считает по
   * `archived_at IS NULL`), и то же поведение сторожит сценарий 86 для
   * блокированного.
   *
   * ## ОДНИМ ЗАПРОСОМ, И СРАВНЕНИЕ СТОИТ В SQL
   *
   * Предел и счёт берутся из ОДНОГО снимка: двумя запросами между ними
   * помещается чужой коммит, и отказ выписывался бы по числам из разных
   * моментов.
   *
   * Сравнение — в SQL, а не в JavaScript, и это не вкусовщина. `count(*)` —
   * bigint, и node-pg отдаёт его СТРОКОЙ, а `max_products` — int4, и он
   * приезжает ЧИСЛОМ (измерено на живой базе, сценарий 92). Пока типы такие,
   * JS-сравнение `used >= allowed` работает случайно — через приведение строки
   * к числу; сделай кто-нибудь `max_products::bigint` или замени COALESCE на
   * второй счётчик, и обе стороны станут строками, а `'10' >= '9'` ложно.
   * Написать на это тест нельзя: сегодня мутация «убрать Number()» зелена, то
   * есть щель есть, а сторожа у неё нет. В SQL типы точные, и щели не остаётся
   * вовсе. Тот же приём, что у потолка машины (`count(*) < h.capacity`).
   *
   * ## ПРЕДЕЛ МЯГКИЙ ПОД ОДНОВРЕМЕННЫМИ ЗАЯВКАМИ — ИЗМЕРЕНО, НЕ ЗАКРЫТО
   *
   * Проверка и вставка продукта — два оператора, а каждый запрос через пул сам
   * себе транзакция: заявки одного залпа видят снимок без чужих строк и
   * проходят все сразу. Снято на тестовой ноде (PostgreSQL 16, предел 2,
   * потолок машины снят, два прогона, Promise.all без барьера):
   *
   *     заявок в залпе   2    3    5   10   20   50
   *     завелось         2    2    3  5–7 10–15 30–31
   *
   * Спека называет ценой «третий продукт вместо двух» — это верно только для
   * залпа из трёх. Клиентская машина рассчитана на двадцать продуктов, то есть
   * один аккаунт забирает её целиком одним залпом: от честной ошибки предел
   * бережёт, от намеренной — нет. Сценарий 95 держит это измерение.
   *
   * Одним оператором не чинится: `INSERT … SELECT` берёт тот же снимок.
   * Закрывается advisory-локом на владельца (PgService.tryAdvisoryLock —
   * выделенное соединение, снятие на нём же) вокруг проверки И вставки; это
   * своя задача, потому что заодно закрывает тот же дефект у потолка машины
   * (сценарий 51м) и трогает самую сложную запись модуля.
   *
   * ## ЧИТАЕТСЯ ФАЙЛ-ЗАКРЫТО
   *
   * Отказ ставится на всё, что не равно явному `false`. Потерянный алиас или
   * пустая выдача дают `undefined`, и мягкое `if (over === true)` открыло бы
   * предел НАСТЕЖЬ и молча — ровно тем способом, которым в этом каталоге уже
   * терялся `product_id` в RETURNING. Сломанный предел обязан запирать
   * заведение, а не отменять себя.
   *
   * ## АДМИНИСТРАТОРА ПРЕДЕЛ НЕ КАСАЕТСЯ — И ЭТО ИЗМЕРЕНО
   *
   * Предел бережёт клиентскую машину и бесплатный месяц. Продукты
   * администратора туда не попадают вовсе: `pickForNewProduct(isAdmin)` уводит
   * их на машины аудитории `own`, у которых свой потолок ёмкости, — то есть
   * админ и так ограничен, просто другим числом и по другому поводу.
   *
   * Цена обратного решения снята с прода 22.09.2026: у аккаунта владельца
   * (79030169187) РОВНО ДВА живых продукта — `demo` и `shop2`. Предел,
   * распространённый на администратора, запер бы владельца в день выката, на
   * его собственной машине с восемнадцатью свободными местами из двадцати, и
   * посоветовал бы ему «написать нам». Обойти это можно только строкой,
   * вписанной в product_user_limits руками на проде, — а 007 нарочно не делает
   * ни одного INSERT, значит такая строка не появится сама и её забудут.
   *
   * Признак берётся оттуда же, откуда его берёт выбор машины, — из `req.user`
   * через CreateInput.isAdmin. Второго понятия «свой пользователь» в заведении
   * не заводится.
   */
  async assertCanCreate(userId: string, isAdmin: boolean): Promise<void> {
    if (isAdmin === true) return;

    const r = await this.pg.query(
      `WITH mine AS (
          SELECT count(*) AS used
            FROM products p
           WHERE p.user_id = $1
             AND p.archived_at IS NULL
       ), cap AS (
          SELECT COALESCE(
                   (SELECT l.max_products FROM product_user_limits l WHERE l.user_id = $1),
                   $2
                 ) AS allowed
       )
       SELECT m.used, c.allowed, m.used >= c.allowed AS over
         FROM mine m, cap c`,
      [userId, DEFAULT_MAX_PRODUCTS],
    );

    const row = r.rows[0];
    if (row?.over === false) return;

    // Число для ТЕКСТА, а не для решения: решение уже принято выше, в SQL.
    // Проверка на конечность — на случай той самой сломанной выдачи, ради
    // которой чтение сделано файл-закрытым: «Предел — NaN продуктов» хуже, чем
    // предел по умолчанию в сообщении об отказе, который и так неправда только
    // в уже сломанном состоянии.
    const raw = Number(row?.allowed);
    const allowed = Number.isFinite(raw) ? raw : DEFAULT_MAX_PRODUCTS;

    // Строка в журнале — единственный способ узнать, что предел кого-то задел:
    // раздел «Сайты и боты» (GET /webhook/admin/products) показывает заведённые
    // продукты, а не отбитые заведения, а триггер пересмотра в спеке —
    // «первая жалоба либо первый случай, когда это заметят».
    this.logger.warn(
      `предел аккаунта: у ${userId} занято ${row?.used} из ${row?.allowed} — заведение отбито`,
    );

    // 422, А НЕ 409, И ЭТО ИЗМЕРЕНО В КУСКЕ 4а, А НЕ ВЫБРАНО ПО ВКУСУ.
    // Кабинет разбирает КОД: на 409 он показывает «Этот адрес уже занят —
    // выберите другой» и текст сервера игнорирует, а всё `>= 500` глушит своей
    // формулировкой (explain() в ProductsListView.tsx). 422 попадает в ветку
    // `p.message`, то есть показывает НАШ текст. Тот же код у отказа по местам
    // на машине — других значений этот маршрут не отдаёт.
    //
    // ТЕКСТ НАЗЫВАЕТ ДЕЙСТВИЕ, И ДЕЙСТВИЕ СУЩЕСТВУЕТ. «Заархивируйте ненужный»
    // писать нельзя: архивации нет ни маршрута, ни кнопки, ни строки кода —
    // `products.archived_at` не пишет НИКТО (проверено грепом по src). Совет
    // сделать недоступное — то же самое, что «попробуйте позже»: человек
    // ищет несуществующую кнопку и не пишет в поддержку.
    throw new UnprocessableEntityException(
      `Предел — ${allowed} ${plural(allowed)} на один аккаунт, и он уже занят. ` +
        'Напишите нам, если нужно больше: поднимем предел вашему аккаунту.',
    );
  }
}
