import { Injectable, Logger, UnprocessableEntityException } from '@nestjs/common';
import { PgService } from '../common/services/pg.service';

/**
 * Машина, выбранная под новый продукт. Ровно три поля — те, что уезжают в
 * строку продукта: метка, адрес и зона доменов.
 *
 * Строка реестра целиком отсюда НЕ возвращается, и это то же решение, что у
 * HostGuard: в ней лежит `agent_token_hash`, а заведение продукта — путь, с
 * которого данные уходят наружу (ответ кабинету, лог прокси). Отдавать надо
 * ровно то, что записывается.
 */
export interface ChosenHost {
  id: string;
  /** `product_hosts.public_ip` — из inet драйвер отдаёт строку. */
  publicIp: string;
  domainSuffix: string;
}

/**
 * Реестр машин под продукты: кто принимает новый продукт.
 *
 * Своим сервисом, а не дописью в ProvisioningService: тот за 1200 строк и
 * отвечает за жизненный цикл продукта.
 */
@Injectable()
export class HostsService {
  private readonly log = new Logger(HostsService.name);

  constructor(private readonly pg: PgService) {}

  /**
   * Машина под новый продукт: есть место, принимает новые, нужная аудитория.
   *
   * ## АУДИТОРИЯ ВЫВОДИТСЯ ИЗ ПРИЗНАКА АДМИНИСТРАТОРА, И ИЗ НЕГО ОДНОГО
   *
   * Признак приезжает с запроса (`request.user.isAdmin`, кладёт JwtGuard из
   * `ai_profiles_consolidated.isadmin`) — тот же самый, которым закрыта вкладка
   * «Продукты» в Студии (`user?.isAdmin` в spirits_front/src/pages/StudioPage.tsx).
   * Второго понятия «свой пользователь» здесь не заводится: список админов,
   * перечисленный в окружении или в своей таблице, разошёлся бы с кабинетом
   * молча — вкладка открыта, а продукт уезжает на клиентскую машину.
   *
   * `=== true`, а не приведение к истинности. Признак проходит через `any`
   * (`@CurrentUser() user: any`), и строка `'false'` из чужого вызова
   * истинна. Строгое сравнение уводит любое НЕ-`true` в `clients`, то есть в
   * безопасную сторону: чужой продукт рядом с боевыми — та самая авария, ради
   * которой машины и разделяют, а продукт владельца на клиентской машине
   * просто работает.
   *
   * ## ПОТОЛОК СЧИТАЕТ ВСЕ ПРОДУКТЫ МАШИНЫ, КРОМЕ АРХИВНЫХ
   *
   * Спящих в том числе. Спящий контейнер остановлен и памяти не ест — считать
   * его выглядит расточительным, но НЕ считать опаснее: двадцать спящих
   * просыпаются от одного пополнения баланса, и машина, заполненная «по
   * живым», ляжет. Место занято до архивации, а не до остановки.
   *
   * Считает база, а не Node. `count(*)` приезжает из node-pg СТРОКОЙ (bigint
   * не влезает в number), и сравнение `count < capacity`, вынесенное в
   * JavaScript, сравнивало бы строку с числом — `'10' < 9` ложно, `'9' < 10`
   * ложно тоже. Ровно этот отказ уже ловили в куске 4а у гварда агента.
   *
   * ## ПЕРВАЯ ПО МЕТКЕ, А НЕ САМАЯ СВОБОДНАЯ
   *
   * `ORDER BY h.id` — детерминированный «набиваем по очереди». Балансировка
   * сверх «есть место / нет места» вынесена из куска сознательно; выбор без
   * ORDER BY отдавал бы машину в порядке, который решает планировщик, то есть
   * менялся бы от статистики таблицы.
   *
   * ## ПОТОЛОК МЯГКИЙ ПОД ОДНОВРЕМЕННЫМИ ЗАЯВКАМИ — ИЗМЕРЕНО, НЕ ЗАКРЫТО
   *
   * Выбор и вставка продукта — два разных оператора, а каждый запрос через пул
   * сам себе транзакция. Два заведения, начатых в одну миллисекунду, видят
   * снимок БЕЗ строки соседа и оба проходят последнее свободное место
   * (сценарий 51м, измерено на PostgreSQL 16.14). Одним оператором это НЕ
   * чинится: `INSERT … SELECT … FROM product_hosts` берёт тот же снимок, а
   * `FOR UPDATE` на строке машины лочит её после вычисления условия и на
   * подзапрос счёта не влияет. Настоящее закрытие — выделенное соединение и
   * явная транзакция (как у 005 в products.service), где второй командой
   * берётся НОВЫЙ снимок.
   *
   * Не сделано, и цена названа: сегодня заведение доступно только админам
   * (вкладка закрыта признаком isAdmin), то есть «одновременно» означает двух
   * владельцев, жмущих кнопку в одну миллисекунду, а перебор на единицу стоит
   * ~90 МБ. ТРИГГЕР ПЕРЕСМОТРА — кусок 4б: вкладка открывается всем, и тогда
   * пятьдесят одновременных заявок кладут машину при потолке двадцать.
   */
  async pickForNewProduct(isAdmin: boolean): Promise<ChosenHost> {
    const audience = isAdmin === true ? 'own' : 'clients';

    // ОДИН ЗАПРОС, ТРИ ОТВЕТА: машина плюс два счётчика, которыми различаются
    // причины отказа. Тот же приём, что в HostGuard, и по той же причине —
    // «мест нет» и «реестра нет» лечатся разными руками, а выглядят одинаково.
    //
    // LEFT JOIN к `(SELECT 1)`, а не голый SELECT с LIMIT: при пустом отборе
    // обычный запрос вернул бы НОЛЬ СТРОК, и счётчики не приехали бы вместе с
    // отказом — пришлось бы ходить в базу второй раз именно в тот момент, ради
    // которого всё написано. Здесь строка ровно одна всегда.
    //
    // Поля машины берутся из ОДНОГО подзапроса (CTE), а не тремя скалярными с
    // одинаковым ORDER BY: три подзапроса сходятся на одной машине только пока
    // все три условия совпадают дословно, и правка одного из них дала бы метку
    // одной машины с адресом другой — ровно то расхождение, ради снятия
    // которого убраны константы адреса и зоны.
    const r = await this.pg.query(
      `WITH chosen AS (
          SELECT h.id, h.public_ip, h.domain_suffix
            FROM product_hosts h
           WHERE h.accepts_new
             AND h.audience = $1
             AND (SELECT count(*) FROM products p
                   WHERE p.host_id = h.id AND p.archived_at IS NULL) < h.capacity
           ORDER BY h.id
           LIMIT 1
       )
       SELECT c.id, c.public_ip, c.domain_suffix,
              (SELECT count(*) FROM product_hosts) AS total,
              (SELECT count(*) FROM product_hosts WHERE audience = $1) AS in_audience
         FROM (SELECT 1) AS always
         LEFT JOIN chosen c ON true`,
      [audience],
    );

    const row = r.rows[0];
    if (!row?.id) throw this.noRoom(audience, row);
    return { id: row.id, publicIp: row.public_ip, domainSuffix: row.domain_suffix };
  }

  /**
   * Отказ, НАЗЫВАЮЩИЙ ПРИЧИНУ. Три разные причины, три разных текста и два
   * разных уровня в журнале.
   *
   * «Попробуйте позже» здесь было бы неправдой: ни одна из трёх сама не
   * пройдёт, пока владелец не добавит машину, не откроет её для новых или не
   * заведёт реестр. Человек, которому сказали «позже», повторяет нажатие
   * сутками и не пишет в поддержку — то есть отказ становится невидимым с
   * обеих сторон.
   *
   * ПУСТОЙ РЕЕСТР — СОСТОЯНИЕ ДОСТИЖИМОЕ, а не теоретическое: 005 нарочно
   * сделана безвредным no-op при незаполненном PRODUCT_HOST_TOKEN (сценарий
   * 40в), и на свежем окружении реестр пуст. Без отдельного текста это
   * выглядело бы как «машины переполнены», и владелец пошёл бы добавлять
   * вторую машину вместо того, чтобы дописать переменную.
   *
   * КОД ОТВЕТА — 422, И ЭТО ИЗМЕРЕНО, А НЕ ВЫБРАНО ПО ВКУСУ.
   *
   *   - 409 (как предлагал план) кабинет РАЗБИРАЕТ ПО КОДУ и показывает «Этот
   *     адрес уже занят — выберите другой», игнорируя текст сервера
   *     (`explain()` в spirits_front/src/components/products/ProductsListView.tsx:
   *     «409 значит „слаг занят“ и чинится сменой адреса»). Владелец
   *     переименовывал бы продукт до бесконечности — отказ, выглядящий другим
   *     отказом;
   *   - 503 семантически точнее всего, но кабинет глушит текст у всего `>= 500`
   *     («Сервер не принял продукт») — сознательно, чтобы не показывать
   *     человеку «Internal server error». Причина пропала бы;
   *   - 400 отдаёт текст, но объявляет виноватым запрос, а он в порядке;
   *   - 403 отдаёт текст, но ходит по ветке apiClient, которая при одном
   *     значении тела выкидывает пользователя на экран входа.
   *
   * 422 попадает в ветку `p.message` кабинета, то есть показывает НАШ текст, и
   * ни с одним другим значением этого маршрута не сталкивается.
   *
   * МЕТКИ МАШИН В ТЕКСТ НЕ УЕЗЖАЮТ — по тому же правилу, по которому из выборки
   * кабинета вычеркнуты host_ip и checkout_path: внутренняя топология не
   * показывается в браузере. В журнал она уезжает вся.
   */
  private noRoom(audience: string, row: any): UnprocessableEntityException {
    // Number() обязателен: count(*) — bigint, и node-pg отдаёт его СТРОКОЙ.
    // `row.total === 0` ложно всегда, и пустой реестр молча превратился бы в
    // «мест нет».
    const total = Number(row?.total ?? 0);
    const inAudience = Number(row?.in_audience ?? 0);

    if (total === 0) {
      this.log.error(
        'реестр машин пуст: завести продукт некуда. Машина заводится миграцией 005 ' +
          'из PRODUCT_HOST_TOKEN либо строкой в product_hosts',
      );
      return new UnprocessableEntityException(
        'Хостинг продуктов ещё не настроен — завести продукт пока некуда. Мы уже знаем.',
      );
    }

    if (inAudience === 0) {
      this.log.error(
        `в реестре нет ни одной машины с audience=${audience} (всего машин ${total}): ` +
          'продукты этой аудитории завести некуда',
      );
      return new UnprocessableEntityException(
        'Хостинг для таких продуктов ещё не открыт — завести продукт пока некуда. Мы уже знаем.',
      );
    }

    // Не error: переполнение — не поломка сервера, а исчерпанный ресурс. Но и
    // не debug — это первый и единственный признак того, что пора добавлять
    // машину (риск «машины кончаются, владелец не заметил»).
    this.log.warn(
      `свободных мест нет: ни одна из ${inAudience} машин audience=${audience} ` +
        'не принимает новый продукт (потолок исчерпан либо accepts_new снят)',
    );
    return new UnprocessableEntityException(
      'Свободных мест на машинах нет — новый продукт пока завести некуда. Мы уже знаем.',
    );
  }
}
