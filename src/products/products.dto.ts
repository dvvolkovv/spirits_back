import { Transform } from 'class-transformer';
import {
  IsBoolean,
  IsIn,
  IsInt,
  IsObject,
  IsOptional,
  IsString,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
} from 'class-validator';
import { SLUG_RE } from './provisioning.service';

/**
 * ТЕЛА ЗАПРОСОВ ПРОВЕРЯЮТСЯ ЗДЕСЬ, А НЕ «НА ВСЯКИЙ СЛУЧАЙ».
 *
 * ValidationPipe в main.ts поднят с `whitelist: false`, то есть лишние поля он
 * не срезает, а без DTO не проверяет и типы: метатип тела становится `Object`,
 * и труба пропускает что угодно. Практические последствия измерены:
 *   - `{ ok: 'нет' }` — непустая строка, то есть истина: отчёт агента об
 *     ОТКАЗЕ записывается как успех, продукт получает порт и уезжает в
 *     running, не будучи развёрнутым;
 *   - строковый `'8003'` уезжает прямо в `COALESCE($2, port)` по колонке int и
 *     роняет запись 500-й уже внутри отчёта — задание остаётся в running до
 *     сборщика зависших.
 *
 * Сторож связки «маршрут ↔ этот файл» — products.routes.spec.ts: он берёт
 * метатип тела из метаданных САМОГО МАРШРУТА и гоняет через трубу,
 * собранную настройками из main.ts.
 */

/** Отчёт агента хоста о развёртывании. Приходит с чужой машины. */
export class CompleteJobDto {
  // Строго boolean: от него зависит, каким путём пойдёт completeJob, и
  // «истинность» строки здесь была бы не проверкой, а лотереей.
  @IsBoolean()
  ok!: boolean;

  // Порт выбирает агент — только он знает занятые. У бота его нет вовсе,
  // поэтому необязателен; COALESCE в completeJob именно поэтому и стоит.
  //
  // @IsInt, а не @IsNumber: 8003.5 уедет в COALESCE($2, port) по колонке int
  // и уронит запись 500-й уже внутри отчёта агента. Разница между этими двумя
  // декораторами проверяется отдельным тестом — на глаз она не видна.
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(65535)
  port?: number;

  /**
   * Причина отказа. БЕЗ потолка длины, и это решение, а не недосмотр.
   *
   * Сюда уезжает `e?.message` шага провижининга — `Command failed: docker
   * build …` вместе со stderr, где две тысячи символов норма. Отбой по длине
   * означал бы 400 в ответ агенту, а агент хоста отчёт в try не заворачивает:
   * отказ всплыл бы из цикла опроса неперехваченным и убил бы процесс. Тогда
   * задание висит в running до сборщика зависших и заканчивается
   * формулировкой про срок — неверной, потому что агент отчитался.
   *
   * Причина — диагностика, а не управляющее значение: длинная строка ничего
   * не ломает, колонка text. Режется она на СЕРВЕРЕ, в маршруте (см.
   * ERROR_MAX в host.controller.ts), а не отбивается. Этим она принципиально
   * отличается от `ok` и `port`, где тип решает, каким путём пойдёт запись.
   */
  @IsOptional()
  @IsString()
  error?: string;
}

/** Заведение продукта кнопкой в кабинете. */
export class CreateProductDto {
  // Подрезка ДО проверки длины: без неё '   ' проходит @MinLength(1) —
  // пробелы считаются символами, — и в кабинете появляется продукт с пустым
  // именем, который дальше никак не назвать (имя менять нечем).
  // Нестроковое значение пропускается как есть, чтобы его отбил @IsString.
  @Transform(({ value }) => (typeof value === 'string' ? value.trim() : value))
  @IsString()
  @MinLength(1)
  @MaxLength(80)
  name!: string;

  // Форма слага — ОДНА на весь модуль, и живёт она в provisioning.service.ts
  // рядом с объяснением, почему дефис разрешён только внутри ('-rf' уезжает
  // аргументом docker/nginx). Вторая копия регекспа здесь означала бы, что
  // однажды они разойдутся, и сервис начнёт отбивать то, что труба пропустила.
  @IsString()
  @Matches(SLUG_RE)
  slug!: string;

  // Форма продукта решает, публикуется ли порт наружу и заводится ли vhost.
  // Незнакомое значение отбивает и сервис, но здесь оно не доходит даже до
  // проверки занятости слага.
  @IsIn(['site', 'bot'])
  kind!: 'site' | 'bot';

  // Только «это объект» (массив и строка отсекаются): имена и значения
  // секретов проверяет create() — там же, где они шифруются, и там же, где
  // объясняется, почему пустая строка в секрете хуже отсутствия секрета.
  @IsOptional()
  @IsObject()
  secrets?: Record<string, string>;
}
