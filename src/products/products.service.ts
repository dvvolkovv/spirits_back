import { Injectable, Logger, NotFoundException, OnModuleInit } from '@nestjs/common';
import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { PgService } from '../common/services/pg.service';

export interface ProductRow {
  id: string;
  user_id: string;
  name: string;
  slug: string;
  status: string;
  kind: string;
  domain: string | null;
  runner_seen_at: string | null;
  provision_error: string | null;
  // До какого момента оплачена аренда. Без `| null`: колонка NOT NULL с
  // DEFAULT (миграция 004), пустой она не бывает ни у одной строки.
  paid_until: string;
  // Почему спит. NULL — не спит либо причина не записана; см. 004 о том,
  // почему это не пустая строка.
  sleep_reason: string | null;
  // За что погашен администратором (миграция 007). Своя колонка, а не
  // `sleep_reason`: путь отказа задания сна обнуляет ту — см. 007.
  block_reason: string | null;
  created_at: string;
}

/**
 * Файлы схемы модуля в порядке применения. ОДИН список на репозиторий: его
 * читает и onModuleInit, и интеграционный сьют, который накатывает схему теми
 * же файлами. Пока списков было два, они описывали схему в двух местах — и
 * разошлись бы молча: сьют гоняет запросы по базе без новой колонки и падает с
 * «column does not exist» там, где ошибка на самом деле в списке.
 *
 * Порядок — это и есть описание схемы. 002 навешивает колонки на таблицу,
 * которую создаёт 001. 003 и 004 формально ни от кого не зависят (003 — своя
 * таблица; 004 расширяет то, что завела 002), но едут по номерам: список,
 * допускающий перестановку, перестанут читать как порядок.
 *
 * 006 зависит СРАЗУ ОТ ДВУХ предшественниц, и обе обязаны стоять раньше: она
 * перестраивает таблицу, которую заводит 003, и вешает внешний ключ на реестр,
 * который заводит 005.
 *
 * 007 формально не зависит ни от кого (она расширяет словарь, заведённый 002, и
 * заводит свою таблицу), но порядок здесь — это и есть описание схемы, и он
 * идёт по номерам. Важнее другое: её значение словаря `blocked` дописано И в
 * 002, И в 004 — иначе те два файла, едущие ПЕРЕД ней при каждом старте API,
 * отказывали бы на первом же блокированном продукте. См. длинный блок в 007.
 *
 * 008 ни от кого не зависит функционально: её единственная строка ссылается
 * на products(id), которую заводит 001, а в общем словаре `kind` очереди
 * заданий она не участвует вовсе — тот объявлен только в 004 (008
 * обязательная и потому не несёт ни одного ADD CONSTRAINT, см. её шапку).
 * Порядок здесь — по номеру, как у 007.
 */
export const MIGRATIONS = [
  '001_products.sql',
  '002_provisioning.sql',
  '003_host_agent.sql',
  '004_rent.sql',
  '005_hosts.sql',
  '006_host_agent_per_host.sql',
  '007_selfservice.sql',
  '008_domains.sql',
] as const;

/**
 * Миграции, чей отказ обязан РОНЯТЬ СТАРТ, а не уходить строкой в лог.
 *
 * Обычное поведение applyMigration — «записал отказ и поехал дальше», и оно
 * осознанное: схема продуктов не должна ронять чат, оплаты и вход. Но 005
 * заводит то, БЕЗ ЧЕГО ОСТАЛЬНОЙ МОДУЛЬ НЕВЕРЕН: гвард агента превращает токен
 * в метку машины запросом к product_hosts, выдача заданий фильтрует по
 * products.host_id. Молча не применившаяся 005 — это не «одна недостающая
 * колонка», а 500 на каждый опрос агента: ни одного заведения, ни одного сна,
 * ни одного пробуждения — и ни одной строки о причине.
 *
 * Сюда же попадает вторая половина той же мысли: 005 отказывает НАРОЧНО, когда
 * продукт не сопоставился с машиной по адресу. Отказ, уходящий в лог, оставил
 * бы этот случай незамеченным — а именно ради того, чтобы его заметили, он и
 * написан.
 *
 * Цена названа честно: единственная ситуация, в которой 005 роняет старт на
 * живых данных, — живой продукт, чьего адреса нет в реестре. Продолжать в ней
 * значит выдавать заданиям чужую машину или терять продукт из выдачи молча.
 *
 * 006 попадает сюда ПО ДРУГОЙ ПРИЧИНЕ, и её стоит назвать отдельно. Выдачу
 * заданий она не трогает вовсе: без неё продукты по-прежнему уезжают каждый на
 * свою машину. Ломается одна вещь — правдивость индикатора, и ломается в
 * сторону зелёного. Все пути отказа проверки в кабинете отвечают «агент жив»
 * нарочно (тревога, выведенная из СВОЕГО отказа, отправляет владельца чинить
 * исправную машину — см. products.controller.ts), поэтому не применившаяся 006
 * даёт не «диагностики нет», а «диагностика горит зелёным всегда». Это ровно та
 * ложь, ради снятия которой написан кусок, и отличить её от исправной работы
 * снаружи нечем.
 *
 * Цена при этом близка к нулю: у 006 нет ни одного ЗАПЛАНИРОВАННОГО отказа —
 * она вся под проверкой формы и на уже перестроенной базе не делает ничего.
 * Сработать этот флаг может только на действительно сломанном выкате.
 *
 * 008 попадает сюда ПРЕВЕНТИВНО, до того как в модуле появится код, который
 * её реально использует: таблицу станут читать выдача заданий агенту
 * (claimJob, задания ЛЮБОГО вида, не только 'domain') и выборка продуктов
 * кабинета (COLUMNS). Молча не применившаяся 008 в тот момент — это уже не
 * «нет своего домена», а 42P01 на каждом опросе агента (ни одного заведения,
 * ни одного сна, ни одного пробуждения) и 500 на списке кабинета.
 * deploy.sh jest не гоняет, а прод-smoke продукты не трогает вовсе —
 * необязательная 008 проехала бы зелёными test и smoke и молча уронила бы
 * модуль продуктов на проде уже после того, как этот код появится, а
 * разбираться пришлось бы по недосчитанным продуктам, а не по строке в логе.
 *
 * Цена обязательности здесь такая же, как у 006: в файле нет ни одного
 * ЗАПЛАНИРОВАННОГО отказа — только CREATE ... IF NOT EXISTS, а на уже
 * накатанной базе он не делает ничего. Сработать этот флаг может только на
 * действительно сломанном выкате — кроме ОДНОГО известного и ожидаемого
 * исключения. На ПЕРВОМ выкате (пока таблицы ещё нет) PM2-кластер поднимает
 * несколько воркеров параллельно, и если два одновременно доходят до этого
 * CREATE TABLE IF NOT EXISTS, проигравший ловит 23505 на системном индексе
 * pg_type_typname_nsp_index (CREATE TABLE неявно заводит строку в pg_type) и
 * падает на старте — ровно один раз. PM2 поднимает воркер заново, таблица к
 * этому моменту уже создана победителем, и повторный старт — чистый no-op.
 * Та же гонка в равной мере касается 005 и 006 (они настолько же
 * обязательны и настолько же не защищены от параллельного применения);
 * системное лечение — advisory-лок вокруг всей накатки миграций, отдельной
 * задачей, а не точечно для 008.
 */
const FATAL_MIGRATIONS: ReadonlySet<string> = new Set<string>([
  '005_hosts.sql',
  '006_host_agent_per_host.sql',
  '008_domains.sql',
]);

/**
 * Имя параметра сессии, которым 005 получает хеш токена агента машины `own`.
 *
 * Именно хеш, а не токен: digest() живёт в pgcrypto, а на проде 21.09.2026
 * стоят только citext и plpgsql — считать sha256 внутри SQL там нечем.
 * Побочно это и лучше: в Postgres не уезжает даже то, что можно предъявить.
 */
const OWN_HOST_TOKEN_GUC = 'linkeon.own_host_token_sha256';

// Список колонок перечислен явно и собран ПО КАБИНЕТУ: здесь ровно те поля,
// которые объявлены в `interface Product` фронта (spirits_front
// src/services/productsApi.ts), плюс user_id.
//
// Двух колонок здесь нет по соображениям безопасности: runner_token_hash —
// хеш токена доступа к клиентской VM, secrets_encrypted — шифротекст секретов
// продукта. Эти методы обслуживают клиента, и ни то, ни другое ему не нужно ни
// в каком виде. Заменить перечисление на SELECT * нельзя: обе колонки уедут в
// ответ молча, и следующая секретная колонка тоже. Сторож —
// products.access.spec.ts.
//
// Остальных нет по другой причине — они не секреты, но и не дело кабинета.
// host_ip, checkout_path, build_cmd, restart_cmd, health_url, repo_url и
// claude_session_id описывают, КАК продукт развёрнут на нашей машине: их читают
// агент хоста и раннер внутри контейнера, каждый своим запросом
// (runner.guard.ts перечисляет их отдельно и для себя). В браузере им делать
// нечего — это внутренняя топология, которая через кабинет утекает в консоль,
// в расширения и в снимок вкладки. Ровно тем же приёмом и по той же причине
// собирает ответ create() в products.controller.ts.
//
// kind и provision_error перечислены здесь не для полноты: без них карточка
// отказа в кабинете показывает «сервер не передал причину» при заполненной
// колонке в базе, а бот выглядит сайтом. Колонки завела миграция 002, и
// перечисление — единственное место, которое надо было при этом дописать;
// пропуск ничего не ломает на сервере и потому не виден ни одним его тестом.
// port не перечислен намеренно: это порт на петле хоста, клиенту он не нужен
// и в ответ уходить не должен.
//
// paid_until и sleep_reason — аренда (миграция 004). Не топология и не секрет:
// это ровно то, что карточка обязана показать владельцу вместо молчаливого
// «остановлен» — до какого числа оплачено и почему продукт спит.
//
// block_reason — гашение администратором (миграция 007), и здесь он по той же
// причине, что и sleep_reason: статус 'blocked' сам по себе объясняет владельцу
// ровно ничего. Без этой колонки карточка показала бы «остановлен» человеку,
// который пойдёт искать поломку у себя, — а общего списка продуктов у
// администратора нет, то есть спросить его владельцу больше негде.
//
// user_id остаётся, хотя фронт его не читает: это id самого спрашивающего
// (WHERE user_id = $1), то есть не утечка, а подтверждение того, чьи продукты
// приехали. На него же опирается сторож формы выборки в products.access.spec.ts.
const COLUMNS = `id, user_id, name, slug, status, kind, domain,
                 runner_seen_at, provision_error, paid_until, sleep_reason,
                 block_reason, created_at`;

@Injectable()
export class ProductsService implements OnModuleInit {
  private readonly logger = new Logger(ProductsService.name);

  constructor(private readonly pg: PgService) {}

  async onModuleInit() {
    // Последовательно, а не Promise.all: порядок из MIGRATIONS — это и есть
    // описание схемы (см. доку константы).
    for (const file of MIGRATIONS) {
      await this.applyMigration(file);
    }
  }

  async list(userId: string): Promise<ProductRow[]> {
    const r = await this.pg.query(
      `SELECT ${COLUMNS} FROM products
        WHERE user_id = $1 AND archived_at IS NULL
        ORDER BY created_at DESC`,
      [userId],
    );
    return r.rows;
  }

  /**
   * Владелец в WHERE, а не в проверке после выборки. Разница между «нет
   * такого» и «есть, но не твой» — это утечка существования чужих продуктов.
   */
  async getOwned(id: string, userId: string): Promise<ProductRow> {
    const r = await this.pg.query(
      `SELECT ${COLUMNS} FROM products
        WHERE id = $1 AND user_id = $2 AND archived_at IS NULL`,
      [id, userId],
    );
    if (!r.rows[0]) throw new NotFoundException('Product not found');
    return r.rows[0];
  }

  /**
   * Модуль накатывает свою схему сам: общий runner миграций на проде застрял
   * на base/001 и не докатывает ничего после. Тот же приём в custom-agents и
   * tg-bot.
   *
   * ВНИМАНИЕ по порядку кандидатов: в nest-cli.json нет секции assets, поэтому
   * .sql в dist не копируется вообще. На проде существует ВТОРОЙ путь (через
   * src), а не первый. Первый оставлен на случай, если assets когда-нибудь
   * добавят. Не удаляй второй как «dev-фолбэк» — это выключит миграции молча.
   */
  private async applyMigration(filename: string) {
    const candidates = [
      path.join(__dirname, 'migrations', filename),
      path.join(__dirname, '..', '..', 'src', 'products', 'migrations', filename),
    ];
    let found = false;
    let lastError: Error | null = null;
    for (const p of [...new Set(candidates)]) {
      if (!fs.existsSync(p)) continue;
      found = true;
      try {
        await this.runMigration(filename, fs.readFileSync(p, 'utf8'));
        this.logger.log(`products migration ${filename} applied from ${p}`);
        return;
      } catch (e: any) {
        // Ошибка запоминается, а не только печатается: у обязательной миграции
        // она обязана доехать до того, кто читает падение старта. «Не
        // применилась» без причины отправляет оператора искать её в логах
        // Postgres.
        lastError = e;
        this.logger.error(`products migration ${filename} failed (${p}): ${e.message}`);
      }
    }
    if (found) {
      this.logger.error(`products migration ${filename} was found but did not apply on any candidate path`);
    } else {
      this.logger.warn(`products migration ${filename} not found, skipping`);
    }
    if (FATAL_MIGRATIONS.has(filename)) {
      // Бросается ПОСЛЕ перебора всех путей, а не внутри цикла: второй путь
      // (через src) — это тот, по которому миграции применяются на проде, и
      // отказ на первом не должен мешать ему отработать.
      throw new Error(
        `products migration ${filename} обязательна и не применилась: ` +
          (lastError?.message ?? 'файл не найден ни по одному из путей'),
      );
    }
  }

  /**
   * Применить текст миграции. Обычные едут через пул одним запросом, как и
   * прежде; тем, кому нужен параметр сессии, отводится ВЫДЕЛЕННОЕ соединение и
   * ЯВНАЯ транзакция.
   *
   * Без выделенного соединения это не работает, и не работает ТИХО. Измерено на
   * PostgreSQL 16.14 через настоящий pg.Pool:
   *
   *   set_config('linkeon.x', 'секрет', true) отдельным pool.query(), затем
   *   current_setting('linkeon.x') следующим pool.query()  →  ПУСТАЯ СТРОКА.
   *
   * Не ошибка — пустая строка: параметр живёт до конца транзакции, а через пул
   * каждый запрос сам себе транзакция; имя же в сессии остаётся заведённым,
   * поэтому строгий current_setting не жалуется, а отдаёт сброшенное значение.
   * Миграция, считающая по такому значению хеш токена, применилась бы успешно и
   * записала бы в реестр хеш пустой строки.
   *
   * Сессионный вариант (is_local = false) чинит это лишь на глаз: тот же
   * замер показывает значение на СВОЁМ соединении и NULL на соседнем, стоит
   * пулу быть занятым. То есть зелено в тестах и наугад в проде — плюс токен,
   * оставшийся в состоянии соединения, которое пул отдаст следующему запросу.
   *
   * Параметром запроса в сам INSERT токен тоже не подставить: в файле несколько
   * операторов, а с параметрами драйвер уходит в расширенный протокол, где это
   * `cannot insert multiple commands into a prepared statement` (измерено там
   * же).
   */
  private async runMigration(filename: string, sql: string) {
    const settings = this.sessionSettings(filename);
    if (!settings.length) {
      await this.pg.query(sql);
      return;
    }

    const client = await this.pg.getClient();
    try {
      // BEGIN первым: set_config(..., true) вне явной транзакции сбросится
      // ровно в тот момент, когда закончится его собственный запрос.
      await client.query('BEGIN');
      for (const [name, value] of settings) {
        await client.query('SELECT set_config($1, $2, true)', [name, value]);
      }
      await client.query(sql);
      await client.query('COMMIT');
    } catch (e) {
      // Откат своей ошибкой не заслоняет исходную: соединение всё равно
      // возвращается в пул, а причина отказа нужна вызывающему.
      await client.query('ROLLBACK').catch(() => undefined);
      throw e;
    } finally {
      client.release();
    }
  }

  /** Параметры сессии, нужные конкретному файлу миграции. */
  private sessionSettings(filename: string): [string, string][] {
    if (filename !== '005_hosts.sql') return [];

    const token = process.env.PRODUCT_HOST_TOKEN ?? '';
    if (!token) {
      // Не бросаем здесь сами: пустой токен — это состояние окружения, а не
      // сломанная схема, и ронять им чат с оплатами незачем. На живых данных
      // 005 всё равно откажет — сопоставлять продукты будет не с чем, — а на
      // пустой базе (тесты, свежее окружение) отсутствие машины безвредно.
      this.logger.error(
        'PRODUCT_HOST_TOKEN не задан: машина own в реестр не попадёт, ' +
          'и агент хоста не получит ни одного задания',
      );
      return [[OWN_HOST_TOKEN_GUC, '']];
    }
    return [[OWN_HOST_TOKEN_GUC, crypto.createHash('sha256').update(token).digest('hex')]];
  }
}
