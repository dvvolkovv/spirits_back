export type JobKind = 'provision' | 'sleep' | 'wake' | 'domain';

/**
 * Задание, выданное агенту хоста. Единственное место, где открытый
 * runner-токен вообще существует: агенту он отдаётся один раз, в теле ответа.
 */
export interface ClaimedJob {
  jobId: string;
  productId: string;
  slug: string;
  // Человеческое имя продукта. Уезжает в каркас (заголовок страницы сайта,
  // имя бота) — слаг там не годится: 'my-shop' вместо «Мой магазин».
  // Агент берёт его из задания: другого способа узнать имя у него нет, а
  // undefined в каркасе виден только глазами, уже на готовом продукте.
  name: string;
  kind: ProductKind;
  /**
   * Вид работы. БЕЗ него агент разворачивает продукт заново на задании
   * «усыпить»: упирается в занятый каталог, и владелец читает про каталог
   * вместо сна.
   *
   * Поле обязательное, хотя колонка в базе имеет DEFAULT: значение берётся из
   * строки задания, а не подставляется здесь. Подстановка `?? 'provision'` в
   * коде была бы мёртвой (колонка NOT NULL DEFAULT 'provision') и при этом
   * прятала бы настоящую поломку — потерянный алиас в SELECT.
   */
  jobKind: JobKind;
  /**
   * Порт продукта, как он записан в базе. Нужен ПРОБУЖДЕНИЮ: домен возвращают
   * на тот же порт, с которого его сняли, а знает его только сервер. Ровно
   * так же он нужен заданию domain: конфиг своих имён в режиме прокси ведёт
   * на этот порт.
   *
   * У заведения он NULL и обязан быть NULL: порт там ВЫБИРАЕТ агент (первый
   * свободный на хосте) и присылает его обратно в отчёте.
   */
  port: number | null;
  /**
   * Открытый runner-токен. Есть ТОЛЬКО у заведения — и ключа нет вовсе, а не
   * пустая строка, когда его не выпускали.
   *
   * Сон и пробуждение токен не поворачивают: раннер живёт ВНУТРИ контейнера, и
   * после пробуждения тот же процесс обязан продолжить работать со старым
   * токеном. Повёрнутый на пробуждении хеш означал бы контейнер, который
   * поднялся и не может аутентифицироваться, — то есть продукт, который
   * «разбудили» в мёртвое состояние.
   */
  runnerToken?: string;
  secrets: Record<string, string>;
  /**
   * Свои имена продукта (product_domains в issuing или active). Приезжают в
   * КАЖДОМ задании: любая перегенерация конфига строит его из того, что
   * прислал сервер, и потерять домен не может. У отвязки (removing) и у
   * задания-уборки (строки домена нет) — пусто: агент понимает намерение
   * задания domain именно по пустоте списка.
   *
   * Отказавшей заявки (failed — например, orphan_issuing после потерянного
   * отчёта) здесь тоже нет, хотя сертификат на машине мог остаться: ближайший
   * сон или пробуждение перегенерирует конфиг без своих имён, и домен
   * вернётся только после «Проверить снова». Так задумано — в конфиге живут
   * лишь имена, чей выпуск сервер считает состоявшимся или идущим.
   */
  customNames: string[];
  /**
   * Режим конфига для задания domain. Вычисляет сервер: агенту нечем узнать
   * статус продукта. Спящий, но уже проснувшийся (пробуждение сделано,
   * promoteReady ещё не перевёл) — прокси: его конфиг уже прокси.
   */
  vhostMode: 'proxy' | 'asleep';
}

