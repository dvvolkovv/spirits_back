import { Body, Controller, Param, Post, UseGuards } from '@nestjs/common';
import { HostGuard } from './host.guard';
import { assertUuid, CompleteJobDto } from './products.dto';
import { ProvisioningService } from './provisioning.service';

/**
 * Потолок причины отказа — на СЕРВЕРЕ, подрезкой, а не отбоем.
 *
 * Отбой по длине (@MaxLength в DTO) отдал бы агенту 400 на честном отчёте:
 * туда уезжает вывод `docker build` со stderr, где две тысячи символов —
 * норма. Агент отчёт в try не заворачивает, и 400 всплыл бы из цикла опроса
 * неперехваченным отказом — процесс агента умирает, задание висит в running
 * до сборщика зависших, владелец читает про истёкший срок. Подрезка сохраняет
 * и отчёт, и диагностику.
 *
 * Хвост помечается многоточием: иначе по обрезанной строке не отличить
 * «сообщение кончилось» от «мы его срезали».
 */
const ERROR_MAX = 2000;

/**
 * Маршруты агента хоста продуктов. Соединение всегда инициирует хост, поэтому
 * ключей от клиентских машин у нас нет и их белый IP нам не нужен.
 *
 * КОНТРАКТ С ДРУГИМ РЕПОЗИТОРИЕМ (product-runner, точка входа host):
 *   - оба маршрута POST, и оба отдают 201, а не 200 — это дефолт Nest для
 *     @Post. Проверка `res.status !== 200` на стороне агента сломается;
 *   - ответ опроса — КОНВЕРТ `{ job }`, а не само задание. `const job = await
 *     api.poll()` без разворота даёт объект, истинный ВСЕГДА, и агент уедет
 *     разворачивать пустоту;
 *   - ответ завершения — `{ ok: true }`.
 *
 * Префикс контроллера ПУСТОЙ. В main.ts стоит `app.setGlobalPrefix('webhook')`,
 * и оба соседних контроллера модуля объявлены так же: путь пишется целиком в
 * самом маршруте. `@Controller('webhook')` дал бы
 * /webhook/webhook/products/host/poll — агент получил бы 404 при полностью
 * зелёном прогоне, потому что от адреса не зависит ни одна проверка вида
 * `new HostController(mock)`. Сторож адреса — products.routes.spec.ts.
 */
@Controller('')
@UseGuards(HostGuard)
export class HostController {
  constructor(private readonly provisioning: ProvisioningService) {}

  /**
   * Опрос очереди. Агент зовёт этот маршрут по кругу, поэтому пустая очередь —
   * обычное состояние, а не ошибка.
   *
   * ОПРОС КОРОТКИЙ, а не длинный — в отличие от соседнего products/runner/poll,
   * который висит до 35 секунд. Здесь маршрут возвращается немедленно, в том
   * числе с `{ job: null }`, поэтому паузу между оборотами держит АГЕНТ.
   * `for (;;) await tick()` без сна превратится в горячий цикл по API и базе с
   * частотой сети. Если длинный опрос понадобится — он делается здесь, а не
   * на той стороне, и тогда эта строка обязана поменяться вместе с ним.
   *
   * Задание прокидывается ЦЕЛИКОМ, в отличие от соседнего маршрута раннера,
   * где ответ собирается явным списком. Разница не в небрежности: там в
   * `req.product` лежит вся строка продукта из базы, и явный список защищает
   * от того, чтобы новая колонка уехала раннеру сама собой. Здесь же объект
   * собирает сам claimJob, и его поля — это и есть контракт с агентом:
   * открытый runner-токен и расшифрованные секреты существуют ровно один раз,
   * в теле этого ответа, и потерять их по дороге нельзя.
   */
  @Post('products/host/poll')
  async poll() {
    // Отметка о жизни агента ставится ДО выдачи и НЕЗАВИСИМО от неё: факт «наш
    // агент пришёл и предъявил токен» состоялся здесь, что бы дальше ни
    // ответила очередь. Поставленная после claimJob, она пропадала бы ровно в
    // том случае, когда нужнее всего, — при отказе базы на выдаче: кабинет
    // показывал бы «агент не забирает задания» вместо настоящей причины.
    //
    // touchHostAgent не бросает (см. там же): сломанная отметка не имеет права
    // останавливать очередь.
    await this.provisioning.touchHostAgent();
    return { job: await this.provisioning.claimJob() };
  }

  /**
   * Отчёт о развёртывании. `id` берётся из URL; из тела — только исход, порт и
   * причина, и берутся они ЯВНЫМ списком.
   *
   * Список именно явный, потому что DTO лишние поля не отсекает:
   * ValidationPipe поднят с `whitelist: false`, а class-transformer копирует на
   * экземпляр и незнакомые ключи. Тело приезжает сюда как есть.
   */
  @Post('products/host/jobs/:id/complete')
  async complete(@Param('id') id: string, @Body() body: CompleteJobDto) {
    // Мусорный id даёт 22P02 в `WHERE id = $1`, то есть 500-ку вместо 404.
    // Задание с ХОРОШИМ, но неизвестным id по-прежнему отвечает { ok: true } и
    // пишет предупреждение (см. completeJob) — это отдельный, законный путь:
    // повторный отчёт после обрыва связи выглядит именно так.
    assertUuid(id, 'Job');
    await this.provisioning.completeJob(id, {
      ok: body.ok,
      port: body.port,
      // Подрезка, а не отбой: см. ERROR_MAX выше.
      error:
        body.error && body.error.length > ERROR_MAX
          ? `${body.error.slice(0, ERROR_MAX - 1)}…`
          : body.error,
    });
    return { ok: true };
  }
}
