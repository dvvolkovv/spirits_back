/** Частота на всём пути моста. Ресемплинга в нашем коде нет нигде. */
export const SAMPLE_RATE = 48_000;

/** Длина тика. 20 мс — стандартный размер пакета WebRTC. */
export const TICK_MS = 20;

export const SAMPLES_PER_TICK = (SAMPLE_RATE * TICK_MS) / 1000; // 960

/** Что мы держим по каждому участнику: его звук и его громкость. */
interface Track {
  queue: Int16Array[];
  /** Сколько кадров пришло всего — отличает «молчит» от «звук не доходит». */
  frames: number;
  /** Сколько из них были речью, а не тишиной. */
  speechFrames: number;
  /** Огибающая громкости: от неё считается, что у ЭТОГО участника речь. */
  peak: number;
  /** Скользящая громкость речи. Ноль — речи ещё не было. */
  speechRms: number;
  /** Фон микрофона: уровень, к которому участник возвращается в паузах. */
  noiseFloor: number;
  /**
   * Сколько тиков собраны не до конца — хвост добит тишиной.
   *
   * Это и есть порча речи: 10–20 мс тишины внутри слова. Громкость не
   * страдает, разборчивость рассыпается. Считаем отдельно от выброса: там
   * данные лишние, здесь их не хватило.
   */
  underruns: number;
  /** Сколько тиков подряд очередь пуста — участник просто молчит. */
  idleTicks: number;
  /**
   * Сколько тиков прошло с последнего пришедшего кадра.
   *
   * По нему отличаем «кадры ещё едут, подождём запаса» от «поток кончился,
   * дожимаем хвост». Без этого хвост реплики застревал бы в очереди навсегда:
   * запаса не наберётся, а отдавать мы отказываемся.
   */
  ticksSincePush: number;
  /**
   * Сколько кусков выброшено вытеснением очереди.
   *
   * Выброс — это дыра прямо посреди фразы: кадры приехали, но тикер не успел
   * их забрать. На слух это щелчок, для распознавания — каша. Счётчик нужен,
   * чтобы отличить «звук не дошёл» от «звук дошёл и был испорчен у нас».
   */
  dropped: number;
  /**
   * Сколько тиков подряд участник не был признан говорящим.
   *
   * По нему решается, усиливать его прямо сейчас или он молчит и идёт в
   * сведение как есть. Счётчик тиков, а не время: микшер живёт тиками и часов
   * не знает, а тесты не должны зависеть от таймера.
   */
  ticksSinceSpeech: number;
}

/** Среднеквадратичная громкость кадра. */
function rmsOf(samples: Int16Array): number {
  let sum = 0;
  for (let i = 0; i < samples.length; i++) sum += samples[i] * samples[i];
  return Math.sqrt(sum / samples.length);
}

/**
 * Сведение речи участников встречи в один поток.
 *
 * Realtime принимает ровно один вход, а AgentSession из коробки слышит только
 * одного участника: RoomInputOptions прямым текстом — «link to the first
 * participant». Значит сводить обязан кто-то, и это мы.
 *
 * Складываем сэмплы, а НЕ перемежаем кадры. У AudioInput внутри лежит
 * MultiInputStream с addInputStream(), и соблазнительно отдать ему по потоку
 * на участника — но он именно перемежает: дорожки LiveKit публикуются
 * непрерывно, и при пятерых в поток пошло бы пять кадров на каждые 20 мс
 * реального времени. Realtime получал бы аудио впятеро быстрее реального и не
 * понял бы ничего — причём постоянно, а не только при наложении речи.
 *
 * Кадры приходят вразнобой и разной длины, поэтому выравнивать их не пытаемся:
 * у каждого участника свой буфер, тикер раз в 20 мс забирает из каждого по 960
 * сэмплов. Нет данных — тишина, и молчащий не тормозит говорящего.
 */
export class Mixer {
  /**
   * Потолок буфера — полсекунды.
   *
   * Участник может слать быстрее, чем мы читаем: рассинхрон часов, всплеск
   * сети. Без потолка буфер растёт неограниченно — сначала это задержка,
   * которая только копится, потом память. Лучше выкинуть старое: во встрече
   * важна свежая речь, а не полная.
   */
  static readonly MAX_BUFFERED_TICKS = 25;

  /**
   * Целевой уровень речи в сведении, RMS для int16 (≈ −20 dBFS).
   *
   * Ниже него участника ПОДНИМАЕМ, выше — не трогаем. Только вверх и никогда
   * вниз: громкого в комнате слышно и так, а тихого не слышно вовсе, и
   * приглушать первого ради второго значило бы чинить одно, ломая другое.
   */
  static readonly TARGET_RMS = 3000;

  /**
   * Ниже этого уровня кадр — тишина, и в оценку громкости он не идёт.
   *
   * Здесь стояло 300, и это была ровно та ошибка, из-за которой участника
   * теряли: у тихого собеседника речь идёт на уровне 287, то есть ЦЕЛИКОМ под
   * порогом. В оценку попадали только редкие пики, она выходила завышенной
   * (405 вместо 287), а усиление из неё — заниженным вдвое. Опыт на
   * синтетической встрече 07.09.2026: вход 287 поднимался до 1726 при цели
   * 3000, и распознавание такого участника не слышало вовсе, тогда как
   * громкого слышало всегда.
   *
   * Сорок — это уже почти цифровая тишина, ниже неё речи не бывает ни у
   * какого микрофона.
   *
   * Ровный фоновый шум на уровне речи такой порог, конечно, не отличит:
   * по громкости кадра они неразличимы в принципе, отличаются модуляцией.
   * Мы сознательно ошибаемся в сторону «поднять лишнее»: цена — приподнятый
   * фон у шумного микрофона (не выше MAX_GAIN), цена обратной ошибки —
   * участник, которого не слышно вовсе.
   */
  static readonly ABS_SILENCE_RMS = 40;

  /**
   * Сколько первых речевых кадров усредняются быстро.
   *
   * Скользящее среднее с шагом 0.05 набирает уровень за пару секунд — а
   * фраза столько и длится, то есть её начало уходит в модель неусиленным.
   * В живом опыте первая фраза тихого участника целиком прошла при ×1.
   */
  static readonly FAST_ATTACK_FRAMES = 20;

  /**
   * Какая доля от собственной огибающей участника считается речью.
   *
   * Среднее по ВСЕМ кадрам громче абсолютного пола оценку занижает: внутри
   * фразы полно тихих кадров — паузы между словами, хвосты слогов, — и
   * громкого участника такая оценка тоже начинает усиливать (на бенче ×5.73
   * там, где нужно ×1.25). Порог, привязанный к огибающей САМОГО участника,
   * работает одинаково и на громком, и на тихом: у каждого «речь» меряется
   * относительно его же уровня.
   */
  static readonly SPEECH_OVER_PEAK = 0.15;

  /** Потолок усиления. Больше — и шум тихого микрофона станет громче речи. */
  static readonly MAX_GAIN = 12;

  /**
   * Запас кадров, который копим, прежде чем начать отдавать участника.
   *
   * Кадры едут по сети неровно: 10-миллисекундный пакет может опоздать на
   * пару миллисекунд, и тик собирается не до конца. Раньше недобор молча
   * добивался тишиной — то есть в середину слова вставлялась дырка. На слух
   * это щелчок, для распознавания — каша: синтетический стенд 16.09.2026
   * показал, что чистая фраза «Роман, вопрос к тебе: сколько будет семью
   * восемь?» выходит из микшера арабской галлюцинацией.
   *
   * Три тика — 60 мс задержки на весь разговор, этого не слышно, а дрожание
   * такого размера перекрывается с запасом. Ноль возвращает прежнее
   * поведение: держим переменной, чтобы сравнить на живой встрече без выката.
   */
  static readonly PREBUFFER_TICKS = Number(process.env.VOICE_PREBUFFER_TICKS ?? 3);

  /**
   * Сколько тиков после последней речи участник ещё считается говорящим.
   *
   * Нужно ради хвостов фразы: между словами и на тихих окончаниях кадры
   * проваливаются ниже порога, и без удержания усиление моргало бы в середине
   * слова. Пятнадцать тиков — это 300 мс: паузу между словами перекрывает,
   * паузу между репликами нет.
   */
  static readonly SPEECH_HOLD_FRAMES = 15;

  /**
   * Во сколько раз кадр должен быть громче собственного фона участника, чтобы
   * считаться речью.
   *
   * Вдвое — это +6 дБ, и граница выбрана по худшему живому случаю, а не по
   * круглому числу: 15.09.2026 самый тихий участник шёл на 276 при фоне своего
   * микрофона около 120, то есть с запасом проходит. Ровный шум своего же фона
   * вдвое себя не превышает: его уровень от кадра к кадру гуляет процентов на
   * двадцать.
   *
   * Разделить шум и речь по одной громкости кадра нельзя в принципе — они
   * отличаются модуляцией. Поэтому правило не «это шум», а «этот сейчас не
   * громче собственной тишины, поднимать его не надо».
   *
   * Порог снижен с двух до полутора 16.09.2026: на живой встрече ассистент
   * слышал участника с десктопа и не слышал того же человека с телефона.
   * У телефонного микрофона фон выше, речь превышает его слабее — и двойного
   * запаса она не набирала. Тогда мобильный участник шёл в сумму без
   * усиления, втрое тише соседа, и детектор речи его пропускал.
   *
   * Значение можно менять переменной окружения, не выкатывая воркер: правильную
   * границу видно только по живым встречам, а каждый выкат рвёт сессию.
   */
  static readonly SPEECH_OVER_NOISE = Number(process.env.VOICE_SPEECH_OVER_NOISE || 1.5);

  private tracks = new Map<string, Track>();

  /**
   * @param levelling выравнивать ли громкость участников. Выключено по
   *   умолчанию: сведение и выравнивание — разные обязанности, и инварианты
   *   сведения (геометрия тика, вытеснение очереди, ограничение суммы) должны
   *   проверяться без усиления, иначе тест на них меряет заодно и его.
   *   Вход встречи создаёт микшер с выравниванием.
   */
  /**
   * @param levelling выравнивать ли громкость участников. Выключено по
   *   умолчанию — см. комментарий выше.
   * @param samplesPerTick сколько сэмплов в тике. По умолчанию 960 — это
   *   48 кГц, частота LiveKit, на которой работают свои комнаты и Taler ID.
   *   Встречи через мост идут на 24 кГц (родная частота Realtime, ни одного
   *   ресемпла на пути), там тик — 480.
   */
  constructor(
    private readonly levelling = false,
    private readonly samplesPerTick: number = SAMPLES_PER_TICK,
    /**
     * Запас кадров перед отдачей. По умолчанию — боевое значение; тесты на
     * геометрию сведения ставят ноль, потому что проверяют сумму, а не время.
     */
    private readonly prebufferTicks: number = Mixer.PREBUFFER_TICKS,
  ) {}

  push(participant: string, samples: Int16Array): void {
    if (!samples.length) return;
    const t = this.track(participant);
    t.queue.push(samples);
    while (this.countTicks(t.queue) > Mixer.MAX_BUFFERED_TICKS) { t.queue.shift(); t.dropped++; }
    t.frames++;
    t.ticksSincePush = 0;
    const rms = rmsOf(samples);

    // Огибающая: мгновенно вверх, медленно вниз (около секунды на затухание).
    t.peak = rms > t.peak ? rms : t.peak * 0.999;

    if (rms > Math.max(Mixer.ABS_SILENCE_RMS, t.peak * Mixer.SPEECH_OVER_PEAK)) {
      // Скользящее среднее по РЕЧЕВЫМ кадрам: оценка не должна прыгать от
      // одного громкого слога и не должна проседать в паузах. В начале шаг
      // крупнее — иначе первая фраза успевает пройти неусиленной.
      const a = t.speechFrames < Mixer.FAST_ATTACK_FRAMES ? 0.3 : 0.05;
      t.speechRms = t.speechFrames === 0 ? rms : t.speechRms * (1 - a) + rms * a;
      t.speechFrames++;
    }
  }

  /**
   * Фон микрофона участника: к чему его звук возвращается в паузах.
   *
   * Следит за минимумом — быстро вниз, очень медленно вверх. Речь поднимает
   * уровень в разы и длится секунды, поэтому вверх фон за ней не успевает, а
   * вот за сменой обстановки (закрыли окно, включили вентилятор) — успевает.
   *
   * Абсолютным числом этот порог задать нельзя: у одного микрофона фон 30, у
   * другого 120, и на живой встрече 15.09.2026 самый тихий участник говорил на
   * 276 — тише, чем фон соседа.
   */
  private trackNoiseFloor(t: Track, rms: number): void {
    // Цифровая тишина о фоне не говорит НИЧЕГО.
    //
    // Здесь была дыра, стоившая рабочего дня: фон инициализировался первым же
    // кадром, а первый кадр в комнате — ровный ноль. Признаком «фон ещё не
    // измерен» служил сам ноль, поэтому фон переписывался текущей громкостью
    // на каждом кадре, и порог речи превращался в «громче самого себя в
    // полтора раза» — невыполнимый никогда. В логе живой встречи 16.09.2026
    // это выглядело как «фон 0, молчит ×1» у всех участников разом: никого не
    // усиливали, и тихого участника переставало быть слышно.
    if (rms <= 0) return;
    if (t.noiseFloor <= 0) {
      t.noiseFloor = rms;
      return;
    }
    if (rms < t.noiseFloor) {
      t.noiseFloor = t.noiseFloor * 0.9 + rms * 0.1;
      return;
    }
    // Вверх фон ползёт только на кадрах, которые речью НЕ считаются.
    //
    // Иначе длинная реплика сама поднимает свой порог: шаг 0.001 за тик — это
    // около двадцати секунд до заметного сдвига, и говорящий без пауз через
    // полминуты перестал бы считаться говорящим.
    if (rms < t.noiseFloor * Mixer.SPEECH_OVER_NOISE) {
      t.noiseFloor = t.noiseFloor * 0.999 + rms * 0.001;
    }
  }


  /**
   * Говорит ли участник прямо сейчас — по решению последнего тика.
   *
   * Отвечает на вопрос «усиливать ли его», а не «есть ли у него звук».
   * Выставляется в tick(), потому что решение относительное: участник молчит
   * не сам по себе, а по сравнению с тем, кто в этот момент говорит.
   */
  private speakingNow(t: Track): boolean {
    return t.ticksSinceSpeech <= Mixer.SPEECH_HOLD_FRAMES;
  }

  remove(participant: string): void {
    this.tracks.delete(participant);
  }

  bufferedTicks(participant: string): number {
    return this.countTicks(this.tracks.get(participant)?.queue || []);
  }

  /**
   * Во сколько раз поднимаем участника, чтобы он не тонул в сведении.
   *
   * Зачем это вообще. Встреча 07.09.2026: трое участников, аудио всех троих
   * дошло до микшера (в логе три подписки и ровный поток кадров весь час), но
   * в транскрипт попал в основном владелец. У остальных двоих остались обрывки
   * в два-три слова — при том, что они, по словам владельца, обращались к
   * ассистенту прямо по имени, и ни одного такого обращения в записи нет.
   * Складывая дорожки как есть, мы сохраняем разницу в громкости микрофонов:
   * тихий удалённый участник тонет под громким, и распознавание разбирает
   * только верхний голос.
   */
  gainFor(participant: string): number {
    if (!this.levelling) return 1;
    const t = this.tracks.get(participant);
    // Речи ещё не слышали — усиливать нечего и не из чего.
    if (!t || t.speechFrames === 0 || t.speechRms < Mixer.ABS_SILENCE_RMS) return 1;
    const gain = Mixer.TARGET_RMS / t.speechRms;
    return Math.min(Math.max(gain, 1), Mixer.MAX_GAIN);
  }

  /** Что слышно от каждого участника — для диагностики в логе. */
  stats(): {
    participant: string;
    frames: number;
    speechFrames: number;
    rms: number;
    gain: number;
    speaking: boolean;
    /** Фон микрофона: от него считается порог речи. */
    floor: number;
    /** Сколько кусков выброшено вытеснением очереди. */
    dropped: number;
    /** Сколько тиков собрано не до конца — дырки внутри слов. */
    underruns: number;
  }[] {
    return [...this.tracks.entries()].map(([participant, t]) => ({
      participant,
      frames: t.frames,
      speechFrames: t.speechFrames,
      rms: Math.round(t.speechRms),
      gain: Number(this.gainFor(participant).toFixed(2)),
      speaking: this.speakingNow(t),
      floor: Math.round(t.noiseFloor),
      dropped: t.dropped,
      underruns: t.underruns,
    }));
  }

  /** Один смикшированный кадр. Вызывается ровно раз в TICK_MS. */
  tick(): Int16Array {
    const chunks: { t: Track; participant: string; chunk: Int16Array; rms: number }[] = [];
    for (const [participant, t] of this.tracks) {
      // Подкачка: пока у живого участника не накопился запас, не трогаем его
      // очередь вовсе. Иначе тик соберётся наполовину, хвост добьётся тишиной
      // — и дырка уедет в середину слова. Ждём только того, кто уже звучит:
      // молчащего ждать нечего, у него очередь пуста по определению.
      t.ticksSincePush++;
      const buffered = this.countTicks(t.queue);
      // Ждём запаса, только пока кадры реально едут. Кончился поток — хвост
      // дожимаем как есть, иначе он застрянет в очереди навсегда.
      if (buffered > 0 && buffered < this.prebufferTicks && t.ticksSincePush <= 2) {
        t.underruns++;
        chunks.push({ t, participant, chunk: new Int16Array(this.samplesPerTick), rms: 0 });
        continue;
      }
      const chunk = this.takeTick(t);
      chunks.push({ t, participant, chunk, rms: rmsOf(chunk) });
    }

    const out = new Int16Array(this.samplesPerTick);
    for (const { t, participant, chunk, rms } of chunks) {
      // Речь отличаем от фона по СОБСТВЕННОМУ фону участника, а не по
      // громкости соседа.
      //
      // Сравнение с самым громким в тике я попробовал первым, и оно протекает
      // ровно там, где дороже всего: в паузах говорящего самым громким
      // становится чужой фон, проходит как речь и снова поднимается в ×12.
      // Замер на записи живой встречи: относительное правило дало 65% слов
      // против 59% без правила вовсе — то есть закрыло меньше трети потерь.
      this.trackNoiseFloor(t, rms);
      const speech = rms >= Math.max(Mixer.ABS_SILENCE_RMS, t.noiseFloor * Mixer.SPEECH_OVER_NOISE);
      t.ticksSinceSpeech = speech ? 0 : t.ticksSinceSpeech + 1;

      // Усиливаем ТОЛЬКО того, кто говорит.
      //
      // Молчащий участник — это не тишина, а фон его микрофона, около 120 при
      // пороге речи 40. Он проходил как речь, из него строилась оценка
      // громкости, и выравнивание тянуло ШУМ к целевым 3000, то есть в ×12.
      // Под каждой фразой говорящего лежали два-три таких усиленных шипения.
      //
      // Замер 15.09.2026 на записи живой встречи (окно 03:00–13:00, эталон
      // 1527 слов): один говорящий через микшер — 83% слов, он же плюс двое
      // молчащих — 59%. Из потерянных пунктов шесть давало само сложение
      // дорожек, остальные тринадцать — подъём фона.
      const gain = this.speakingNow(t) ? this.gainFor(participant) : 1;
      for (let i = 0; i < chunk.length; i++) {
        const sum = out[i] + chunk[i] * gain;
        // Ограничение обязательно: Int16Array переполняется молча, и сумма
        // двух громких голосов превращается в треск на противоположном знаке.
        out[i] = sum > 32767 ? 32767 : sum < -32768 ? -32768 : sum;
      }
    }
    return out;
  }

  private track(participant: string): Track {
    let t = this.tracks.get(participant);
    if (!t) {
      t = { queue: [], frames: 0, speechFrames: 0, speechRms: 0, peak: 0, noiseFloor: 0, dropped: 0, underruns: 0, idleTicks: 0, ticksSincePush: 0, ticksSinceSpeech: Infinity };
      this.tracks.set(participant, t);
    }
    return t;
  }

  private countTicks(queue: Int16Array[]): number {
    let n = 0;
    for (const c of queue) n += c.length;
    return Math.ceil(n / this.samplesPerTick);
  }

  /**
   * Снять с очереди ровно тик.
   *
   * Если данных не хватает — раньше хвост просто добивался тишиной, и дырка
   * уезжала в середину слова. Теперь недобор считается, а участнику с живой,
   * но ещё не накопившейся очередью даётся тик тишины целиком: лучше ровная
   * пауза, чем рваное слово. Разбирается это в tick(), здесь только сборка.
   */
  private takeTick(t: Track): Int16Array {
    const queue = t.queue;
    const out = new Int16Array(this.samplesPerTick);
    let filled = 0;
    while (filled < this.samplesPerTick && queue.length) {
      const head = queue[0];
      const need = this.samplesPerTick - filled;
      if (head.length <= need) {
        out.set(head, filled);
        filled += head.length;
        queue.shift();
      } else {
        out.set(head.subarray(0, need), filled);
        // subarray, а не slice: slice на Int16Array поверх чужого буфера ведёт
        // себя непредсказуемо — про это есть прямое предупреждение в примерах
        // rtc-node.
        queue[0] = head.subarray(need);
        filled += need;
      }
    }
    if (filled === 0) {
      t.idleTicks++;
    } else {
      t.idleTicks = 0;
      if (filled < this.samplesPerTick) t.underruns++;
    }
    // Длина всегда samplesPerTick: тик обязан быть ровным, иначе поток в
    // Realtime поедет по времени.
    return out;
  }
}
