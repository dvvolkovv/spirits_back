/**
 * Сколько ждём первого человека.
 *
 * Правило «нет живых участников → выходим» без этой отсрочки выкидывало бы
 * ассистента мгновенно: его вполне могут позвать раньше, чем соберутся люди,
 * и комната в этот момент пуста.
 */
export const LOBBY_MS = 15 * 60 * 1000;

/**
 * Грубый предохранитель на общую длительность.
 *
 * Продуктовое решение, не ограничение API: у звонка из интерфейса потолок час,
 * у встречи два — переговоры регулярно длиннее часа. Это ещё и потолок по
 * деньгам: Realtime тарифицируется всё время, пока ассистент в комнате.
 */
export const HARD_CAP_MS = 2 * 60 * 60 * 1000;

/**
 * Сколько ждём, прежде чем поверить, что встреча опустела.
 *
 * Для своих комнат — ноль: LiveKit о составе не врёт, и уходить надо сразу.
 *
 * Для Meet ноль оказался нельзя. Живая встреча 09.09.2026: владелец сидел во
 * встрече, а Meet отдал его со `status: 8` («unknown» — этого кода нет даже в
 * таблице статусов самого Attendee, где расписаны 1, 6 и 7). Attendee
 * переводит любой статус кроме `in_meeting` в уход
 * (`active = humanized_status == "in_meeting"`), прислал `leave`, состав стал
 * нулевым — и ассистент вышел из живой встречи через пять секунд, на 229-й
 * секунде разговора.
 *
 * Полторы минуты: меньше, чем 300 с автовыхода Attendee по одиночеству
 * (значит причину выхода по-прежнему называем мы), и достаточно, чтобы
 * переждать мигание статуса. Заодно `meet_speaking` возвращает человека в
 * состав сразу: тот, кто говорит, заведомо во встрече.
 */
export const MEET_EMPTY_GRACE_MS = 90_000;

/**
 * Сколько речь человека считается доказательством его присутствия.
 *
 * Нужна там, где состав приходит из вёрстки и может молчать (свой бот), а не
 * из LiveKit. Десять минут: в живом разговоре люди говорят куда чаще, а цена
 * ошибки в большую сторону — лишние минуты Realtime после конца встречи,
 * тогда как цена ошибки в меньшую — выход из живых переговоров при клиенте.
 *
 * Перебор здесь дёшев ещё и потому, что это не основной путь выхода: когда
 * встреча кончается, бот закрывает вебсокет, и воркер уходит по потере звука
 * (onLost → abortMeet) примерно за полторы минуты.
 */
export const SPEECH_PRESENCE_TTL_MS = 10 * 60_000;

export type Verdict =
  /** остаёмся в комнате */
  | 'stay'
  /** за всё ожидание никто не пришёл — вход не состоялся */
  | 'never_started'
  /** люди были и разошлись */
  | 'empty'
  /** уперлись в потолок */
  | 'hard_cap';

/**
 * Кто живой в комнате и пора ли выходить.
 *
 * Чистая логика без таймеров и сети: воркер скармливает ей события и текущее
 * время, она отвечает вердиктом. Так правила выхода проверяются тестами, а не
 * двухчасовым сидением в реальной встрече.
 *
 * Участники считаются множеством, а не счётчиком: LiveKit может прислать
 * participantConnected дважды на переподключении, и счётчик после этого уже
 * никогда не дойдёт до нуля — ассистент остался бы в пустой комнате навсегда.
 */
export class Occupancy {
  private readonly humans = new Set<string>();
  private everHadHuman = false;
  /** С какого момента состав пуст. `null` — кто-то есть. */
  private emptyAt: number | null = null;
  /** Когда человек говорил в последний раз. `null` — не говорил вовсе. */
  private lastSpeechAt: number | null = null;

  /**
   * `emptyGraceMs` — выдержка перед вердиктом «опустела». Ноль для своих
   * комнат, MEET_EMPTY_GRACE_MS для Meet: там источник состава врёт.
   * `speechTtlMs` — сколько речь считается присутствием. Параметр ради
   * тестов: десять минут в юнит-тесте не подождёшь.
   */
  constructor(
    private readonly startedAt: number,
    private readonly emptyGraceMs = 0,
    private readonly speechTtlMs = SPEECH_PRESENCE_TTL_MS,
  ) {}

  joined(identity: string): void {
    this.humans.add(identity);
    this.everHadHuman = true;
  }

  left(identity: string): void {
    this.humans.delete(identity);
  }

  /**
   * Человек говорил — значит он здесь.
   *
   * Источник, не зависящий от вёрстки: состав у своего бота читается зацепкой
   * на странице, а расшифровка речи приходит из звука встречи. Когда зацепка
   * молчит, это единственное свидетельство, что встреча живая.
   *
   * everHadHuman поднимаем здесь же: разговор был, и вердикт «во встречу так
   * никто и не пришёл» после него — неправда, за которую звонок пометят
   * failed.
   *
   * Личности у говорящего нет и не нужно: в Телемосте имён в разметке нет
   * вовсе, а для правил выхода важно лишь, что живой человек тут есть.
   */
  speechHeard(now: number): void {
    this.lastSpeechAt = now;
    this.everHadHuman = true;
  }

  get liveCount(): number {
    return this.humans.size;
  }

  verdict(now: number): Verdict {
    // Потолок проверяется первым: если истекли оба условия, причина выхода
    // должна называться честно, иначе в логах будет «встреча опустела» там,
    // где на самом деле сработал предохранитель.
    if (now - this.startedAt >= HARD_CAP_MS) return 'hard_cap';
    if (!this.everHadHuman) {
      return now - this.startedAt >= LOBBY_MS ? 'never_started' : 'stay';
    }
    // Недавняя речь равносильна непустому составу. Проверяется ВМЕСТЕ с
    // размером, а не вместо: при живом составе уходить не за чем и без речи,
    // а при сломанном счётчике речь — единственное, что остаётся.
    const speaking = this.lastSpeechAt !== null && now - this.lastSpeechAt < this.speechTtlMs;
    if (this.humans.size > 0 || speaking) {
      this.emptyAt = null;
      return 'stay';
    }
    if (this.emptyGraceMs <= 0) return 'empty';
    // Отсчёт ведём здесь, а не в left(): время в этот класс приходит только
    // параметром, и своих часов у него нет — ровно поэтому правила выхода
    // проверяются тестами, а не двухчасовым сидением в реальной встрече.
    if (this.emptyAt === null) {
      this.emptyAt = now;
      return 'stay';
    }
    return now - this.emptyAt >= this.emptyGraceMs ? 'empty' : 'stay';
  }
}
