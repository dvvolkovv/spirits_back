describe('answerTo', () => {
  test('называет ту реплику, на которую отвечать', () => {
    // Смысл указания в том, что модель отвечает на КОНКРЕТНУЮ фразу. Если
    // текст в него не попал, останется прежнее «ответь на разговор целиком»,
    // и вернётся ответ про Джомолунгму на вопрос про насадку.
    assert.match(answerTo('Роман, что скажешь по срокам?'), /Роман, что скажешь по срокам\?/);
  });

  test('запрещает отвечать на фон встречи', () => {
    const s = answerTo('вопрос');
    assert.match(s, /не отвечай на это/);
  });

  test('требует переспросить вместо догадки', () => {
    // Распознавание на встрече выдаёт мусор вроде «Зависота двуса». Уверенный
    // ответ на него хуже переспроса.
    const s = answerTo('Зависота двуса');
    assert.match(s, /не расслышал/);
    assert.match(s, /Не угадывай/);
  });

  test('кавычки внутри реплики не рвут указание', () => {
    // Распознавание вставляет кавычки само; указание должно остаться цельным.
    const s = answerTo('он сказал «потом» и ушёл');
    assert.match(s, /он сказал «потом» и ушёл/);
    assert.match(s, /Ответь ПО-РУССКИ именно на неё/);
  });
});

