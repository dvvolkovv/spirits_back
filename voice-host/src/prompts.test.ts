describe('transcriptionPrompt', () => {
  test('называет имя ассистента — ради него подсказка и нужна', () => {
    assert.match(transcriptionPrompt('Роман'), /Роман/);
    assert.match(transcriptionPrompt('Шанкар'), /Шанкар/);
  });

  test('задаёт язык: подсказка едет в тот же блок, что и language', () => {
    assert.match(transcriptionPrompt('Роман'), /русск/i);
  });

  test('короткая — это подсказка распознаванию, а не инструкция модели', () => {
    // Длинный текст в этом поле уводит расшифровку в пересказ подсказки.
    assert.ok(transcriptionPrompt('Роман').length < 150);
  });

  // ⚠️ Термин, который расслышали как непристойность и в таком виде записали в профиль
  // (разговор 12.10.2026: «ЕБИ-терапия» вместо «ABA-терапия»).
  test('называет термины, которые распознавание ломает', () => {
    assert.match(transcriptionPrompt('Роман'), /ABA-терапия/);
  });

  test('личный словарь приходит параметром, а не глобальным списком', () => {
    const s = transcriptionPrompt('Роман', ['нейрографика']);
    assert.match(s, /нейрографика/);
    assert.ok(!/ABA/.test(s), 'переданный список ЗАМЕНЯЕТ общий, а не дополняет');
  });

  test('без терминов — прежняя короткая подсказка, без хвоста', () => {
    const s = transcriptionPrompt('Роман', []);
    assert.ok(!/термин/i.test(s));
    assert.ok(s.endsWith('по имени.'));
  });

  // Эхо-заслон сверяет НАЧАЛО подсказки, поэтому термины дописаны в конец.
  test('эхо подсказки по-прежнему ловится', () => {
    assert.ok(isTranscriptionEcho('Рабочая встреча на русском языке.', 'Роман'));
    assert.ok(isTranscriptionEcho(transcriptionPrompt('Роман'), 'Роман'));
  });
});

/**
 * Рассказ о себе — по прямому вопросу, а не во вступлении.
 *
 * Раньше ассистент выкладывал всё на входе: кто он, чей он, как к нему
 * обращаться. На чужой встрече это полминуты служебного текста до того, как
 * люди успели поздороваться. Решение владельца 12.10.2026: на входе — только
 * приветствие и запись, подробности — когда спросят.
 */
describe('рассказ о себе', () => {
  test('по вопросу отвечает коротко и называет, чей он ассистент', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
      ownerName: 'Дмитрий',
    }));
    assert.match(s, /Спросили, кто ты/);
    assert.match(s, /ассистент Дмитрий/);
    assert.match(s, /двумя-тремя фразами/);
  });

  test('без имени владельца подставляется заглушка', () => {
    // «Ассистент пользователя» на внешней встрече звучит как строка из лога.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
    }));
    assert.match(s, /ассистент владельца встречи/);
    assert.doesNotMatch(s, /ассистент пользователя/);
  });

  test('формула «пока слушай» переехала сюда из вступления', () => {
    // Это единственный способ заткнуть ассистента. Из вступления она ушла,
    // значит обязана звучать хотя бы в ответе на прямой вопрос.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
    }));
    assert.match(s, /«Роман, пока слушай»/);
    assert.match(s, /назвать по имени/);
  });

  test('сам, без вопроса, о себе не рассказывает', () => {
    // Без явного запрета «расскажи, когда спросят» читается как разрешение
    // рассказать — и модель выкладывает возможности в первом же ответе.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
    }));
    assert.match(s, /САМ, пока не спросили/);
    assert.match(s, /ни во вступлении, ни в первом ответе/);
  });
});

describe('isTranscriptionEcho', () => {
  test('ловит подсказку, вернувшуюся вместо реплики', () => {
    assert.equal(isTranscriptionEcho(transcriptionPrompt('Роман'), 'Роман'), true);
  });

  test('ловит обрезанное эхо — именно так оно и приходит', () => {
    // Живая встреча 16.09.2026: в гейт пришло «Рабочая встреча на русском
    // языке.» и «Рабочая встреча на русском языке. Ассистента зовут Роман — к
    // нему обращаются по ».
    assert.equal(isTranscriptionEcho('Рабочая встреча на русском языке.', 'Роман'), true);
    assert.equal(
      isTranscriptionEcho('Рабочая встреча на русском языке. Ассистента зовут Роман — к нему обращаются по ', 'Роман'),
      true,
    );
  });

  test('живую речь не трогает, даже если в ней есть слово «встреча»', () => {
    assert.equal(isTranscriptionEcho('Роман, вопрос к тебе по вчерашней встрече', 'Роман'), false);
    assert.equal(isTranscriptionEcho('давайте начнём рабочую встречу', 'Роман'), false);
  });
});

/**
 * Первая фраза на встрече.
 *
 * Тестов на неё не было вовсе, а менялась она по решению владельца дважды:
 * 26.08.2026 в неё добавили правило обращения, 12.10.2026 убрали вместе с
 * «ассистент такого-то». Чтобы третий заход не пришлось восстанавливать по
 * истории git, состав фразы закреплён здесь.
 */
describe('meetingIntro', () => {
  const s = flat(meetingIntro('Роман'));

  test('одна фраза: имя и запись', () => {
    assert.match(s, /ОДНУ короткую фразу/);
    assert.match(s, /Роман/);
    assert.match(s, /записывается/);
  });

  test('правила обращения во вступлении больше нет', () => {
    // Гейт открывается на одно имя (addressedByName в name-gate.ts), формула
    // «вопрос к тебе» не обязательна. А формулу возврата произносит listenAck()
    // ровно в тот момент, когда она нужна.
    assert.doesNotMatch(s, /вопрос к тебе/i);
    assert.doesNotMatch(s, /пока слушай/i);
  });

  test('не представляется ассистентом владельца', () => {
    // Чей он — видно в списке участников: «Роман · ассистент Дмитрия».
    assert.doesNotMatch(s, /ассистент/i);
  });

  test('модели прямо запрещено добирать контекст из промпта', () => {
    // persona и список специалистов лежат в том же системном промпте, и на
    // «представься» модель охотно пересказывает их целиком.
    assert.match(s, /Не рассказывай, кто ты и что умеешь/);
    assert.match(s, /не перечисляй списков/);
  });

  test('по-русски — требование осталось', () => {
    // До первой реплики человека у Realtime нет звукового сигнала о языке, и
    // он берёт английский: живой звонок 25.08.2026 начался с «Hi there!».
    assert.match(s, /ПО-РУССКИ/);
    assert.match(s, /Ни одного английского слова/);
  });
});
