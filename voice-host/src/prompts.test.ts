import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import {
  answerTo,
  answerToChat,
  CALL_CRISIS_RULE,
  callInstructions,
  meetingInstructions,
  meetingIntro,
  transcriptionPrompt,
  isTranscriptionEcho,
} from './prompts.js';

const SPECIALISTS = [
  { name: 'Алексей', role: 'юрист' },
  { name: 'Александра', role: 'маркетолог' },
];

/**
 * Промпты свёрстаны по ширине строки и склеиваются через '\n', поэтому любая
 * фраза длиннее семидесяти знаков разорвана переносом в произвольном месте.
 * Проверять надо смысл, а не вёрстку: иначе тест краснеет от переноса слова.
 */
const flat = (s: string) => s.replace(/\s+/g, ' ');

/**
 * Роман — не языковая модель в вакууме: сеть у него есть, просто чужими
 * руками. Пока в промпте об этом не было ни слова, он на вопрос про курс или
 * новость честно отвечал, что в интернет посмотреть не может, — и разговор
 * заканчивался отказом там, где ответ был в одном вызове ask_specialist
 * (замечено владельцем 04.09.2026). Инструкция держится только промптом,
 * поэтому её и проверяем: удалят строку — тест это поймает.
 */
describe('доступ к интернету', () => {
  test('в звонке запрещено отказывать под предлогом отсутствия сети', () => {
    const s = flat(callInstructions('', SPECIALISTS));
    assert.match(s, /не можешь посмотреть в интернете/i);
    assert.match(s, /У тебя ЕСТЬ доступ к интернету/);
  });

  test('в звонке поиск идёт через коллег, а не объявляется способностью самого Романа', () => {
    // Тула поиска у ведущего нет. Если написать «ты умеешь искать», модель
    // пообещает найти и замолчит: искать ей будет нечем.
    const s = flat(callInstructions('', SPECIALISTS));
    assert.match(s, /через коллег/);
    assert.match(s, /ask_specialist/);
  });

  test('на встрече тот же запрет отказывать', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: 'ведущий', preamble: '', specialists: SPECIALISTS,
    }));
    assert.match(s, /не можешь посмотреть в интернете/i);
  });
});

/**
 * Кризисное правило в звонке. Промпт Романа из БД звонок не читает, поэтому
 * правило, которое штатные ассистенты несут в своём промпте, живёт здесь
 * отдельно — и держится только этим текстом. Номера сверяет с бэкендом
 * src/chat/crisis-rule.spec.ts.
 */
describe('кризисная ситуация в звонке', () => {
  test('правило в инструкциях звонка, с номерами помощи', () => {
    const s = flat(callInstructions('', SPECIALISTS));
    assert.match(s, /КРИЗИСНАЯ СИТУАЦИЯ — ЭТО ПРАВИЛО ВАЖНЕЕ ВСЕХ ОСТАЛЬНЫХ/);
    for (const phone of ['112', '+7 (495) 989-50-50', '8-800-2000-122']) {
      assert.ok(s.includes(phone), `нет номера ${phone}`);
    }
    assert.match(s, /не в России — пусть звонит в местную экстренную службу/);
  });

  test('к каждому номеру приписано, как его произносить', () => {
    const s = flat(CALL_CRISIS_RULE);
    assert.match(s, /112, «сто двенадцать»/);
    assert.match(s, /\+7 \(495\) 989-50-50: «плюс семь, четыреста девяносто пять, девятьсот восемьдесят девять, пятьдесят, пятьдесят»/);
    assert.match(s, /8-800-2000-122: «восемь, восемьсот, две тысячи, сто двадцать два»/);
  });

  test('спрашивать прямо и не передавать кризис коллегам', () => {
    const s = flat(CALL_CRISIS_RULE);
    assert.match(s, /прямо спроси, думает ли он о самоубийстве/);
    assert.match(s, /Не ставь это вопросом коллегам через ask_specialist/);
    assert.match(s, /Не давай сведений о способах навредить/);
  });

  test('без markdown-списков: ни одна строка не начинается с маркера', () => {
    for (const line of CALL_CRISIS_RULE.split('\n')) {
      assert.doesNotMatch(line, /^\s*([-*•—]|\d+[.)])\s/, line);
    }
  });

  test('среди правил, до контекста переписки', () => {
    const s = callInstructions('Пользователь: привет', SPECIALISTS);
    assert.ok(s.includes(CALL_CRISIS_RULE));
    assert.ok(s.indexOf('КРИЗИСНАЯ СИТУАЦИЯ') < s.indexOf('СПРАВКА О ПРОШЛОЙ ПЕРЕПИСКЕ'));
  });
});

/**
 * Правила, выведенные из разбора трёх живых разговоров 24–25.10.2026.
 * Каждое оплачено конкретным дефектом; в тесте он назван, чтобы правило не
 * сократили как воду.
 */
describe('звонок: правила против повторов и выдумок', () => {
  const s = callInstructions('Пользователь: подготовь текст заявления', SPECIALISTS);

  test('прямой запрет повторять свою реплику и переспрашивать отвеченное', () => {
    // 24.10.2026: блок «Это звучит как зрелое решение…» прозвучал дважды
    // слово в слово, во второй раз — с вопросом, на который человек уже
    // ответил двумя репликами выше.
    assert.match(s, /НИКОГДА НЕ ПОВТОРЯЙ СВОЮ ПРОШЛУЮ РЕПЛИКУ/);
    assert.match(s, /вопрос, на который\s+человек уже ответил, не задавай второй раз/);
  });

  test('обрывок мысли — не повод для развёрнутого ответа', () => {
    // Та же причина, что и длинная тишина в session-options: мысль владельца
    // приходит кусками, и ответ на первый кусок уходит мимо.
    assert.match(s, /ДУМАЕТ ВСЛУХ/);
    assert.match(s, /молчи или скажи одно короткое/);
  });

  test('не выдумывать, с чем человек позвонил', () => {
    // 25.10.2026: звонок открылся «Похоже, вы начали печатать и
    // остановились… текст заявления, карта маршрута или что-то ещё».
    assert.match(s, /НЕ ПРИДУМЫВАЙ, С ЧЕМ ОН ПОЗВОНИЛ/);
    assert.match(s, /не предполагай тему/);
  });

  test('справка о переписке обрамлена как прошлое, а не как реплика', () => {
    assert.match(s, /это ПРОШЛОЕ, не текущий разговор/);
    assert.match(s, /Не отвечай на неё, не продолжай начатое в ней/);
    // Сам текст справки при этом на месте — рамка его не съела.
    assert.ok(s.includes('Пользователь: подготовь текст заявления'));
  });

  test('только «ты», даже если в переписке было «вы»', () => {
    // 25.10.2026: обращение скакало внутри одного разговора.
    assert.match(s, /Обращайся на «ты»/);
    assert.match(s, /даже если/);
  });

  test('шаблонные обороты названы поимённо', () => {
    // Три хода подряд начинались «Версия для размышления… Один вопрос:».
    assert.match(s, /Версия для размышления/);
    assert.match(s, /Один вопрос/);
    assert.match(s, /не должны повторяться из хода в ход/);
  });

  test('без справки рамка не появляется', () => {
    const empty = callInstructions('', SPECIALISTS);
    assert.doesNotMatch(empty, /СПРАВКА О ПРОШЛОЙ ПЕРЕПИСКЕ/);
    assert.match(empty, /Прошлой переписки нет/);
  });
});

describe('чат встречи', () => {
  test('со чатом промпт объясняет, что в него можно писать', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.match(s, /write_to_chat/);
    assert.match(s, /ссылк/i);
    // Пересказ вслух того, что уже написано текстом, — главный способ
    // испортить встречу: участники слышат зачитанный URL посимвольно.
    assert.match(s, /не дублируй|не зачитывай/i);
  });

  test('лента до прихода подаётся как справка, а не как обращения', () => {
    // Ассистента зовут в середине встречи, и написанного раньше в data-канале
    // быть не может. Но отвечать на закрытые вопросы он не должен.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
      chatHistory: ['Дмитрий: смета на 200 квадратов', 'Анна: жду цифры'],
    }));
    assert.match(s, /смета на 200 квадратов/);
    assert.match(s, /Анна: жду цифры/);
    assert.match(s, /НЕ адресованы|не отвечай на них/i);
  });

  test('без ленты блока справки нет', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.doesNotMatch(s, /ДО твоего прихода/);
  });

  /**
   * Читать чат модель умеет только инструментом: сообщения лежат в буфере
   * воркера. Живая встреча 11.09.2026 показала, чем кончается умолчание о нём
   * в промпте — на вопрос «что за ссылку я кинул в чат» ассистент послал
   * коллеге задачу «проверь содержимое страницы по ссылке из чата», без самой
   * ссылки. Инструмент был, но модель о нём не подумала.
   */
  test('чтение чата названо инструментом и объяснено, когда его звать', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.match(s, /read_chat/);
    assert.match(s, /что там за ссылка/);
    assert.match(s, /не говори, что в чате ничего нет, не заглянув/i);
  });

  test('ссылку коллеге передавать дословно', () => {
    // Иначе повторится живой случай: вопрос ушёл специалисту как «ссылка из
    // чата», и искать ему было нечего.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.match(s, /ДОСЛОВНО/);
  });

  test('писать в чат велено и без просьбы — когда в ответе ссылка', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.match(s, /сам, без просьбы/);
  });

  test('отказ инструмента запрещено выдавать за отправку', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS, hasChat: true,
    }));
    assert.match(s, /status: rejected/);
  });

  test('где писать нельзя — сказано прямо, и обещать отправку запрещено', () => {
    // Телемост пускает в чат только вошедших под учётной записью: гостю там
    // показывают «Войдите, чтобы написать сообщение». 15.09.2026 ассистент
    // сказал, что написал, — сообщения не было.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
      hasChat: true, canWriteChat: false,
    }));
    assert.match(s, /писать в него не можешь/);
    assert.match(s, /Никогда не говори, что написал или отправил/);
    // Инструмента записи в таком промпте быть не должно вовсе.
    assert.doesNotMatch(s, /write_to_chat/);
  });

  test('где писать можно — инструмент назван', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
      hasChat: true, canWriteChat: true,
    }));
    assert.match(s, /write_to_chat/);
  });

  test('чтение объясняется в обоих случаях', () => {
    for (const canWriteChat of [true, false]) {
      const s = flat(meetingInstructions({
        name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
        hasChat: true, canWriteChat,
      }));
      assert.match(s, /read_chat/);
    }
  });

  test('без чата не упомянут и инструмент чтения', () => {
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
    }));
    assert.doesNotMatch(s, /read_chat/);
  });

  test('без чата про него в промпте ни слова', () => {
    // Чат есть только в чужих комнатах Taler ID; тула write_to_chat на своей
    // встрече нет вовсе. Рассказать модели про инструмент, которого ей не
    // дали, — значит получить обещание «написал в чат» без единого сообщения.
    const s = flat(meetingInstructions({
      name: 'Роман', persona: '', preamble: '', specialists: SPECIALISTS,
    }));
    assert.doesNotMatch(s, /write_to_chat/);
    assert.doesNotMatch(s, /чат встречи/i);

  });
});

