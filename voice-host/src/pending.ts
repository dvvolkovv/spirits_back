/**
 * Очередь ответов специалистов, ждущих, когда их можно произнести.
 *
 * Realtime не принимает второй запрос на ответ, пока идёт первый: возвращает
 * `conversation_already_has_active_response`, и вставка просто пропадает. Когда
 * Роман задал три вопроса подряд, ответы вернулись почти одновременно, и из
 * трёх прозвучал один — два были отброшены API. На экране при этом все три
 * значились отвеченными (список консультаций живёт отдельно от голоса), так
 * что Роман вслух уверял, будто коллеги не ответили. Живой звонок 26.08.2026.
 *
 * Поэтому очередь отдаёт накопленное ОДНИМ куском: одна вставка — один ответ
 * Романа, в котором он пересказывает всё пришедшее. И отдаёт только когда он
 * свободен: не говорит и не думает.
 */
export class PendingAnswers {
  private queue: string[] = [];
  private busy = false;

  /**
   * Занят ли Роман. Занят — это и «говорит», и «думает»: между вызовом
   * generateReply и началом речи модель проходит через 'thinking', и вставка
   * в этот промежуток отбивается тем же самым active-response.
   */
  setBusy(v: boolean): void { this.busy = v; }
  get isBusy(): boolean { return this.busy; }

  push(text: string): void { this.queue.push(text); }

  /**
   * Забрать накопленное одной репликой, если сейчас можно вставлять.
   * Возвращает null, когда Роман занят или очередь пуста — вызывающему
   * ничего делать не нужно.
   */
  take(): string | null {
    if (this.busy || this.queue.length === 0) return null;
    const merged = this.queue.join('\n\n');
    this.queue = [];
    // Помечаем занятость сами: состояние сессии сменится только через
    // несколько миллисекунд, а следующий ответ может прийти раньше.
    this.busy = true;
    return merged;
  }

  get size(): number { return this.queue.length; }
}
