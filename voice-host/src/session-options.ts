/**
 * Опции сессии для встречи.
 *
 * Выделено отдельным модулем ради одного флага, цена которого — все встречи
 * разом: без него ассистент слышит ровно одного участника. См. ниже.
 */

/**
 * Чем кормить сессию во встрече.
 *
 * `closeOnDisconnect: false` — иначе сессия закрывается, когда выйдет тот
 * участник, к которому RoomIO привязался первым, и встреча обрывается всем
 * остальным.
 *
 * `audioEnabled: false` — единственный способ оставить встрече НАШ микшер
 * (`MixedRoomAudioInput`), собирающий всех участников. Своего входа мало:
 * подстановку в `session.input.audio` обязан дополнять этот флаг.
 *
 * Предупреждение фреймворка при этом врёт. Найдя поле занятым,
 * `agent_session.js:403` пишет в лог «RoomIO audio input is enabled but
 * input.audio is already set, ignoring..» — и НИЧЕГО не игнорирует: следом
 * `RoomIO.start()` безусловно выполняет
 * `this.agentSession.input.audio = this.audioInput` (`room_io.js:418`) и
 * заменяет наш микшер своим `ParticipantAudioInputStream`, а тот, как сказано
 * в типах SDK, «link to the first participant».
 *
 * Отсюда жалоба, с которой всё началось: «Роман слышит только одного, похоже,
 * подписан на одну дорожку». Замер на синтетической встрече 17.09.2026 — трое
 * участников с разной громкостью, каждый зовёт по имени со своим вопросом:
 *
 *   без флага: в дампе нашего сведения все двенадцать фраз, а в API уходит
 *              один участник, и кадры чужой геометрии — 240 сэмплов вместо
 *              наших 480;
 *   с флагом:  кадры 480, в API все двенадцать фраз, ассистент отвечает всем
 *              троим.
 *
 * Обратное утверждение («флаг глушит весь аудиотракт, трогать нельзя») стояло
 * здесь с 27.08.2026 и стоило трёх дней поисков не там. Оно родилось из живой
 * встречи, где ассистент действительно вошёл глухим, но причина была другая и
 * вскрылась в тот же день: на дорожки участников тогда не подписывался никто.
 * Подписку мы с тех пор делаем сами (`mixed-audio-input.ts`), и глушить
 * нечему — во всём SDK 1.7.0 `inputOptions.audioEnabled` читается ровно в
 * одном месте, `room_io.js:367`, где решается, заводить ли RoomIO собственный
 * вход. Мьют живёт в другом поле (`AgentInput.setAudioEnabled`), этот флаг его
 * не трогает.
 *
 * Зависимость от чужого поведения проверяется тестом по коду установленного
 * SDK: `session-options.test.ts`.
 */
export function meetingInputOptions(): { closeOnDisconnect: false; audioEnabled: false } {
  return { closeOnDisconnect: false, audioEnabled: false };
}
