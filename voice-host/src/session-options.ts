/**
 * Опции сессии для встречи.
 *
 * Выделено отдельным модулем ради одного флага, цена которого — все встречи
 * разом: без него ассистент слышит ровно одного участника. См. ниже.
 */

/**
 * Чем кормить сессию во встрече.
 *
 * `closeOnDisconnect: false` — иначе сессия закрывается, когда выйдет тот
 * участник, к которому RoomIO привязался первым, и встреча обрывается всем
 * остальным.
 *
 * `audioEnabled: false` — единственный способ оставить встрече НАШ микшер
 * (`MixedRoomAudioInput`), собирающий всех участников. Своего входа мало:
 * подстановку в `session.input.audio` обязан дополнять этот флаг.
 *
 * Предупреждение фреймворка при этом врёт. Найдя поле занятым,
 * `agent_session.js:403` пишет в лог «RoomIO audio input is enabled but
 * input.audio is already set, ignoring..» — и НИЧЕГО не игнорирует: следом
 * `RoomIO.start()` безусловно выполняет
 * `this.agentSession.input.audio = this.audioInput` (`room_io.js:418`) и
 * заменяет наш микшер своим `ParticipantAudioInputStream`, а тот, как сказано
 * в типах SDK, «link to the first participant».
 *
 * Отсюда жалоба, с которой всё началось: «Роман слышит только одного, похоже,
 * подписан на одну дорожку». Замер на синтетической встрече 17.09.2026 — трое
 * участников с разной громкостью, каждый зовёт по имени со своим вопросом:
 *
 *   без флага: в дампе нашего сведения все двенадцать фраз, а в API уходит
 *              один участник, и кадры чужой геометрии — 240 сэмплов вместо
 *              наших 480;
 *   с флагом:  кадры 480, в API все двенадцать фраз, ассистент отвечает всем
 *              троим.
 *
 * Обратное утверждение («флаг глушит весь аудиотракт, трогать нельзя») стояло
 * здесь с 27.08.2026 и стоило трёх дней поисков не там. Оно родилось из живой
 * встречи, где ассистент действительно вошёл глухим, но причина была другая и
 * вскрылась в тот же день: на дорожки участников тогда не подписывался никто.
 * Подписку мы с тех пор делаем сами (`mixed-audio-input.ts`), и глушить
 * нечему — во всём SDK 1.7.0 `inputOptions.audioEnabled` читается ровно в
 * одном месте, `room_io.js:367`, где решается, заводить ли RoomIO собственный
 * вход. Мьют живёт в другом поле (`AgentInput.setAudioEnabled`), этот флаг его
 * не трогает.
 *
 * Зависимость от чужого поведения проверяется тестом по коду установленного
 * SDK: `session-options.test.ts`.
 */
export function meetingInputOptions(): { closeOnDisconnect: false; audioEnabled: false } {
  return { closeOnDisconnect: false, audioEnabled: false };
}

/** Тишина, после которой реплика считается законченной, на ВСТРЕЧЕ. */
export const MEETING_SILENCE_MS = 900;

/**
 * То же в ЗВОНКЕ. Вдвое длиннее: человек наедине с ассистентом думает вслух,
 * и пауза в секунду — середина мысли, а не её конец (замер 24.10.2026, см.
 * докстринг realtimeTurnDetection).
 */
export const CALL_SILENCE_MS = 1800;

/**
 * Разметка реплик на входе Realtime.
 *
 * Вынесено сюда из agent.ts 20.10.2026 — по той же причине, что и
 * `meetingInputOptions`: один флаг, цена которого все встречи разом, и менять
 * его уже приходилось дважды по живым наблюдениям. Теперь он на виду и закрыт
 * тестом, а не живёт посреди большого выражения.
 *
 * Порог и тишина подняты против дефолтных 0.5 и 500 мс: короткий посторонний
 * звук не должен считаться началом реплики, а пауза в середине фразы — её
 * концом.
 *
 * `create_response: false` на встрече — ответ начинает не модель, а гейт по
 * имени. Разметка реплик при этом сохраняется, мы её и слушаем.
 *
 * `interrupt_response: false` НА ВСТРЕЧЕ — это разворот решения 16.09.2026, и
 * вот чем он оплачен.
 *
 * Прежде стояло `true`: без него сервер, пока у ассистента открыт ответ, может
 * не размечать чужую речь вовсе. Опасение было «пока он говорит, никого не
 * слышно, а говорит он ЧАСТО» — и на синтетическом стенде так и было: девять
 * фраз на входе, до гейта дошли две.
 *
 * Но на стенде гейта по имени фактически не было. Замер настоящей встречи
 * 20.10.2026 (Meet, четверо участников, 64 минуты) показал обратное:
 *
 *   решения гейта:    4 respond, 88 silent
 *   речь ассистента:  8.1с + 1.6с + 2.8с(прерван) = 12,5 секунды, то есть 0,3%
 *
 * Говорит он не часто, а почти никогда. Зато `interrupt_response: true` — это
 * СЕРВЕРНОЕ перебивание: OpenAI снимает ответ, едва его VAD услышал чужую
 * речь, и наша защита `turnHandling.interruption` (800 мс, два слова) к нему
 * отношения не имеет — она живёт внутри SDK. На многолюдной встрече, где
 * говорят непрерывно, это означало, что ассистент не может договорить ни одной
 * фразы: его обрывали на второй-третьей секунде, а один ответ умер через 160
 * мс, не дав ни звука. Со стороны это выглядело как «позвали — не ответил».
 *
 * Цена разворота — те самые двенадцать секунд в час, когда он может не
 * услышать начала чужой фразы. Перебить его по-прежнему можно: тормоз на
 * уровне SDK никуда не делся.
 *
 * ЕСЛИ ВОЗВРАЩАТЬ `true` — сначала убедитесь, что он снова говорит часто.
 * Решение 20.10.2026 опирается на долю его речи, а не на вкус.
 *
 * ⚠️ ТИШИНА В ЗВОНКЕ ДЛИННЕЕ, ЧЕМ НА ВСТРЕЧЕ (26.10.2026) — и вот почему.
 *
 * На встрече люди говорят друг с другом законченными фразами. В звонке
 * владелец думает вслух, и его мысль приходит обрывками с паузами длиннее
 * секунды. Разбор звонка 24.10.2026 (13 минут, отказ от вейпа): на один
 * смысловой ход пришлось до ПЯТИ отдельных реплик — «Прайси и…», «После
 * того, как просыпаюсь, когда пью кофе.», «…у меня ощущение…», «Как будто
 * вата в голове появляется.», и только потом законченная мысль.
 *
 * При 900 мс сервер открывал ответ на ПЕРВОМ же огрызке. Пока модель его
 * генерировала (полминуты), приезжали остальные четыре — но ответ уже был
 * зафиксирован на «Прайси и…», то есть на тексте без смысла. Модели нечего
 * было сказать нового, и она ДОСЛОВНО повторила свою прошлую реплику:
 * шестьдесят секунд речи, в точности повторяющей предыдущую, включая
 * вопрос, на который человек только что ответил. В том же разговоре это
 * случилось дважды, в разговоре 23.10.2026 — шесть раз.
 *
 * Повтор, таким образом, не причуда модели, а следствие разметки: ответ
 * строится на снимке контекста, который к моменту речи устарел.
 *
 * 1800 мс — это пауза, после которой человек в разговоре один на один
 * действительно замолчал, а не набирает воздух. Цена — ответ начинается на
 * девятьсот миллисекунд позже; перебить Романа по-прежнему можно в любой
 * момент (`interrupt_response` в звонке остаётся умолчанием API, то есть
 * включён).
 */
export function realtimeTurnDetection(isMeeting: boolean): {
  type: 'server_vad';
  threshold: number;
  prefix_padding_ms: number;
  silence_duration_ms: number;
  create_response?: false;
  interrupt_response?: false;
} {
  return {
    type: 'server_vad',
    threshold: 0.65,
    prefix_padding_ms: 300,
    // Звонок — человек думает вслух и говорит обрывками; встреча — люди
    // говорят друг с другом законченными фразами. См. докстринг.
    silence_duration_ms: isMeeting ? MEETING_SILENCE_MS : CALL_SILENCE_MS,
    ...(isMeeting ? { create_response: false as const, interrupt_response: false as const } : {}),
  };
}
