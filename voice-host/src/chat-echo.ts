/**
 * Своё эхо в чате встречи через мост.
 *
 * ЗАЧЕМ. Мост отдаёт нам ВСЕ сообщения чата, включая те, что сам же отправил
 * по нашей просьбе. Живая встреча Teams 14.09.2026: ассистент написал в чат
 * «„Ночь в Лиссабоне“ — Эрих Мария Ремарк», сообщение вернулось входящим с
 * автором «Роман · ассистент пользователя», гейт счёл его обращением и
 * ассистент ответил вслух на собственную реплику. В комнатах Taler ID такого
 * не бывает: там эхо отсекается по `clientMsgId`, который мы сами и задаём.
 * У моста своего опознавателя сообщения нет.
 *
 * КАК. Две проверки, и обе нужны:
 *
 * 1. По автору — точная. Наше имя во встрече мы знаем, и мост присылает его
 *    в `sender_name`.
 * 2. По тексту — на случай, когда имя не совпадает. Teams обрезает длинные
 *    имена ботов (в самом Attendee есть правка ровно об этом), и сверка имён
 *    там разойдётся на ровном месте. Помним только недавно отправленное:
 *    участник вправе повторить чужую фразу дословно, и вечная память
 *    проглатывала бы его сообщение.
 */

/** Сколько помним отправленное. Эхо приходит за секунды; минуты — с запасом. */
const TTL_MS = 120_000;

/** Сколько сообщений помним. Больше — уже не эхо, а история. */
const LIMIT = 20;

/** Сравниваем по смыслу, а не побайтово: мост может сжать пробелы. */
function norm(s: string): string {
  return String(s ?? '').replace(/\s+/g, ' ').trim().toLowerCase();
}

export class OwnChatEcho {
  private sent: { at: number; text: string }[] = [];

  /**
   * @param displayName имя ассистента во встрече — то же, под которым он
   *   вошёл. Пустое значит «сверять только по тексту».
   */
  constructor(private readonly displayName = '') {}

  /** Запомнить своё отправленное сообщение. */
  note(text: string, now = Date.now()): void {
    const t = norm(text);
    if (!t) return;
    this.sent.push({ at: now, text: t });
    if (this.sent.length > LIMIT) this.sent.shift();
  }

  /**
   * Наше ли это сообщение.
   *
   * Совпавшее по тексту эхо ЗАБЫВАЕТСЯ: иначе повтор той же фразы человеком
   * через минуту тоже пропал бы, а это уже его реплика, и отвечать на неё
   * ассистент обязан.
   */
  isOwn(sender: string, text: string, now = Date.now()): boolean {
    if (this.displayName && norm(sender) === norm(this.displayName)) return true;
    const t = norm(text);
    if (!t) return false;
    const i = this.sent.findIndex((m) => m.text === t && now - m.at <= TTL_MS);
    if (i < 0) return false;
    this.sent.splice(i, 1);
    return true;
  }
}
