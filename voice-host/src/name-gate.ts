/**
 * Окончания, с которыми имя остаётся обращением.
 *
 * Список закрытый, а не «имя плюс до трёх букв»: свободный хвост превращает
 * «Роман» в «романтику», а «Анну» в «аннотацию» — то есть ассистент влезал бы
 * в чужой разговор, не будучи позванным. Ложное молчание дешевле ложной
 * реплики при клиенте.
 */
const ENDINGS = ['', 'а', 'у', 'е', 'ы', 'и', 'ом', 'ой', 'ей', 'ю', 'я', 'ье', 'ем'];

/** «Роман, пока слушай» и синонимы. */
const LISTEN_CMD = /(пока\s+слушай|просто\s+слушай|молчи|в\s+режим\w*\s+слушател)/i;

/** «Роман, вопрос к тебе» и синонимы. */
const RESUME_CMD = /(вопрос\s+к\s+тебе|можешь\s+говорить|возвращайся|подключайся|включайся)/i;

/**
 * «Это не тебе», «помолчи», «тихо» — просьба замолчать.
 *
 * Проверяется РАНЬШЕ обращения по имени и раньше окна продолжения. Иначе
 * получается замкнутый круг: во фразе «Роман, это не тебе вопрос» есть имя,
 * гейт считает её обращением и отвечает — то есть попытка остановить
 * ассистента сама заставляет его говорить. Поймано на живой встрече
 * 28.08.2026.
 */
const STOP_CMD = /(не\s+теб[ея]|не\s+к\s+тебе|помолчи|тише|тихо|замолчи|не\s+вмешивайся|это\s+не\s+твой)/i;

/**
 * Поддакивание, а не реплика: «угу», «ага», «ну да», «понятно», смех.
 *
 * Отсекается ТОЛЬКО в окне продолжения — там, где имени не прозвучало и ход
 * даётся по инерции. Обращение по имени проходит всегда, даже если это одно
 * слово: «Роман» само по себе — законный вызов.
 *
 * Зачем. Окно открывается фактом ответа, а на встрече между вопросами звучат
 * десятки таких междометий. Каждое получало ход, модель по инструкции из
 * answerTo() честно отвечала «я не расслышал вопрос», этот ответ снова
 * продлевал окно — и дальше по кругу. Встреча 07.09.2026, 09:25–09:27: восемь
 * отговорок подряд на «угу», «м», «да-да». Со стороны это выглядело так, будто
 * ассистент не слышит никого, кроме владельца, — участники так и решили, и
 * прямо в записи спросили «похоже, только меня что ли слышно?».
 */
const BACKCHANNEL =
  /^(угу|ага|м+|хм+|э+|да|да-да|нет|ну|ну\s+да|ну\s+вот|вот|так|ок|окей|понятно|понял|хорошо|ладно|ясно|точно|конечно|спасибо|ха(-?ха)*|хах+|было|есть)[\s.,!?…-]*$/i;

/** Реплика — только поддакивание, отвечать не на что. */
export function isBackchannel(text: string): boolean {
  return BACKCHANNEL.test(normalize(text).trim());
}

/**
 * Ассистент не ответил, а отговорился: «не расслышал», «это не ко мне».
 *
 * Формулировки не случайные — их диктует наш же answerTo() на случай, когда
 * реплика оборвана или не разобрана. Отговорка не должна продлевать окно
 * продолжения: разговора с ассистентом не возникло, продолжать нечего. Без
 * этого условия окно держал открытым сам факт того, что он что-то произнёс, и
 * петля из комментария выше не разрывалась даже после фильтра поддакиваний —
 * отговорку вызывает и обычная фоновая фраза, не разобранная распознаванием.
 */
export function isDeflection(text: string): boolean {
  return /(не\s+(совсем\s+)?рассл|не\s+услыш|не\s+вопрос\s+ко\s+мне|не\s+ко\s+мне|просто\s+слушаю|продолжаю\s+слушать)/i.test(
    normalize(text),
  );
}

/** Что делать с репликой, которую только что распознали. */
export type GateDecision =
  /** промолчать */
  | 'silent'
  /** дать модели ход */
  | 'respond'
  /** подтвердить уход в режим слушателя одной фразой */
  | 'ack_listen'
  /** подтвердить возвращение в диалог одной фразой */
  | 'ack_resume';

function normalize(s: string): string {
  return (s || '').toLowerCase().replace(/ё/g, 'е');
}

/**
 * Основа имени для склонения: у имён на гласную она без неё (Анна → анн),
 * у остальных — само имя (Роман → роман).
 */
function stemOf(name: string): string {
  const n = normalize(name).trim();
  return /[аеиоуыэюя]$/.test(n) ? n.slice(0, -1) : n;
}

/** Прозвучало ли в реплике обращение к ассистенту с этим именем. */
export function addressedByName(text: string, name: string): boolean {
  const stem = stemOf(name);
  if (!stem) return false;
  return normalize(text)
    .split(/[^a-zа-я0-9]+/)
    .filter(Boolean)
    .some((w) => w.startsWith(stem) && ENDINGS.includes(w.slice(stem.length)));
}

/**
 * Когда ассистенту позволено говорить на встрече.
 *
 * По умолчанию молчит. Отвечает, если назвали по имени, и дальше некоторое
 * время отвечает без имени: иначе доспросить его «а почему?» было бы
 * невозможно, пришлось бы звать заново на каждую фразу.
 *
 * Окно продолжения открывает ФАКТ ответа (noteReplied), а не факт обращения.
 * Если модель промолчала — разговора нет, и продолжать нечего.
 *
 * Поверх этого — режим слушателя по голосовой команде. Команды распознаются
 * ТОЛЬКО вместе с именем: «вопрос к тебе», сказанное одним живым участником
 * другому, не должно возвращать в разговор ассистента, которого оттуда
 * специально убрали.
 */
export class NameGate {
  private openUntil = 0;
  private muted = false;
  /**
   * Кто открыл окно продолжения. Ведём для лога и разбора: на решение окно
   * больше не влияет — см. решение владельца 07.09.2026 в decide().
   */
  private windowOwner: string | undefined;

  /**
   * Когда к ассистенту обратились по имени в последний раз.
   *
   * От этого момента, а НЕ от последнего его ответа, считается общий потолок
   * окна. Иначе выходит самоподдерживающийся цикл: ответил — окно открылось
   * ещё на windowMs, в него попала следующая реплика, ответил снова — окно
   * продлилось опять. Пока разговор идёт, оно не закрывается никогда, и
   * «отвечает, когда позвали» вырождается в «отвечает всегда».
   *
   * Живая встреча 28.08.2026: под конец он отзывался на «Филипп», «Сестра»,
   * «я», «никому» — на любой обрывок распознавания. А получасом раньше, когда
   * окно успело закрыться, молчал на прямые содержательные вопросы. Один и тот
   * же параметр давал обе крайности.
   *
   * Ноль как начальное значение работает на нас: до первого обращения потолок
   * лежит в далёком прошлом, поэтому представление ассистента (он говорит, не
   * будучи позванным) окно не открывает.
   */
  private lastAddressedAt = 0;

  /**
   * В комнате один живой участник.
   *
   * Тогда молчание по умолчанию теряет смысл: правило «отвечай, только когда
   * назвали» защищает от вмешательства в чужой разговор, а чужого разговора
   * при одном человеке не бывает. Живая встреча 03.09.2026 показала цену
   * этого буквоедства — владелец вёл нормальную деловую беседу, а ассистент
   * молчал на три содержательные реплики подряд просто потому, что в них не
   * прозвучало его имя.
   *
   * Команды при этом продолжают работать и без имени: звать по имени, чтобы
   * попросить помолчать, наедине тоже незачем.
   */
  private solo = false;

  /**
   * @param windowMs сколько окно живёт после каждого ответа
   * @param maxWindowMs сколько оно живёт суммарно от обращения по имени.
   *   Две минуты: доспросить «а почему?» и уточнить ответ успеваешь, а
   *   бесконечно висеть открытым оно перестаёт.
   */
  constructor(
    private readonly name: string,
    private readonly windowMs: number,
    private readonly maxWindowMs: number = 120_000,
  ) {}

  /** Сколько живых участников в комнате. Считает воркер по составу комнаты. */
  setSolo(solo: boolean): void {
    this.solo = solo;
  }

  /**
   * @param speaker кто говорит, если известно. На решение не влияет — окно
   *   продолжения действует на всю комнату; запоминается только для лога.
   */
  decide(text: string, now: number, speaker?: string): GateDecision {
    const addressed = addressedByName(text, this.name);

    // Просьба замолчать — раньше всего остального.
    if (STOP_CMD.test(text)) {
      this.openUntil = 0;
      this.windowOwner = undefined;
      // Молча отходим в сторону: подтверждать вслух «хорошо, молчу» — значит
      // снова заговорить там, где попросили этого не делать.
      return 'silent';
    }

    // Отметка об обращении — до всех веток, а не только перед 'respond'.
    // «Роман, вопрос к тебе» из режима слушателя возвращает ack_resume и
    // выходит раньше; без отметки здесь потолок остался бы от прошлого
    // обращения (или от нуля), и доспросить после возвращения было бы нельзя.
    if (addressed) this.lastAddressedAt = now;

    // Наедине команды принимаются и без имени — обращаться не к кому больше.
    const addressedOrSolo = addressed || this.solo;

    if (addressedOrSolo && LISTEN_CMD.test(text)) {
      this.muted = true;
      // Окно тоже гасим: без этого следующая реплика прошла бы по нему, и
      // режим слушателя включился бы с задержкой в полминуты.
      this.openUntil = 0;
      return 'ack_listen';
    }

    // Обратная команда работает только из режима слушателя. Иначе обычное
    // «Роман, вопрос к тебе» превращалось бы в подтверждение вместо ответа.
    if (this.muted && addressedOrSolo && RESUME_CMD.test(text)) {
      this.muted = false;
      return 'ack_resume';
    }

    if (this.muted) return 'silent';
    // Один человек — разговор с ним и идёт. Гейт по имени включится сам,
    // как только в комнате появится второй.
    if (this.solo) return 'respond';
    if (addressed) {
      this.windowOwner = speaker;
      return 'respond';
    }

    // Окно продолжения — на всю комнату, а не на того, кто ассистента позвал.
    //
    // Раньше здесь стояла привязка windowOwner === speaker: окно действовало
    // только для человека, произнёсшего имя. Ставилась она 28.08.2026 против
    // ложных срабатываний — ассистент влезал в разговор двух других людей.
    // Цена оказалась выше пользы, и видно это стало на встрече 07.09.2026:
    // имя за весь час произнёс ОДИН участник, владелец. Остальные задавали
    // вопросы («а для livekit нет плагинчиков для зума?», «как мы попадём в
    // этот ТикТок?») и не получали ничего; владелец дважды передавал слово
    // вслух — «Серёга, скажешь что-нить?», «Володя, ты спроси что-то» — и оба
    // раза ассистент молчал. Участники решили, что он их не слышит, и прямо
    // в записи спросили «похоже, только меня что ли слышно?».
    //
    // Ложные срабатывания, ради которых привязку вводили, теперь снимаются
    // ближе к причине: поддакивания в окно не проходят (BACKCHANNEL), а
    // отговорка окно не продлевает (isDeflection) — раньше именно они держали
    // его открытым бесконечно. Плюс потолок maxWindowMs от обращения по имени
    // никуда не делся: без нового обращения окно закроется через две минуты.
    //
    // Решение владельца 07.09.2026.
    if (now < this.openUntil && !isBackchannel(text)) {
      return 'respond';
    }
    return 'silent';
  }

  /**
   * Ассистент закончил реплику — окно продолжения продлевается, но не дальше
   * общего потолка от последнего обращения по имени.
   *
   * @param text что он произнёс. Нужен, чтобы отличить ответ от отговорки:
   *   «я не расслышал вопрос» разговора не начинает, и продлевать окно после
   *   него — значит поддерживать петлю самому (см. isDeflection).
   */
  noteReplied(now: number, text?: string): void {
    if (this.muted) return;
    if (text !== undefined && isDeflection(text)) return;
    // Ни разу не звали — продолжать нечего. Это представление или служебная
    // реплика, и окна после них быть не должно. Условие явное, а не через
    // «нулевой потолок лежит в прошлом»: в бою now — это эпоха и трюк бы
    // сработал, но логика не должна зависеть от величины таймстампа.
    if (!this.lastAddressedAt) return;
    this.openUntil = Math.min(now + this.windowMs, this.lastAddressedAt + this.maxWindowMs);
  }
}
