/**
 * Инструкции и служебные реплики для голосовых сессий.
 *
 * Звонок и встреча — разные режимы: в звонке собеседник один и говорит с
 * ассистентом, на встрече их несколько и разговор идёт между ними. Отсюда две
 * пары функций, а не одна с флагом.
 */

/** Контекст встречи. У звонка его нет — там ведущий всегда Роман. */
export interface MeetingPromptContext {
  /** Имя ассистента, как его знают люди */
  name: string;
  /** Его собственный системный промпт из таблицы agents */
  persona: string;
  /**
   * Имя владельца — чтобы было чем представиться, когда спросят.
   *
   * Во вступлении его больше нет (см. meetingIntro): на входе ассистент
   * называет только себя. Развёрнутый ответ остался один — по прямому
   * вопросу, и имя нужно здесь.
   *
   * В именительном падеже: это инструкция модели, а не скрипт на
   * произнесение, падеж она поставит сама. ownerGenitive() из
   * src/meeting/assistant-signature.ts сюда не тянем — он в бэкенде, воркер
   * отдельный процесс, и связывать их ради одной строки незачем.
   */
  ownerName?: string;
  preamble: string;
  specialists: { name: string; role: string }[];
  /**
   * Есть ли у встречи текстовый чат.
   *
   * Бывает на чужой встрече: в комнате Taler ID (их ручка чата) и на встрече
   * через мост — Meet или Zoom. В свои встречи и в звонок тулы чата не
   * попадают вовсе. Рассказывать про инструмент, которого у модели нет,
   * нельзя — она пообещает «написал в чат» и не напишет никуда.
   */
  hasChat?: boolean;
  /**
   * Можно ли в этот чат писать. По умолчанию да — исключение одно.
   *
   *
   * На Телемосте нельзя: гостю площадка показывает «Войдите, чтобы написать
   * сообщение». Читать можно. Рассказывать про запись там, где её нет, —
   * значит получить «я написал в чат» без единого сообщения, что и случилось
   * 15.09.2026.
   */
  canWriteChat?: boolean;
  /**
   * Что написали в чате ДО прихода ассистента, строками «Кто: текст».
   *
   * Это справка, а не обращения к нему: встреча шла без него, и вопросы в этих
   * строках заданы не ему и, скорее всего, давно закрыты.
   */
  chatHistory?: string[];
}

