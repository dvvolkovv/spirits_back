/**
 * Первая фраза на встрече — приветствие и предупреждение о записи.
 *
 * Единственное исключение из молчания: произносится сразу после подключения,
 * до всякого обращения.
 *
 * Правило обращения отсюда УБРАНО (решение владельца 12.10.2026, отменяет
 * решение 26.08.2026). Оно занимало половину вступления, а нужды в нём нет:
 *   • гейт открывается на одно ИМЯ — «Роман» сам по себе законный вызов
 *     (addressedByName в name-gate.ts), формула «вопрос к тебе» необязательна;
 *   • формулу возврата произносит listenAck() — то есть ровно в тот момент,
 *     когда ассистента увели в молчание и она кому-то понадобилась;
 *   • полный ответ про себя и про обе команды остался в meetingInstructions()
 *     и звучит по прямому вопросу.
 *
 * Имя владельца тоже убрано: на внешней встрече люди видят его в списке
 * участников — «Роман · ассистент Дмитрия» (assistant-signature.ts).
 *
 * Запреты перечислены явно и поимённо. Persona и список специалистов лежат в
 * том же системном промпте, и на короткое «представься» модель охотно
 * пересказывает их целиком — ровно та многословность, от которой уходим.
 */
export function meetingIntro(name: string): string {
  return (
    'Ты только что вошёл во встречу. Скажи ПО-РУССКИ ОДНУ короткую фразу и замолчи: ' +
    `поздоровайся, назовись — ${name}, — и скажи, что встреча записывается. ` +
    'Ни одного английского слова. Не рассказывай, кто ты и что умеешь, ' +
    'не объясняй, как к тебе обращаться, не задавай вопросов и не перечисляй списков.'
  );
}

/**
 * Подсказка распознаванию: как зовут ассистента.
 *
 * Имя — единственная точка отказа всей встречи. Гейт сверяет ТЕКСТ, и одна
 * перепутанная буква превращает «Роман, вопрос к тебе» в чужой разговор:
 * ассистент молчит, в логе — обычная строка silent, и со стороны это выглядит
 * как «он нас не слышит». Ровно так и было 14.09.2026, и раньше — 28.08.2026,
 * когда имя распознавалось как «Норман» и «Raman».
 *
 * Замер 15.09.2026 на шести записях, где имя слетало: без подсказки модель
 * услышала «Роман» 1 раз из 18, с подсказкой — 18 из 18. Смысловая часть
 * фразы при этом не страдала никогда, даже при отношении сигнал/шум 3 дБ:
 * ломается именно имя собственное, и лечится оно тем, что модели заранее
 * сказали, какое имя здесь ожидается.
 *
 * Поле `prompt` живёт в тех же настройках звука, что и злополучный `keywords`,
 * который API отвергает целиком вместе с языком и голосом. Поэтому перед
 * правкой оно проверено на живом API (`POST /v1/realtime/client_secrets`):
 * `prompt` принимается и возвращается в конфиге сессии, `keywords` в том же
 * запросе отбивается. Добавлять сюда что-то ещё — только так же, с проверкой.
 */
export function transcriptionPrompt(name: string, terms: readonly string[] = ASR_TERMS): string {
  const tail = terms.length > 0 ? ` Встречаются термины: ${terms.join(', ')}.` : '';
  return `Рабочая встреча на русском языке. Ассистента зовут ${name} — к нему обращаются по имени.${tail}`;
}

/**
 * Подсказка распознаванию для ЗВОНКА.
 *
 * <p>Отдельная от встречи, и это не косметика. До 26.10.2026 у звонка не было НИКАКОЙ
 * настройки распознавания: блок `inputAudioTranscription` стоял под условием `isMeeting`,
 * то есть звонок шёл на модели по умолчанию и БЕЗ указания языка. Цена видна в живых
 * расшифровках владельца: посреди русского разговора «Evet», «Ne zaman?», «Прайси и…»,
 * «отказ от творения от Вэки» вместо «отказ от вейпа», «отказ от выплат» вместо того же.
 *
 * <p>Это не косметика расшифровки: на ней стоит всё, что остаётся от разговора. Резюме
 * пересказывает её, профиль извлекает из неё факты — и 24.10.2026 верный факт «поставил
 * задачу на 31 октября, отказ от вейпа» был отклонён проверкой именно потому, что в
 * расшифровке стояло «отказ от выплат», которого в свидетельстве, разумеется, нет.
 *
 * <p>Рамка другая, чем у встречи: разговор один на один, собеседник один, и «рабочая
 * встреча» сбивала бы модель с регистра речи.
 */
export function callTranscriptionPrompt(terms: readonly string[] = ASR_TERMS): string {
  const tail = terms.length > 0 ? ` Встречаются термины: ${terms.join(', ')}.` : '';
  return `Личный разговор один на один на русском языке. Человек думает вслух, говорит ` +
    `неторопливо и с паузами.${tail}`;
}

/**
 * Термины, которые распознавание ломает предсказуемо.
 *
 * Пополняется ТОЛЬКО по факту: термин попадает сюда, когда его слышали неверно в живом
 * разговоре, — а не «на всякий случай». Длинная подсказка уводит расшифровку в пересказ
 * самой подсказки (см. {@link isTranscriptionEcho}), поэтому место здесь дорогое.
 *
 * `ABA-терапия` — разговор 12.10.2026: расслышано как «ЕБИ-терапия» и в таком виде дошло
 * до профиля. Цена ошибки здесь выше обычной опечатки: термин про занятия с ребёнком
 * превратился в непристойность, и владелец правил это руками.
 *
 * ⚠️ Подсказка общая для всех встреч, поэтому термины должны быть общеупотребимыми. Личный
 * словарь пользователя сюда не кладётся: для этого у `transcriptionPrompt` есть параметр,
 * и такой словарь поедет из бэкенда, когда появится, — а не глобальным списком.
 */
export const ASR_TERMS: readonly string[] = ['ABA-терапия'];

/**
 * Расшифровка вернула саму подсказку, а не то, что сказал человек.
 *
 * Так модель отвечает на невнятный кусок звука: вместо текста реплики отдаёт
 * prompt целиком или его начало. В нём есть имя ассистента, поэтому гейт
 * принимал это за обращение и поднимал Романа отвечать самому себе — живая
 * встреча 16.09.2026, дважды за десять минут.
 *
 * Сверяем по началу подсказки, а не по полному совпадению: эхо приходит и
 * обрезанным («Рабочая встреча на русском языке.»), и с изменённой пунктуацией.
 */
export function isTranscriptionEcho(text: string, name: string): boolean {
  const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();
  const head = norm(transcriptionPrompt(name)).slice(0, 40);
  return norm(text).startsWith(head.slice(0, 30));
}

/**
 * На какую именно реплику отвечать, получив ход.
 *
 * Без этого указания `session.generateReply()` отдаёт модели «разговор целиком»,
 * а на встрече это десятки реплик, которые она слышала, но не отвечала — гейт
 * держал её в молчании. Модель разбирает их как очередь необработанных вопросов
 * и отвечает на позавчерашний.
 *
 * Встреча 28.08.2026: на «Какая насадка червонная?» пришёл ответ про высоту
 * Джомолунгмы — её называли двумя минутами раньше, когда ассистента попросили
 * просто слушать. Выглядело как будто он невпопад, а он добросовестно разгребал
 * накопленное.
 *
 * Отдельно про «не угадывай». Распознавание на встрече разваливается: дальнее
 * поле плюс несколько голосов в одном потоке дают «Зависота двуса» вместо «а
 * высота Эльбруса». Уверенный ответ на такой мусор хуже переспроса — при клиенте
 * особенно.
 */
export function answerTo(text: string): string {
  return (
    `Тебе адресована реплика: «${text}». Ответь ПО-РУССКИ именно на неё. ` +
    'Всё, что звучало раньше без обращения к тебе, — фон встречи: помни как ' +
    'контекст, но не отвечай на это и не возвращайся к этому сам. ' +
    'Если реплика оборвана или не разобрана — скажи одной фразой, что не ' +
    'расслышал, и замолчи. Не угадывай, о чём тебя могли спросить.'
  );
}

/**
 * Обращение пришло текстом, а не голосом.
 *
 * Отдельно от answerTo по двум причинам. Автор письменного сообщения известен
 * точно (его присылает их сервер), а у речи он угадан по активному
 * говорящему — этим стоит воспользоваться. И ответ на письменную просьбу
 * часто сам просится текстом: ссылку, продиктованную вслух, никто не наберёт.
 */
export function answerToChat(who: string, text: string): string {
  return (
    `${who} написал в чат встречи: «${text}». Ответь ПО-РУССКИ вслух, коротко, ` +
    'обращаясь к нему. Если ответ — ссылка, адрес, номер или список, отправь ' +
    'его инструментом write_to_chat, а голосом скажи одной фразой, что написал ' +
    'в чат. Остальное, что звучало без обращения к тебе, — фон встречи: не ' +
    'отвечай на это.'
  );
}

/**
 * Подтверждения переключения режима.
 *
 * Заданы явно, а не отданы модели на импровизацию: это служебная реакция, и
 * звучать она должна одинаково, чтобы участники понимали — команда услышана.
 */
/**
 * Уход в режим слушателя. Вместе с подтверждением — как оттуда вернуть.
 *
 * Правило обращения проговаривается и во вступлении, но к моменту команды оно
 * прозвучало давно и не для всех: ассистента зовут в середине встречи, люди
 * входят и выходят. Встреча 14.09.2026: «Роман, пока слушай» сказали на второй
 * минуте, формулу возврата не вспомнил никто, и остальные 47 минут участники
 * считали, что он их не слышит. Одна фраза в нужный момент дешевле любого
 * автоматического послабления.
 */
export function listenAck(name: string): string {
  return (
    `Скажи ПО-РУССКИ ровно «Хорошо, слушаю. Скажите «${name}, вопрос к тебе», ` +
    'когда понадоблюсь» и замолчи. Больше ни слова.'
  );
}

/**
 * Прощание при уходе по просьбе.
 *
 * Ровно одна фраза: ассистента попросили уйти, и разворачивать на этом месте
 * благодарности — значит задержать встречу ещё на полминуты. Но и молча
 * исчезать нельзя: на слух «вышел» и «замолчал» неразличимы, а вернуть его
 * можно только карточкой из чата.
 */
export function farewell(): string {
  return 'Скажи ПО-РУССКИ ровно «Хорошо, до свидания» и замолчи. Больше ни слова.';
}

export function resumeAck(): string {
  return 'Скажи ПО-РУССКИ ровно «Снова на связи» и замолчи. Больше ни слова.';
}
