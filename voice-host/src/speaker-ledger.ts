/**
 * Кому приписать реплику на встрече.
 *
 * Раньше говорящий брался одним снимком: обработчик ActiveSpeakersChanged писал
 * имя в переменную, а ConversationItemAdded читал её в момент коммита реплики.
 * Момент выбран неудачно — коммит приходит ПОСЛЕ того, как человек замолчал, и
 * к этой секунде активных говорящих либо уже нет, либо это следующий участник.
 *
 * Встреча 07.09.2026, 298 человеческих реплик: 130 ушли вообще без метки, а из
 * размеченных содержательные фразы владельца регулярно приписывались соседям.
 * Метка «Сергей» стояла на 76 репликах, суммарно 1965 знаков — почти сплошь
 * «угу» и «ну да», то есть на длинных фразах снимок не срабатывал никогда.
 * Разбор по этому транскрипту дал ложный вывод «ассистент слышал всех
 * поимённо», хотя поимённо он не слышал никого.
 *
 * Считаем иначе: копим ВРЕМЯ речи каждого участника между коммитами и
 * приписываем реплику тому, кто наговорил больше. Хоровую речь это тоже
 * разрешает в пользу того, кто говорил дольше, — при перебивании метка
 * по-прежнему приблизительная, но перестаёт быть случайной.
 */
export class SpeakerLedger {
  /** Наговорено с прошлого коммита, по участникам. */
  private readonly msByName = new Map<string, number>();
  /** Кто говорит прямо сейчас. */
  private active: string[] = [];
  /** С какого момента идёт текущий отрезок. */
  private since: number;

  /**
   * @param startedAt момент старта отсчёта. Передаётся явно: в тестах время
   *   своё, а брать Date.now() внутри — значит не уметь их писать.
   */
  constructor(startedAt: number) {
    this.since = startedAt;
  }

  /** Активные говорящие сменились. */
  setActive(names: string[], now: number): void {
    this.charge(now);
    this.active = names;
    this.since = now;
  }

  /**
   * Кто говорил дольше всех с прошлого вызова. Счётчик обнуляется: следующая
   * реплика считается со своего отрезка, иначе первый же разговорчивый
   * участник забирал бы метку у всей встречи.
   *
   * undefined — если за отрезок никто не был активен. Так бывает: у части
   * участников LiveKit не отдаёт активность вовсе (браузер без индикации
   * громкости), и лучше честно не знать, чем приписать реплику соседу.
   */
  takeDominant(now: number): string | undefined {
    this.charge(now);
    this.since = now;
    let best: string | undefined;
    let bestMs = 0;
    for (const [name, ms] of this.msByName) {
      if (ms > bestMs) {
        best = name;
        bestMs = ms;
      }
    }
    this.msByName.clear();
    return best;
  }

  /** Начислить прошедшее время тем, кто был активен на отрезке. */
  private charge(now: number): void {
    const dt = now - this.since;
    if (dt <= 0) return;
    for (const name of this.active) {
      this.msByName.set(name, (this.msByName.get(name) ?? 0) + dt);
    }
  }
}
