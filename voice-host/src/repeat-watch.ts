/**
 * Дословные повторы реплик в расшифровке — и чем каждый из них оказался.
 *
 * ⚠️ Зачем отдельный заслон, если в agent.ts уже есть сверка по идентификатору
 * записи. Та сверка отвечает только на половину вопроса: если одна и та же
 * запись приехала дважды, она скажет это в лог; если ту же фразу принесла
 * ДРУГАЯ запись — молчит, и молчит ровно так же, как при полном отсутствии
 * повторов. С 30.10 по 02.11.2026 в логе прода не было ни одной такой строки,
 * а в расшифровках владельца за те же недели — 72 дословных повтора на 35
 * разговоров (разбор 03.11.2026). То есть молчание лога не значило ничего.
 *
 * Здесь вторая половина: повтор ловится по тексту, независимо от id. Вердикт
 * отличает двойную доставку одной записи от второго ответа модели.
 *
 * Что известно о 72 повторах на 03.11.2026: все до единого — реплики
 * ассистента; 64 из 72 стоят сразу за репликой человека; медиана разрыва 84 с,
 * минимум 6,8 с. В том же разговоре лог Realtime показывает много ответов с
 * `cancelled` — похоже на переответ после перебивания, но это ещё НЕ измерено:
 * идентификаторов записей в сохранённых расшифровках нет, их приносит только
 * живой разговор.
 *
 * Повтор отсюда НЕ выбрасывается. Если модель правда сказала фразу дважды,
 * запись об этом верна, а выбросив её, мы потеряли бы вместе с ней и замер.
 */

/**
 * Короче какого повтора не считаем.
 *
 * Тот же порог, по которому считались 72 повтора в разборе расшифровок.
 * «Да.», «Понял.», «Слушаю.» повторяются в живом разговоре постоянно и
 * дефектом не являются — на них счётчик сработал бы на каждом звонке.
 */
export const REPEAT_MIN_CHARS = 40;

export interface Repeat {
  role: 'user' | 'assistant';
  /** Знаков в повторённой реплике. */
  chars: number;
  /** Сколько прошло с первой такой реплики, мс. */
  sinceMs: number;
  /** Запись, принёсшая повтор, и запись, принёсшая оригинал. */
  id: string;
  earlierId: string;
  /** Один и тот же идентификатор → это одна запись, доехавшая дважды. */
  sameItem: boolean;
}

export class RepeatWatch {
  private readonly seen = new Map<string, { id: string; at: number }>();

  /**
   * Запомнить реплику и сказать, повтор ли это.
   *
   * Сравниваем по тексту, свёрнутому по пробелам: расшифровка одной и той же
   * фразы приходит с разной разбивкой строк. Регистр и знаки препинания НЕ
   * трогаем — в дословном повторе они совпадают, а их отбрасывание склеило бы
   * разные реплики.
   */
  note(role: 'user' | 'assistant', text: string, itemId: string | undefined, now: number): Repeat | null {
    const said = text.replace(/\s+/g, ' ').trim();
    if (said.length < REPEAT_MIN_CHARS) return null;
    const key = `${role}\n${said}`;
    const earlier = this.seen.get(key);
    this.seen.set(key, { id: itemId || '-', at: now });
    if (!earlier) return null;
    return {
      role,
      chars: said.length,
      sinceMs: now - earlier.at,
      id: itemId || '-',
      earlierId: earlier.id,
      sameItem: !!itemId && itemId === earlier.id,
    };
  }
}

/** Строка для лога. Без текста реплики: содержимое разговора в логи не попадает. */
export function repeatLine(r: Repeat): string {
  const what = r.sameItem ? 'ТА ЖЕ запись, доехала дважды' : 'ДРУГАЯ запись, сказано заново';
  return `[транскрипт] дословный повтор (${r.role}): запись ${r.id} повторяет ${r.earlierId} ` +
    `через ${Math.round(r.sinceMs / 1000)}с, ${r.chars} знаков — ${what}`;
}
