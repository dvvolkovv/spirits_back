/**
 * Файлы первичного каркаса продукта: имя файла → содержимое.
 *
 * Возвращённое отсюда провижининг пишет в чекаут и сразу коммитит, так что
 * набор файлов — это первый коммит продукта.
 *
 * `slug` обязателен: `claimJob` отдаёт его в задании рядом с именем
 * (`RETURNING id, slug, name, kind, …`). Он идёт и в `package.json`, и в
 * заголовок `CLAUDE.md` — везде, где нужно имя, которым не управляет клиент.
 */
export function skeletonFor(
  kind: ProductKind,
  name: string,
  slug: string,
): Record<string, string> {
  return {
    'package.json': packageJson(name, slug),
    'server.js': kind === 'bot' ? botServerJs(name) : siteServerJs(name),
    'CLAUDE.md': kind === 'bot' ? botClaudeMd(name, slug) : siteClaudeMd(name, slug),
  };
}
