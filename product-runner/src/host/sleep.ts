/**
 * ХОСТОВЫЕ ШАГИ СНА И ПРОБУЖДЕНИЯ.
 *
 * Продукт уже заведён: каталог, чекаут, образ и контейнер на месте. Сон гасит
 * контейнер и переводит домен на заглушку; пробуждение поднимает контейнер,
 * ДОЖИДАЕТСЯ ответа и только потом возвращает домен. Устройство контейнера и
 * `PRODUCT_START_SCRIPT` здесь не трогаются вовсе.
 *
 * ## Почему `docker stop`, а не `docker rm -f`
 *
 * Удалённый контейнер теряет всё, что делает пробуждение дешёвым: имя,
 * монтирование каталога и отображение портов. Поднять его заново — это снова
 * `docker run` со всем набором переменных окружения, включая RUNNER_TOKEN,
 * которого у сна НЕТ и взять неоткуда: сервер хранит только sha256, а
 * поворачивать токен на пробуждении нельзя (раннер живёт внутри контейнера и
 * обязан продолжить работать со старым). То есть `rm -f` превращает сон в
 * невозвратную операцию, и увидеть это можно было бы только при первом
 * пополнении баланса.
 *
 * Каталог и git-история целы в обоих случаях — разница видна только по
 * состоянию хоста, поэтому её и сторожит симулятор.
 *
 * ## Почему заглушка, а не 502
 *
 * Между погашенным контейнером и живым vhost домен отдаёт 502. Посетитель
 * читает 502 как НАШУ поломку, а это штатное состояние неоплаченного
 * продукта. Заглушка отвечает 503 («сервис временно недоступен») своей
 * страницей — см. scripts/product-vhost.
 *
 * ## Порядок шагов
 *
 * Сон: сначала заглушка, потом гашение. Наоборот между двумя командами
 * открывается окно, в котором домен смотрит на мёртвый порт, — то есть тот
 * самый 502, ради ухода от которого заглушка и заведена. Окно короткое, но
 * оно приходится ровно на момент, когда владелец смотрит на продукт.
 *
 * Пробуждение: поднять, ДОЖДАТЬСЯ, вернуть домен. Проверка здоровья
 * обязательна и стоит ДО возврата: контейнер мог не подняться (образ
 * обновился, порт достался соседу, диск кончился), и «разбудили» без проверки
 * — то же враньё, что «завели» без проверки. Вернув домен раньше, мы меняем
 * честную заглушку на 502.
 *
 * ## Чего эти шаги НЕ закрывают
 *
 * `hostDeps.freePort` считает свободным порт, которого нет в `docker ps` БЕЗ
 * `-a`, а у спящего продукта контейнер остановлен — то есть его порт может
 * достаться новому продукту. Тогда `docker start` при пробуждении упрётся в
 * «port is already allocated». Отказ при этом ЧЕСТНЫЙ и доезжает до карточки
 * (см. сценарий в sleep.spec.ts), но продукт останется спящим до разбора
 * руками. Чинится это в `freePort` — спрашивать надо `HostConfig.PortBindings`
 * у всех контейнеров, включая остановленные, — и сюда не относится.
 */
import { DEFAULTS, ProvisionDeps, SLUG_RE } from './provision';
import { ProductKind } from './skeleton';

/**
 * Задание сна или пробуждения в том виде, в каком оно приезжает с сервера.
 *
 * `runnerToken` и `secrets` здесь НЕТ, и это не забывчивость: сервер их не
 * присылает (см. claimJob), потому что контейнер уже собран и переменные
 * окружения в нём. Отдельный тип вместо ProvisionJob ровно поэтому — общий
 * заставил бы выдумывать значения для полей, которых в задании не бывает.
 */
export interface SleepJob {
  slug: string;
  kind: ProductKind;
  /** Порт сайта. У бота его нет, у сайта обязан быть при пробуждении. */
  port?: number | null;
}

/** Проверка слага — своя, хотя он и проверен на сервере. См. шапку provision.ts. */
function assertSlug(slug: string): void {
  if (!SLUG_RE.test(slug)) throw new Error(`слаг не годится: ${JSON.stringify(slug)}`);
}

function assertKind(kind: unknown): asserts kind is ProductKind {
  if (kind !== 'site' && kind !== 'bot') {
    throw new Error(`неизвестная форма продукта: ${JSON.stringify(kind)}`);
  }
}

/**
 * Усыпить продукт: перевести домен на заглушку, погасить контейнер.
 *
 * У бота домена нет вовсе — он сам ходит в Telegram, — поэтому заглушка ему не
 * ставится. Поставленная, она завела бы в nginx конфиг на имя, которого
 * никогда не существовало: файл на диске, строка в `nginx -t` и домен,
 * отдающий 503 неизвестно кому.
 */
export async function sleepProduct(job: SleepJob, deps: ProvisionDeps): Promise<void> {
  assertSlug(job.slug);
  assertKind(job.kind);

  if (job.kind === 'site') {
    // ДО гашения: см. «Порядок шагов» в шапке.
    await deps.run([deps.vhostBin ?? DEFAULTS.vhostBin, job.slug, '--asleep']);
  }
  // Именно stop: контейнер обязан остаться. См. шапку.
  await deps.run(['docker', 'stop', job.slug]);
}

/**
 * Разбудить: поднять контейнер, дождаться ответа, вернуть домен.
 *
 * Отказ на любом шаге — исключение, а не тихий успех. Сервер на нём оставит
 * продукт спящим и напишет причину в карточку (completeJob разбирает вид
 * задания), а домен останется на честной заглушке.
 */
export async function wakeProduct(job: SleepJob, deps: ProvisionDeps): Promise<void> {
  assertSlug(job.slug);
  assertKind(job.kind);

  // Порт проверяется ДО `docker start`: поднимать контейнер, зная, что
  // дождаться его будет нечем, — значит оставить хост в состоянии «работает,
  // но домен на заглушке», и отчитаться об отказе. Хуже, чем не начинать.
  if (job.kind === 'site' && !job.port) {
    throw new Error(`у сайта ${job.slug} нет порта — возвращать домен некуда`);
  }

  await deps.run(['docker', 'start', job.slug]);

  if (job.kind !== 'site') return;

  // Опрос ПО ФАКТУ, тот же, что при заведении. Голый TCP-connect здесь
  // бесполезен: порт хоста занимает docker-proxy с момента старта контейнера,
  // и проверка проходила бы, пока внутри не поднялось ничего (замерено в
  // provision.ts). deps.waitPort спрашивает /health и требует 200.
  const timeoutMs = deps.waitPortTimeoutMs ?? DEFAULTS.waitPortTimeoutMs;
  if (!(await deps.waitPort(job.port as number, timeoutMs))) {
    throw new Error(
      `${job.slug} не ответил на порту ${job.port} за ${Math.round(timeoutMs / 1000)} с `
        + 'после пробуждения — домен оставлен на заглушке',
    );
  }

  await deps.run([deps.vhostBin ?? DEFAULTS.vhostBin, job.slug, String(job.port)]);
}
