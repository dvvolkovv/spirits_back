#!/bin/sh
# Поднимает продукт, потом отдаёт управление раннеру.
#
# Порядок важен: раннер должен стать основным процессом контейнера, чтобы его
# падение роняло контейнер и Docker его перезапускал. Если бы основным был
# продукт, мёртвый раннер выглядел бы как живой контейнер — продукт молча
# перестал бы принимать правки.
set -eu

: "${LINKEON_URL:?LINKEON_URL не задан}"
: "${RUNNER_TOKEN:?RUNNER_TOKEN не задан}"
: "${CHECKOUT_PATH:=/product}"

if [ ! -d "$CHECKOUT_PATH/.git" ]; then
  echo "entrypoint: в $CHECKOUT_PATH нет git-репозитория — откат работать не будет" >&2
  exit 1
fi

# PRODUCT_START_SCRIPT — путь к точке входа, а НЕ команда вроде «npm start».
#
# Это принципиально. С командой pm2 запускает bash → npm → node и владеет только
# bash: при перезапуске настоящий node выживает сиротой и продолжает держать
# порт. Новая копия падает, старая отвечает — health-check видит зелёное и
# выкат считается удачным, хотя в HEAD лежит неработающий код.
#
# Поймано живьём: ход с заведомо падающим require закрылся как «Готово», pm2
# показывал errored и 93 перезапуска, а сайт отдавал 200 со старого процесса.
# Автооткат при такой раскладке не срабатывает никогда.
if [ -n "${PRODUCT_START_SCRIPT:-}" ]; then
  cd "$CHECKOUT_PATH"
  pm2 start "$PRODUCT_START_SCRIPT" --name product --time || {
    echo "entrypoint: продукт не стартовал — раннер всё равно поднимется, чтобы можно было прислать правку" >&2
  }
fi

cd /opt/runner
exec node dist/index.js
